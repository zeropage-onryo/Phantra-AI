"""
Phantra Creators (2026-11-03): the small, by-application program beside the
open affiliate link. Mike reads each application and picks who gets in.

This module is the applications and nothing else. What an accepted creator
gets (credits, early access, a place in the community) is handed over by
hand for now, the same way affiliate payouts are; the open link and its
commissions stay in src/affiliates.py and are untouched.

One application per account. Applying again returns the existing row, so a
second click never makes a duplicate and a rejected application is final
until Mike reopens it by hand.

CLI (the review is Mike's, like the affiliate one):
    python -m src.creators list [pending|approved|rejected]
    python -m src.creators approve <account slug | id> [--note ...]
    python -m src.creators reject  <account slug | id> [--note ...]
"""
from __future__ import annotations

import argparse
import re
import sys
import threading
from typing import Any, Optional

from . import db

TERMS_VERSION = "2026-11-03"
MAX_URL = 300
MAX_TEXT = 1200
STATUSES = ("pending", "approved", "rejected")

SCHEMA = """
CREATE TABLE IF NOT EXISTS creator_applications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'pending',
    full_name     TEXT NOT NULL DEFAULT '',
    country       TEXT NOT NULL DEFAULT '',
    channel_url   TEXT NOT NULL DEFAULT '',
    more_links    TEXT NOT NULL DEFAULT '',
    what_you_make TEXT NOT NULL DEFAULT '',
    contribute    TEXT NOT NULL DEFAULT '',
    terms_version TEXT NOT NULL DEFAULT '',
    note          TEXT NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at   TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS creator_applications_account_idx
    ON creator_applications (account_id);
"""

_ready: set = set()
_ready_lock = threading.Lock()


class CreatorError(ValueError):
    """A refusal with a machine-readable `code`, for the route to answer."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


def init(dsn: Optional[str] = None) -> None:
    """Create the table and own it. Idempotent; the app lifespan and
    tests/test_tenancy.py::_init_everything both run it."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "creator_applications")


def ensure(dsn: Optional[str] = None) -> None:
    """init() once per process and database, for a process whose start did
    not run it (a test's fresh schema, the CLI)."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)
            _ready.add(key)


def _iso(value: Any) -> Optional[str]:
    if value is None:
        return None
    return value.isoformat(timespec="seconds") if hasattr(value, "isoformat") else str(value)


def _text(value: Optional[str], *, limit: int = MAX_TEXT) -> str:
    return " ".join((value or "").split())[:limit]


def _url(value: str) -> str:
    value = (value or "").strip()
    if not value:
        raise CreatorError("channel_required", "add a link to where you share your work")
    if not re.match(r"^https?://[^\s/]+\.[^\s/]+", value, re.I) or len(value) > MAX_URL:
        raise CreatorError("bad_channel", "the link must be a full link starting with https://")
    return value


def _public(row: Optional[dict]) -> dict:
    """What the page gets back: where the application stands, never the
    review note."""
    if not row:
        return {"status": None}
    return {"status": row["status"], "applied_at": _iso(row.get("created_at"))}


def get(account_id: int, *, dsn: Optional[str] = None) -> dict:
    ensure(dsn)
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT * FROM creator_applications WHERE account_id = %s", (account_id,)).fetchone()
    return _public(dict(row) if row else None)


def apply(account_id: int, *, channel_url: str, what_you_make: str, accept_terms: bool,
          full_name: str = "", country: str = "", more_links: str = "", contribute: str = "",
          dsn: Optional[str] = None) -> dict:
    """Record an application. The form is a link, a line about the work and
    the terms box; a name and country are asked for but not required. One per
    account. Raises CreatorError on a bad form."""
    if not accept_terms:
        raise CreatorError("terms_required", "agree to the creator terms to apply")
    url = _url(channel_url)
    work = _text(what_you_make)
    if len(work) < 20:
        raise CreatorError("work_required", "tell us a little about what you make (a sentence or two)")
    ensure(dsn)
    with db.connect(dsn) as conn:
        conn.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (f"creator-apply:{account_id}",))
        row = conn.execute(
            "SELECT * FROM creator_applications WHERE account_id = %s", (account_id,)).fetchone()
        if row:
            return _public(dict(row))
        row = conn.execute(
            "INSERT INTO creator_applications (account_id, full_name, country, channel_url, "
            "more_links, what_you_make, contribute, terms_version) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s) RETURNING *",
            (account_id, _text(full_name, limit=120), _text(country, limit=80), url,
             _text(more_links), work, _text(contribute), TERMS_VERSION)).fetchone()
        return _public(dict(row))


# --------------------------------------------------------------------------
# review (Mike's CLI)
# --------------------------------------------------------------------------

def _resolve(conn, who: str) -> dict:
    who = (who or "").strip()
    row = None
    if who.isdigit():
        row = conn.execute("SELECT * FROM creator_applications WHERE id = %s", (int(who),)).fetchone()
    if row is None:
        row = conn.execute(
            "SELECT c.* FROM creator_applications c JOIN accounts a ON a.id = c.account_id "
            "WHERE a.slug = %s", (who,)).fetchone()
    if row is None:
        raise CreatorError("no_such_application", f"no creator application matches {who!r}")
    return dict(row)


def decide(who: str, status: str, *, note: str = "", dsn: Optional[str] = None) -> dict:
    if status not in ("approved", "rejected"):
        raise CreatorError("bad_status", "a decision is approved or rejected")
    ensure(dsn)
    with db.connect(dsn) as conn:
        row = _resolve(conn, who)
        row = conn.execute(
            "UPDATE creator_applications SET status = %s, note = %s, reviewed_at = now() "
            "WHERE id = %s RETURNING *", (status, _text(note, limit=400), row["id"])).fetchone()
        return dict(row)


def listing(status: Optional[str] = None, *, dsn: Optional[str] = None) -> list[dict]:
    ensure(dsn)
    with db.connect(dsn) as conn:
        if status:
            rows = conn.execute(
                "SELECT c.*, a.slug FROM creator_applications c LEFT JOIN accounts a ON a.id = c.account_id "
                "WHERE c.status = %s ORDER BY c.created_at", (status,)).fetchall()
        else:
            rows = conn.execute(
                "SELECT c.*, a.slug FROM creator_applications c LEFT JOIN accounts a ON a.id = c.account_id "
                "ORDER BY c.created_at").fetchall()
    return [dict(r) for r in rows]


def main(argv: Optional[list[str]] = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m src.creators", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    ls = sub.add_parser("list", help="applications, oldest first (optionally one status)")
    ls.add_argument("status", nargs="?", choices=STATUSES)
    for name in ("approve", "reject"):
        p = sub.add_parser(name)
        p.add_argument("who")
        p.add_argument("--note", default="")
    args = parser.parse_args(argv)
    try:
        if args.cmd == "list":
            for r in listing(args.status):
                print(f"#{r['id']} {r['status']:8} {r.get('slug') or r['account_id']}  "
                      f"{r['full_name'] or '-'}  {r['channel_url']}\n    {r['what_you_make']}")
        else:
            status = "approved" if args.cmd == "approve" else "rejected"
            r = decide(args.who, status, note=args.note)
            print(f"#{r['id']} is now {r['status']}")
    except CreatorError as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":  # pragma: no cover
    main()
