"""
What a person told the connector (2026-10-11,
docs/tasks/task-connector-overnight.md PR 4): the `feedback` tool's rows.

A sentence or two about a tool, a render or a scene, kept with who said it
and when. Nothing reads it back into a prompt or a shelf: it is a note to
the studio's operator, read by hand. Insert-only -- a later note is a new
row, never an edit of an earlier one. OWNED (db.OWNED_TABLES): one
account's words.
"""
from __future__ import annotations

from typing import Any, Optional

from . import db

SCHEMA = """
CREATE TABLE IF NOT EXISTS mcp_feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT,
    user_id     TEXT NOT NULL DEFAULT '',
    tool        TEXT,
    ref         TEXT,
    text        TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""

MAX_TEXT = 2000
MAX_TOOL = 64
MAX_REF = 120

_ready: set[str] = set()


def init(dsn: Optional[str] = None) -> None:
    """Create and own the table. Idempotent."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "mcp_feedback")
    _ready.add(db.resolve_dsn(dsn))


def ensure(dsn: Optional[str] = None) -> None:
    """The table, made once per process per database (a request path must
    not run the schema init on every call). A failed init is not remembered."""
    if db.resolve_dsn(dsn) in _ready:
        return
    db.run_init(lambda: init(dsn), dsn)


def record(account_id: Optional[int], user_id: Optional[str], text: str, *,
           tool: Optional[str] = None, ref: Optional[str] = None,
           dsn: Optional[str] = None) -> dict[str, Any]:
    """One note. The caller has already checked the text; the bounds are
    enforced again here so a row never carries more than the tool says."""
    text = " ".join((text or "").split())[:MAX_TEXT]
    if not text:
        raise ValueError("feedback needs some words")
    tool = (" ".join((tool or "").split())[:MAX_TOOL] or None)
    ref = (" ".join((ref or "").split())[:MAX_REF] or None)
    with db.connect(dsn) as conn:
        row = conn.execute(
            "INSERT INTO mcp_feedback (account_id, user_id, tool, ref, text) "
            "VALUES (%s, %s, %s, %s, %s) RETURNING id, created_at",
            (account_id, str(user_id or ""), tool, ref, text)).fetchone()
    return {"id": int(row["id"]), "created_at": row["created_at"], "tool": tool, "ref": ref,
            "text": text}


def recent(account_id: Optional[int], limit: int = 20,
           dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """This account's notes, newest first -- for the operator's reading
    and for the tests; no tool lists them to a caller."""
    with db.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT id, user_id, tool, ref, text, created_at FROM mcp_feedback "
            "WHERE account_id IS NOT DISTINCT FROM %s ORDER BY id DESC LIMIT %s",
            (account_id, max(1, int(limit)))).fetchall()
    return [dict(r) for r in rows]


__all__ = ["MAX_TEXT", "MAX_TOOL", "MAX_REF", "init", "ensure", "record", "recent"]
