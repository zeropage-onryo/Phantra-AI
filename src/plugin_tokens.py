"""
Editing-app plugins signing in to a workspace (2026-10-22, Mike's call:
"lets start with premiere"; docs/tasks/task-premiere-plugin.md).

A Premiere Pro panel cannot hold the studio's cookie, so it signs in the
way a TV app does. The panel asks for a pairing (`start`) and gets two
things back: a short CODE the person reads (`KDPX-7QHR`) and a long
SECRET the panel keeps. The person opens phantra.ai/studio/link, signed in
as themselves, and approves the code (`approve`). From then on the panel
sends the secret as `Authorization: Bearer php_...` and it is a token
for that person's workspace (`resolve`).

THE SECRET IS THE TOKEN. Approving a code moves the secret's SHA-256
from the pairing onto a `plugin_tokens` row, so nothing secret is minted
twice, sent twice, or stored at all: the database holds hashes only, and
a copy of it is not a key to anybody's workspace. A code alone is
worthless -- it signs in only the panel that holds its secret.

TWO TABLES.

- `plugin_pairings` (SHARED: a code waiting for a person has no account
  yet; the approval writes the owned row). Ten minutes, then dead.
- `plugin_tokens` (OWNED): one connected copy of a panel -- whose, which
  app ("Premiere Pro"), the token's hash, when it was made, last used,
  and revoked. A revoked token is simply not found.

Nothing here spends or reads anyone's media.
"""
from __future__ import annotations

import hashlib
import secrets
import threading
from typing import Any, Optional

from . import db

TOKEN_PREFIX = "php_"
CODE_ALPHABET = "BCDFGHJKLMNPQRSTVWXZ23456789"   # no 0/O, 1/I/L, vowels (no words)
CODE_LENGTH = 8
PAIRING_SECONDS = 600
POLL_SECONDS = 5
IDLE_DAYS = 90             # a panel unused this long signs in again
SWEEP_AFTER = "1 day"      # dead pairings are deleted this long after they expire
MAX_CLIENT = 80
CLIENTS = {"premiere": "Premiere Pro", "resolve": "DaVinci Resolve"}

SCHEMA = """
CREATE TABLE IF NOT EXISTS plugin_pairings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    secret_hash  TEXT NOT NULL UNIQUE,
    code         TEXT NOT NULL UNIQUE,
    client       TEXT NOT NULL,
    device       TEXT NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    approved_at  TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS plugin_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT NOT NULL,
    user_id      TEXT NOT NULL,
    client       TEXT NOT NULL,
    device       TEXT NOT NULL DEFAULT '',
    token_hash   TEXT NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ
);
"""

INDEXES = """
CREATE INDEX IF NOT EXISTS idx_plugin_tokens_account
    ON plugin_tokens (account_id, user_id);
"""

_ready: set = set()
_ready_lock = threading.Lock()


class PairingRefused(ValueError):
    """A code that cannot be approved, with a machine-readable `code`:
    bad_code, expired, already_used."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


def init(dsn: Optional[str] = None) -> None:
    """Create both tables. Idempotent; the app lifespan runs it."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "plugin_tokens")
        conn.execute(INDEXES)


def ensure(dsn: Optional[str] = None) -> None:
    """init() once per process and database, for a process whose start did
    not run it (a test's fresh schema, a CLI) -- the fal_requests shape."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)
            _ready.add(key)


def _hash(secret: str) -> str:
    return hashlib.sha256(secret.encode("utf-8")).hexdigest()


def normalize_code(raw: str) -> str:
    """What a person typed, as stored: upper case, with the dash and any
    spaces forgiven ("kdpx 7qhr" -> "KDPX7QHR"). The alphabet has no
    look-alikes, so there is nothing to translate."""
    return "".join(ch for ch in (raw or "").upper() if ch.isalnum())[:CODE_LENGTH * 2]


def display_code(code: str) -> str:
    return f"{code[:4]}-{code[4:]}" if len(code) == CODE_LENGTH else code


def client_label(client: str) -> str:
    return CLIENTS.get((client or "").strip().lower(), "")


def start(client: str, device: str = "", dsn: Optional[str] = None) -> dict[str, Any]:
    """A new pairing for `client` (one of CLIENTS). Returns the secret ONCE
    -- the caller hands it to the panel and keeps nothing -- and the code
    to show the person."""
    label = client_label(client)
    if not label:
        raise ValueError(f"unknown client {client!r}; one of {sorted(CLIENTS)}")
    ensure(dsn)
    # what the panel says about itself: shown to the person as the panel's own
    # claim, so it is kept to plain letters, digits and light punctuation
    device = "".join(ch for ch in (device or "") if ch.isalnum() or ch in " .,-()")
    device = " ".join(device.split())[:MAX_CLIENT]
    secret = TOKEN_PREFIX + secrets.token_urlsafe(32)
    with db.connect(dsn) as conn:
        conn.execute("DELETE FROM plugin_pairings WHERE expires_at < now() - %s::interval",
                     (SWEEP_AFTER,))
        for _ in range(5):
            code = "".join(secrets.choice(CODE_ALPHABET) for _ in range(CODE_LENGTH))
            cur = conn.execute(
                "INSERT INTO plugin_pairings (secret_hash, code, client, device, expires_at) "
                "VALUES (%s, %s, %s, %s, now() + make_interval(secs => %s)) "
                "ON CONFLICT (code) DO NOTHING",
                (_hash(secret), code, label, device, PAIRING_SECONDS))
            if cur.rowcount:
                break
        else:                                           # 28^8 codes: never in practice
            raise RuntimeError("could not pick an unused code")
    return {"secret": secret, "code": display_code(code), "client": label,
            "expires_in": PAIRING_SECONDS, "interval": POLL_SECONDS}


def pending(code: str, dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    """What the link page shows before the click: the app and device a code
    belongs to, if it is still waiting. None for anything else."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT client, device, expires_at FROM plugin_pairings "
            "WHERE code = %s AND approved_at IS NULL AND expires_at > now()",
            (normalize_code(code),)).fetchone()
    if not row:
        return None
    return {"code": display_code(normalize_code(code)), "client": row["client"],
            "device": row["device"], "expires_at": row["expires_at"]}


def approve(code: str, account_id: int, user_id: str,
            dsn: Optional[str] = None) -> dict[str, Any]:
    """The signed-in person approved `code` for their workspace. The
    pairing's secret hash becomes a token for (account, person); the
    pairing is spent in the same transaction, so a code approves once."""
    ensure(dsn)
    normalized = normalize_code(code)
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT id, secret_hash, client, device, expires_at, approved_at, "
            "expires_at > now() AS live FROM plugin_pairings WHERE code = %s FOR UPDATE",
            (normalized,)).fetchone()
        if not row:
            raise PairingRefused("bad_code", "That code isn't one we issued. Check it against "
                                             "the code in your panel.")
        if row["approved_at"] is not None:
            raise PairingRefused("already_used", "That code has already been used. Ask the "
                                                 "panel for a new one.")
        if not row["live"]:
            raise PairingRefused("expired", "That code has expired. Ask the panel for a "
                                            "new one.")
        conn.execute("UPDATE plugin_pairings SET approved_at = now() WHERE id = %s",
                     (row["id"],))
        made = conn.execute(
            "INSERT INTO plugin_tokens (account_id, user_id, client, device, token_hash) "
            "VALUES (%s, %s, %s, %s, %s) RETURNING id, created_at",
            (int(account_id), str(user_id), row["client"], row["device"],
             row["secret_hash"])).fetchone()
    return {"id": int(made["id"]), "client": row["client"], "device": row["device"],
            "created_at": made["created_at"]}


def poll(secret: str, dsn: Optional[str] = None) -> str:
    """Where a pairing stands, for the panel holding its secret:
    "approved", "pending", "expired" or "unknown"."""
    if not (secret or "").startswith(TOKEN_PREFIX):
        return "unknown"
    ensure(dsn)
    h = _hash(secret)
    with db.connect(dsn) as conn:
        if conn.execute("SELECT 1 FROM plugin_tokens WHERE token_hash = %s "
                        "AND revoked_at IS NULL", (h,)).fetchone():
            return "approved"
        row = conn.execute("SELECT approved_at, expires_at > now() AS live "
                           "FROM plugin_pairings WHERE secret_hash = %s", (h,)).fetchone()
    if not row:
        return "unknown"
    if row["approved_at"] is not None:
        return "unknown"            # approved and since revoked
    return "pending" if row["live"] else "expired"


def resolve(secret: str, dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    """The live token row for a bearer secret -- `id`, `account_id`,
    `user_id`, `client` -- or None. Live means: not revoked, used (or made)
    within IDLE_DAYS, and the person is STILL a member of that account --
    a token is never more than the membership it was approved under.
    Stamps last use, at most once a minute."""
    if not (secret or "").startswith(TOKEN_PREFIX) or len(secret) > 200:
        return None
    ensure(dsn)
    live = ("t.token_hash = %s AND t.revoked_at IS NULL "
            "AND COALESCE(t.last_used_at, t.created_at) > now() - make_interval(days => %s) "
            "AND EXISTS (SELECT 1 FROM account_members m "
            "WHERE m.account_id = t.account_id AND m.user_id = t.user_id)")
    args = (_hash(secret), IDLE_DAYS)
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT t.id, t.account_id, t.user_id, t.client, "
            "(t.last_used_at IS NULL OR t.last_used_at < now() - interval '1 minute') AS stale "
            f"FROM plugin_tokens t WHERE {live}", args).fetchone()
        if row and row["stale"]:
            conn.execute("UPDATE plugin_tokens SET last_used_at = now() "
                         "WHERE id = %s AND account_id = %s", (row["id"], row["account_id"]))
    if not row:
        return None
    return {k: row[k] for k in ("id", "account_id", "user_id", "client")}


def connections(account_id: int, user_id: str, dsn: Optional[str] = None) -> list[dict]:
    """This person's live panels on this account, newest use first."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT id, client, device, created_at, last_used_at FROM plugin_tokens "
            "WHERE account_id = %s AND user_id = %s AND revoked_at IS NULL "
            "ORDER BY COALESCE(last_used_at, created_at) DESC, id DESC",
            (int(account_id), str(user_id))).fetchall()
    return [dict(r) for r in rows]


def revoke(token_id: int, account_id: int, user_id: str,
           dsn: Optional[str] = None) -> bool:
    """Disconnect one panel. Only the person's own, on this account;
    anybody else's id is as missing as one that never existed."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        cur = conn.execute(
            "UPDATE plugin_tokens SET revoked_at = now() WHERE id = %s AND account_id = %s "
            "AND user_id = %s AND revoked_at IS NULL",
            (int(token_id), int(account_id), str(user_id)))
    return bool(cur.rowcount)


def revoke_secret(secret: str, dsn: Optional[str] = None) -> bool:
    """The panel signing itself out."""
    if not (secret or "").startswith(TOKEN_PREFIX):
        return False
    ensure(dsn)
    with db.connect(dsn) as conn:
        cur = conn.execute("UPDATE plugin_tokens SET revoked_at = now() "
                           "WHERE token_hash = %s AND revoked_at IS NULL", (_hash(secret),))
    return bool(cur.rowcount)
