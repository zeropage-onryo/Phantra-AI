"""
The free looks' assets, GENERATED here and nowhere else (2026-10-22,
docs/tasks/task-free-looks.md).

Nothing under data/looks/ is downloaded and nothing is committed: the two
LUTs are written from formulas, the whoosh is synthesised, the flash frame
is drawn. `data/` is not tracked, so `looks.ensure_assets()` calls
`write_all` on first use and every file below is rebuilt from this module
when it is missing; `python -m src.looks_assets` writes them by hand.
License-clean by construction: there is no third-party file to license.

- film_grade.cube  a 33^3 teal-and-orange film grade: an S-curve for
                   contrast, teal pushed into the shadows, orange into the
                   highlights, midtone saturation eased a little
- noir.cube        a 33^3 black-and-white curve: Rec.709 luminance, a
                   steeper S-curve with the blacks lifted a touch, the
                   same value on all three channels
- whoosh.wav       0.7s, 48 kHz mono: shaped noise swept through a
                   one-pole low-pass, a fast attack and a long tail
- flash.png        a 640x360 RGBA frame: a warm white radial bloom that
                   fades towards the corners
- README.md        says the above, so a folder listing explains itself
"""
from __future__ import annotations

import math
import random
import struct
import sys
import wave
from pathlib import Path

LUT_SIZE = 33
WHOOSH_SECONDS = 0.7
WHOOSH_RATE = 48000
FLASH_SIZE = (640, 360)
FILES = ("film_grade.cube", "noir.cube", "whoosh.wav", "flash.png", "README.md")

README = """# data/looks -- generated assets for the free looks

Every file here is GENERATED by `src/looks_assets.py` (`python -m src.looks_assets`
rewrites them; `src/free_looks.py` rebuilds any that is missing on first use). Nothing was
downloaded and nothing here carries a third-party license:

- `film_grade.cube`: a teal-and-orange film grade LUT written from a formula.
- `noir.cube`: a black-and-white curve LUT written from a formula.
- `whoosh.wav`: a synthesised whoosh (shaped noise through a swept low-pass).
- `flash.png`: a drawn radial bloom used for the 2000s Flash pops.

Delete the folder and it comes back identical: the generator is seeded.
"""


# --------------------------------------------------------------------------
# LUTs
# --------------------------------------------------------------------------

def _clamp(x: float) -> float:
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x


def _s_curve(x: float, strength: float) -> float:
    """A smooth contrast curve through (0,0), (0.5,0.5) and (1,1): the
    shadows pushed down and the highlights up by `strength`."""
    return _clamp(x - strength * math.sin(2 * math.pi * x) / (2 * math.pi))


def _luma(r: float, g: float, b: float) -> float:
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def film_grade_rgb(r: float, g: float, b: float) -> tuple[float, float, float]:
    """One entry of the teal-orange grade."""
    lum = _luma(r, g, b)
    # contrast first, gently
    r, g, b = (_s_curve(c, 0.55) for c in (r, g, b))
    # ease the midtone saturation a little, so the tint reads as a grade
    # and not as a colour cast on the skin
    mid = 1.0 - abs(lum - 0.5) * 2.0          # 1 at the midtones, 0 at the ends
    desat = 0.10 * mid
    lum2 = _luma(r, g, b)
    r, g, b = (c + (lum2 - c) * desat for c in (r, g, b))
    # teal into the shadows, orange into the highlights
    shadow = (1.0 - lum) ** 2
    high = lum ** 2
    r += -0.040 * shadow + 0.055 * high
    g += 0.018 * shadow + 0.020 * high
    b += 0.060 * shadow - 0.050 * high
    return _clamp(r), _clamp(g), _clamp(b)


def noir_rgb(r: float, g: float, b: float) -> tuple[float, float, float]:
    """One entry of the black-and-white curve: luminance, a steeper curve,
    the blacks lifted a touch, as one value on every channel."""
    y = _luma(r, g, b)
    y = _s_curve(y, 0.9)
    y = _clamp(0.03 + y * 0.97)
    return y, y, y


def write_cube(path: Path, title: str, fn, size: int = LUT_SIZE) -> Path:
    """A .cube file (the Adobe/Resolve LUT format): LUT_3D_SIZE then
    size^3 lines, red fastest, as every reader expects."""
    lines = [f"TITLE \"{title}\"", f"LUT_3D_SIZE {size}",
             "DOMAIN_MIN 0.0 0.0 0.0", "DOMAIN_MAX 1.0 1.0 1.0"]
    step = 1.0 / (size - 1)
    for bi in range(size):
        for gi in range(size):
            for ri in range(size):
                r, g, b = fn(ri * step, gi * step, bi * step)
                lines.append(f"{r:.6f} {g:.6f} {b:.6f}")
    path.write_text("\n".join(lines) + "\n")
    return path


# --------------------------------------------------------------------------
# the whoosh
# --------------------------------------------------------------------------

def whoosh_samples(seconds: float = WHOOSH_SECONDS, rate: int = WHOOSH_RATE,
                   seed: int = 2026) -> list[int]:
    """16-bit samples of a whoosh: white noise through a one-pole low-pass
    whose cutoff sweeps up then down, under a fast-attack long-tail
    envelope. Deterministic for a seed."""
    rng = random.Random(seed)
    n = int(seconds * rate)
    y = 0.0
    peak = 0.0
    raw = []
    for i in range(n):
        t = i / n
        # cutoff sweeps 300 Hz -> 4 kHz -> 300 Hz across the whoosh
        sweep = math.sin(math.pi * t) ** 0.7
        cutoff = 300.0 + 3700.0 * sweep
        alpha = 1.0 - math.exp(-2.0 * math.pi * cutoff / rate)
        y += alpha * (rng.uniform(-1.0, 1.0) - y)
        # envelope: a 60 ms attack, then an exponential tail
        attack = min(1.0, (i / rate) / 0.06)
        tail = math.exp(-3.2 * max(0.0, t - 0.12))
        v = y * attack * tail
        raw.append(v)
        peak = max(peak, abs(v))
    gain = 0.85 / peak if peak else 1.0
    return [int(max(-32767, min(32767, round(v * gain * 32767)))) for v in raw]


def write_whoosh(path: Path) -> Path:
    samples = whoosh_samples()
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(WHOOSH_RATE)
        w.writeframes(struct.pack(f"<{len(samples)}h", *samples))
    return path


# --------------------------------------------------------------------------
# the flash frame
# --------------------------------------------------------------------------

def write_flash(path: Path, size: tuple[int, int] = FLASH_SIZE) -> Path:
    """A warm white bloom, opaque at the centre and thinning towards the
    corners: overlaid for a tenth of a second it reads as a flash."""
    from PIL import Image

    w, h = size
    cx, cy = (w - 1) / 2.0, (h - 1) / 2.0
    dmax = math.hypot(cx, cy)
    im = Image.new("RGBA", (w, h))
    px = im.load()
    for yy in range(h):
        for xx in range(w):
            d = math.hypot(xx - cx, yy - cy) / dmax
            a = max(0.0, 1.0 - d) ** 1.4
            px[xx, yy] = (255, 250, 236, int(round(255 * min(1.0, 0.25 + 0.75 * a))))
    im.save(path)
    return path


# --------------------------------------------------------------------------
# all of it
# --------------------------------------------------------------------------

def write_all(directory: Path, *, only_missing: bool = False) -> dict[str, Path]:
    """Write every asset into `directory` (made if needed). Returns the
    paths by file name."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    paths = {name: directory / name for name in FILES}

    def need(name: str) -> bool:
        return not (only_missing and paths[name].is_file() and paths[name].stat().st_size > 0)

    if need("film_grade.cube"):
        write_cube(paths["film_grade.cube"], "Phantra Film Grade (teal/orange)", film_grade_rgb)
    if need("noir.cube"):
        write_cube(paths["noir.cube"], "Phantra Noir (B&W curve)", noir_rgb)
    if need("whoosh.wav"):
        write_whoosh(paths["whoosh.wav"])
    if need("flash.png"):
        write_flash(paths["flash.png"])
    if need("README.md"):
        paths["README.md"].write_text(README)
    return paths


def main(argv=None) -> int:
    from . import free_looks
    target = Path(argv[0]) if argv else free_looks.ASSETS_DIR
    for path in write_all(target).values():
        print(f"wrote {path} ({path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main(sys.argv[1:]))
