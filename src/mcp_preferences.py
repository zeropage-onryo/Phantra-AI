"""
A workspace's defaults for the connector (2026-10-11,
docs/tasks/task-connector-overnight.md PR 4): `preferences` and
`set_preferences`.

Five values a person sets once so a chat need not repeat them: the frame
(`aspect`) a still is drawn at, the length (`seconds`) a scene is written
to, the clip model (`video_model`) and the still model (`image_model`) a
quote or a draw defaults to, and whether a render should be offered as a
draft first (`draft_first`). Every value is checked against the live
catalogue BY THE CALLER before it reaches here (refused, never clamped);
this module only keeps rows.

INSERT-ONLY (the task's rule: every edit makes a new item, nothing is
overwritten or deleted): `set` writes a new row holding the previous values
merged with the ones given, and `get` reads the newest. The history is
free. A tool reads a preference only where the caller passed nothing.
OWNED (db.OWNED_TABLES): one workspace's defaults.
"""
from __future__ import annotations

from typing import Any, Optional

from . import db

SCHEMA = """
CREATE TABLE IF NOT EXISTS mcp_preferences (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT,
    user_id      TEXT NOT NULL DEFAULT '',
    aspect       TEXT,
    seconds      INTEGER,
    video_model  TEXT,
    image_model  TEXT,
    draft_first  BOOLEAN,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""

FIELDS = ("aspect", "seconds", "video_model", "image_model", "draft_first")

_ready: set[str] = set()


def init(dsn: Optional[str] = None) -> None:
    """Create and own the table. Idempotent."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "mcp_preferences")
    _ready.add(db.resolve_dsn(dsn))


def ensure(dsn: Optional[str] = None) -> None:
    if db.resolve_dsn(dsn) in _ready:
        return
    db.run_init(lambda: init(dsn), dsn)


def empty() -> dict[str, Any]:
    return {field: None for field in FIELDS}


def get(account_id: Optional[int], dsn: Optional[str] = None) -> dict[str, Any]:
    """The newest row's values, every field present (None when never set),
    plus `set_at` and `set_by`; the empty shape for a workspace with none."""
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "mcp_preferences"):
            return {**empty(), "set_at": None, "set_by": ""}
        row = conn.execute(
            "SELECT * FROM mcp_preferences WHERE account_id IS NOT DISTINCT FROM %s "
            "ORDER BY id DESC LIMIT 1", (account_id,)).fetchone()
    if row is None:
        return {**empty(), "set_at": None, "set_by": ""}
    return {**{field: row[field] for field in FIELDS},
            "set_at": row["created_at"], "set_by": row["user_id"] or ""}


def save(account_id: Optional[int], user_id: Optional[str], *,
         dsn: Optional[str] = None, **values: Any) -> dict[str, Any]:
    """A new row: the current values with `values` laid over them (a key
    given as None leaves that field as it was). Returns what `get` now
    answers. (Named `save`, not `set`: a module-level `set` shadows the
    builtin this body uses.)"""
    unknown = sorted(set(values) - set(FIELDS))
    if unknown:
        raise ValueError(f"no such preference: {unknown}")
    current = get(account_id, dsn)
    merged = {field: (values[field] if values.get(field) is not None else current[field])
              for field in FIELDS}
    with db.connect(dsn) as conn:
        conn.execute(
            "INSERT INTO mcp_preferences (account_id, user_id, aspect, seconds, video_model, "
            "image_model, draft_first) VALUES (%s, %s, %s, %s, %s, %s, %s)",
            (account_id, str(user_id or ""), merged["aspect"], merged["seconds"],
             merged["video_model"], merged["image_model"], merged["draft_first"]))
    return get(account_id, dsn)


def history(account_id: Optional[int], limit: int = 20,
            dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """Every row, newest first: what was set when and by whom."""
    with db.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT * FROM mcp_preferences WHERE account_id IS NOT DISTINCT FROM %s "
            "ORDER BY id DESC LIMIT %s", (account_id, max(1, int(limit)))).fetchall()
    return [dict(r) for r in rows]


__all__ = ["FIELDS", "init", "ensure", "empty", "get", "save", "history"]
