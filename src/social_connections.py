"""
A person's own social accounts, connected to their workspace (2026-10-22,
docs/tasks/task-social-connections.md). The Postiz `Integration` row, in
this repo's shape.

WHAT A ROW IS. One channel a post can go to: an Instagram account, a
Discord server + channel, later a TikTok account, a YouTube channel, a
Facebook Page, a LinkedIn member, a Reddit account. `provider` names the
module in src/social/ that made it, `external_id` is the platform's own
id for the channel (an IG user id, a Discord guild id), and the token
Meta or Discord issued is on the row, ENCRYPTED. `meta_json` holds what
the provider needs beyond the token (a Discord channel id). `pending`
names an in-between step still to do (Discord: pick the channel); a
pending row is listed but never posts.

THE VAULT. Tokens are Fernet-encrypted (the deleted BYOK envelope, back)
under SOCIAL_TOKEN_SECRET, else SESSION_SECRET -- an explicit one: a
generated ephemeral secret would make every token unreadable after the
next deploy, so with neither set a connect REFUSES rather than storing
something that will not open. Nothing here prints a token; errors are
redacted before they reach a row or a page (social.base.redact).

WHO POSTS. `token_for(account_id, provider)` is the one reader: the
newest live, finished row for that provider on that account, its token
renewed first when it is inside REFRESH_WINDOW of expiry and the
provider can renew (Instagram's long-lived token, Discord's user token).
A renewal that fails marks the row `refresh_needed` -- the card says
"Reconnect" -- and raises in plain words. publish_review.token_for asks
here first and keeps the operator's env token only as the fallback for
the platform it already posted with.

OWNED (db.OWNED_TABLES): a connection is one account's. Every statement
below carries account_id; a connection is never found by id alone.
Disconnect is SOFT (`deleted_at`): the row stays, the token is wiped,
so "connected on" history survives and a reconnect is a new row.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import threading
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

from cryptography.fernet import Fernet, InvalidToken

from . import db, social
from .social.base import Connected, ConnectRefused, Renewed

SCHEMA = """
CREATE TABLE IF NOT EXISTS social_connections (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT NOT NULL,
    provider       TEXT   NOT NULL,
    external_id    TEXT   NOT NULL,
    display_name   TEXT   NOT NULL DEFAULT '',
    handle         TEXT   NOT NULL DEFAULT '',
    avatar_url     TEXT   NOT NULL DEFAULT '',
    token_enc      TEXT   NOT NULL DEFAULT '',
    refresh_enc    TEXT   NOT NULL DEFAULT '',
    expires_at     TIMESTAMPTZ,
    scopes         TEXT   NOT NULL DEFAULT '',
    meta_json      TEXT   NOT NULL DEFAULT '{}',
    pending        TEXT,
    refresh_needed BOOLEAN NOT NULL DEFAULT FALSE,
    connected_by   TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ
);
"""

# one LIVE row per channel per account; a disconnected row stays as history
INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS idx_social_connections_channel
    ON social_connections (account_id, provider, external_id)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_social_connections_account
    ON social_connections (account_id, provider);
"""

SECRET_ENV = "SOCIAL_TOKEN_SECRET"
REFRESH_WINDOW = timedelta(days=7)
MAX_TEXT = 300

_ready: set[str] = set()
_ready_lock = threading.Lock()


# --------------------------------------------------------------------------
# schema
# --------------------------------------------------------------------------

def init(dsn: Optional[str] = None) -> None:
    """Create and own the table. Idempotent; the app lifespan runs it
    under db.run_init."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "social_connections")
        conn.execute(INDEXES)
    _ready.add(db.resolve_dsn(dsn))


def ensure(dsn: Optional[str] = None) -> None:
    """The table exists before a request names it (the ledger's shape):
    once per process and database, through db.run_init."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)


# --------------------------------------------------------------------------
# the vault
# --------------------------------------------------------------------------

class VaultError(Exception):
    """No secret to encrypt under, or a token that will not open."""


def _secret() -> str:
    for name in (SECRET_ENV, "SESSION_SECRET"):
        value = (os.environ.get(name) or "").strip()
        if value:
            return value
    return ""


def vault_ready() -> bool:
    return bool(_secret())


def _fernet() -> Fernet:
    secret = _secret()
    if not secret:
        raise VaultError(f"{SECRET_ENV} (or SESSION_SECRET) is unset, so a token cannot be "
                         "stored. Set it on the server and connect again.")
    key = base64.urlsafe_b64encode(hashlib.sha256(secret.encode("utf-8")).digest())
    return Fernet(key)


def seal(token: str) -> str:
    if not token:
        return ""
    return _fernet().encrypt(token.encode("utf-8")).decode("ascii")


def unseal(sealed: str) -> str:
    if not sealed:
        return ""
    try:
        return _fernet().decrypt(sealed.encode("ascii")).decode("utf-8")
    except InvalidToken:
        raise VaultError("The stored token does not open under this server's secret; "
                         "connect the account again.")


# --------------------------------------------------------------------------
# rows
# --------------------------------------------------------------------------

def _now() -> datetime:
    return datetime.now(timezone.utc)


def _expires(expires_in: Optional[int]) -> Optional[datetime]:
    if expires_in is None:
        return None
    return _now() + timedelta(seconds=int(expires_in))


def _clip(s: Any) -> str:
    return str(s or "")[:MAX_TEXT]


def save(account_id: int, provider: str, found: Connected, *,
         connected_by: Optional[str] = None, dsn: Optional[str] = None) -> dict[str, Any]:
    """Write a finished grant down. The same channel connected again
    (same account, provider, external_id, still live) is UPDATED in
    place: the new token replaces the old, the display refreshes, and a
    pending step already done is kept done."""
    ensure(dsn)
    if social.get(provider) is None:
        raise ConnectRefused(f"{provider!r} is not a platform this studio connects.")
    token_enc = seal(found.access_token)
    refresh_enc = seal(found.refresh_token or "")
    meta = dict(found.meta or {})
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT id, meta_json, pending FROM social_connections "
            "WHERE account_id = %s AND provider = %s AND external_id = %s AND deleted_at IS NULL",
            (account_id, provider, found.external_id)).fetchone()
        if row:
            old_meta = _meta(row)
            pending = found.pending if row["pending"] else None
            if row["pending"] is None:
                # an in-between step done earlier stays done: keep its keys
                merged = dict(old_meta)
                merged.update(meta)
                meta = merged
            conn.execute(
                "UPDATE social_connections SET display_name = %s, handle = %s, avatar_url = %s, "
                "token_enc = %s, refresh_enc = %s, expires_at = %s, scopes = %s, meta_json = %s, "
                "pending = %s, refresh_needed = FALSE, connected_by = COALESCE(%s, connected_by), "
                "updated_at = now() WHERE id = %s AND account_id = %s",
                (_clip(found.display_name), _clip(found.handle), _clip(found.avatar_url),
                 token_enc, refresh_enc, _expires(found.expires_in), ",".join(found.scopes),
                 json.dumps(meta), pending, connected_by, row["id"], account_id))
            cid = int(row["id"])
        else:
            cid = int(conn.execute(
                "INSERT INTO social_connections (account_id, provider, external_id, display_name, "
                "handle, avatar_url, token_enc, refresh_enc, expires_at, scopes, meta_json, "
                "pending, connected_by) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) "
                "RETURNING id",
                (account_id, provider, found.external_id, _clip(found.display_name),
                 _clip(found.handle), _clip(found.avatar_url), token_enc, refresh_enc,
                 _expires(found.expires_in), ",".join(found.scopes), json.dumps(meta),
                 found.pending, connected_by)).fetchone()["id"])
    got = get(account_id, cid, dsn=dsn)
    assert got is not None
    return got


def _meta(row: dict) -> dict[str, Any]:
    try:
        meta = json.loads(row.get("meta_json") or "{}")
    except (TypeError, ValueError):
        meta = {}
    return meta if isinstance(meta, dict) else {}


def _public(row: dict) -> dict[str, Any]:
    """What a page or a tool may see: never the token. `status` is the
    one word the card draws."""
    mod = social.get(row["provider"])
    meta = _meta(row)
    expires = row.get("expires_at")
    if row.get("pending"):
        status = "pending"
    elif row.get("refresh_needed"):
        status = "reconnect"
    elif expires is not None and expires <= _now():
        status = "expired"
    else:
        status = "connected"
    label = ""
    if mod is not None and hasattr(mod, "display_label"):
        label = mod.display_label(meta) or ""
    return {
        "id": int(row["id"]),
        "provider": row["provider"],
        "provider_name": mod.NAME if mod is not None else row["provider"],
        "external_id": row["external_id"],
        "display_name": row.get("display_name") or "",
        "handle": row.get("handle") or "",
        "avatar_url": row.get("avatar_url") or "",
        "label": label or row.get("display_name") or "",
        "status": status,
        "pending": row.get("pending"),
        "expires_at": expires.isoformat() if expires is not None else None,
        "scopes": [s for s in (row.get("scopes") or "").split(",") if s],
        "meta": {k: v for k, v in meta.items() if not k.endswith("_token")},
        "connected_by": row.get("connected_by"),
        "created_at": row["created_at"].isoformat() if row.get("created_at") else None,
        "updated_at": row["updated_at"].isoformat() if row.get("updated_at") else None,
    }


COLUMNS = ("id, account_id, provider, external_id, display_name, handle, avatar_url, "
           "token_enc, refresh_enc, expires_at, scopes, meta_json, pending, refresh_needed, "
           "connected_by, created_at, updated_at, deleted_at")


def _row(account_id: int, connection_id: int, dsn: Optional[str]) -> Optional[dict]:
    with db.connect(dsn) as conn:
        return conn.execute(
            f"SELECT {COLUMNS} FROM social_connections "
            "WHERE id = %s AND account_id = %s AND deleted_at IS NULL",
            (connection_id, account_id)).fetchone()


def get(account_id: int, connection_id: int, *, dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    row = _row(account_id, connection_id, dsn)
    return _public(row) if row else None


def list_for(account_id: int, *, dsn: Optional[str] = None) -> list[dict[str, Any]]:
    with db.connect(dsn) as conn:
        rows = conn.execute(
            f"SELECT {COLUMNS} FROM social_connections "
            "WHERE account_id = %s AND deleted_at IS NULL ORDER BY provider, created_at",
            (account_id,)).fetchall()
    return [_public(r) for r in rows]


def remove(account_id: int, connection_id: int, *, dsn: Optional[str] = None) -> bool:
    """Disconnect: soft, and the tokens are wiped from the row at once --
    a disconnected account's credential is not kept for anyone."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        cur = conn.execute(
            "UPDATE social_connections SET deleted_at = now(), token_enc = '', refresh_enc = '', "
            "updated_at = now() WHERE id = %s AND account_id = %s AND deleted_at IS NULL",
            (connection_id, account_id))
        return cur.rowcount > 0


# --------------------------------------------------------------------------
# the in-between step
# --------------------------------------------------------------------------

def options(account_id: int, connection_id: int, *, dsn: Optional[str] = None) -> list[dict[str, Any]]:
    row = _row(account_id, connection_id, dsn)
    if not row:
        raise ConnectRefused("No such connection on this workspace.")
    mod = social.get(row["provider"])
    if mod is None or not hasattr(mod, "options") or not row.get("pending"):
        return []
    return mod.options(_meta(row))


def pick(account_id: int, connection_id: int, choice: str, *,
         dsn: Optional[str] = None) -> dict[str, Any]:
    """Finish a pending connection with the person's choice. The provider
    checks the choice is real; only then does `pending` clear."""
    row = _row(account_id, connection_id, dsn)
    if not row:
        raise ConnectRefused("No such connection on this workspace.")
    mod = social.get(row["provider"])
    if mod is None or not hasattr(mod, "pick"):
        raise ConnectRefused("This connection has no step to finish.")
    if not row.get("pending"):
        raise ConnectRefused("This connection is already finished.")
    meta = mod.pick(_meta(row), choice)
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE social_connections SET meta_json = %s, pending = NULL, updated_at = now() "
            "WHERE id = %s AND account_id = %s",
            (json.dumps(meta), connection_id, account_id))
    got = get(account_id, connection_id, dsn=dsn)
    assert got is not None
    return got


# --------------------------------------------------------------------------
# the one reader
# --------------------------------------------------------------------------

def connection_for(account_id: int, provider: str, *,
                   dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    """The newest finished, live connection of this provider, public
    shape (no token). None when the account has none."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        row = conn.execute(
            f"SELECT {COLUMNS} FROM social_connections "
            "WHERE account_id = %s AND provider = %s AND deleted_at IS NULL "
            "AND pending IS NULL ORDER BY created_at DESC LIMIT 1",
            (account_id, provider)).fetchone()
    return _public(row) if row else None


def token_for(account_id: int, provider: str, *, connection_id: Optional[int] = None,
              dsn: Optional[str] = None, now: Optional[datetime] = None) -> tuple[str, dict[str, Any]]:
    """The credential that posts for this account on this platform, and
    the connection it belongs to (public shape). Renews first when the
    token is inside REFRESH_WINDOW of expiry and the provider can.
    Raises ConnectRefused, in plain words, when there is none, it has
    lapsed, or the renewal failed (the row is then marked for reconnect)."""
    ensure(dsn)
    mod = social.get(provider)
    if mod is None:
        raise ConnectRefused(f"{provider!r} is not a platform this studio connects.")
    with db.connect(dsn) as conn:
        if connection_id is not None:
            row = conn.execute(
                f"SELECT {COLUMNS} FROM social_connections "
                "WHERE id = %s AND account_id = %s AND provider = %s AND deleted_at IS NULL",
                (connection_id, account_id, provider)).fetchone()
        else:
            # the newest finished one; with none, the newest pending one,
            # so the refusal says "finish" rather than "connect"
            row = conn.execute(
                f"SELECT {COLUMNS} FROM social_connections "
                "WHERE account_id = %s AND provider = %s AND deleted_at IS NULL "
                "ORDER BY (pending IS NULL) DESC, created_at DESC LIMIT 1",
                (account_id, provider)).fetchone()
    if not row:
        raise ConnectRefused(f"Connect your {mod.NAME} account first (Settings → Connections).")
    if row.get("pending"):
        raise ConnectRefused(f"Finish connecting {mod.NAME} first: the {row['pending']} is not picked yet.")
    if row.get("refresh_needed"):
        raise ConnectRefused(f"Your {mod.NAME} connection needs to be reconnected.")
    moment = now or _now()
    expires = row.get("expires_at")
    token = unseal(row["token_enc"])
    if expires is not None and expires <= moment:
        _mark_refresh_needed(account_id, int(row["id"]), dsn)
        raise ConnectRefused(f"Your {mod.NAME} connection has expired; connect it again.")
    if expires is not None and expires - moment <= REFRESH_WINDOW:
        renewed = _renew(mod, row, token, account_id, dsn)
        if renewed is not None:
            token = renewed
            fresh = _row(account_id, int(row["id"]), dsn)
            row = fresh or row
    return token, _public(row)


def _renew(mod, row: dict, token: str, account_id: int, dsn: Optional[str]) -> Optional[str]:
    refresh_token = unseal(row.get("refresh_enc") or "")
    try:
        renewed: Optional[Renewed] = mod.refresh(token, refresh_token)
    except ConnectRefused:
        _mark_refresh_needed(account_id, int(row["id"]), dsn)
        raise
    if renewed is None or not renewed.access_token:
        return None
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE social_connections SET token_enc = %s, refresh_enc = %s, expires_at = %s, "
            "refresh_needed = FALSE, updated_at = now() WHERE id = %s AND account_id = %s",
            (seal(renewed.access_token), seal(renewed.refresh_token or refresh_token),
             _expires(renewed.expires_in), row["id"], account_id))
    return renewed.access_token


def _mark_refresh_needed(account_id: int, connection_id: int, dsn: Optional[str]) -> None:
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE social_connections SET refresh_needed = TRUE, updated_at = now() "
            "WHERE id = %s AND account_id = %s", (connection_id, account_id))


def has(account_id: int, provider: str, *, dsn: Optional[str] = None) -> bool:
    return connection_for(account_id, provider, dsn=dsn) is not None
