def _ratio(top: Optional[float], bottom: Optional[float]) -> Optional[float]:
    return round(top / bottom, 4) if top is not None and bottom else None


def summary(*, account_id: Optional[int], dsn: Optional[str] = None) -> dict:
    """Every ad this account imported, summed over its windows, with its
    render, its variant and its rates; the variant tests; the imports.
    Never raises: an empty {"ads": [], ...} on any error."""
    empty = {"ads": [], "tests": [], "imports": [], "unmatched": 0}
    if account_id is None:
        return empty
    try:
        ensure(dsn)
        with db.connect(dsn) as conn:
            rows = conn.execute(
                "SELECT r.platform, r.ad_key, max(r.ad_name) AS ad_name, max(r.currency) AS currency, "
                "max(r.asset_id) AS asset_id, max(r.concept_id) AS concept_id, "
                "min(NULLIF(r.period_start, '')) AS first_day, max(r.period_end) AS last_day, "
                "sum(r.spend) AS spend, sum(r.impressions) AS impressions, "
                "sum(r.clicks) AS clicks, sum(r.results) AS results, "
                "max(r.result_type) AS result_type, sum(r.revenue) AS revenue, "
                "count(r.revenue) AS revenue_rows "
                "FROM ad_results r WHERE r.account_id = %s "
                "GROUP BY r.platform, r.ad_key ORDER BY sum(r.spend) DESC LIMIT 500",
                (account_id,)).fetchall()
            concepts = sorted({r["concept_id"] for r in rows if r["concept_id"]})
            variants = {v["concept_id"]: dict(v) for v in conn.execute(
                "SELECT concept_id, group_id, label, test FROM ad_variants "
                "WHERE account_id = %s AND concept_id = ANY(%s)",
                (account_id, concepts)).fetchall()} if concepts else {}
            imports = [dict(r) for r in conn.execute(
                "SELECT import_id, max(platform) AS platform, max(filename) AS filename, "
                "max(imported_at) AS imported_at, count(*) AS rows FROM ad_results "
                "WHERE account_id = %s GROUP BY import_id ORDER BY max(imported_at) DESC LIMIT 20",
                (account_id,)).fetchall()]
    except Exception:                                           # noqa: BLE001
        return empty
    ads = []
    for r in rows:
        spend, results = float(r["spend"] or 0), float(r["results"] or 0)
        revenue = float(r["revenue"]) if r["revenue_rows"] else None
        v = variants.get(r["concept_id"]) or {}
        ads.append({
            "platform": r["platform"], "ad_name": r["ad_name"], "currency": r["currency"],
            "asset_id": r["asset_id"], "concept_id": r["concept_id"],
            "code": code_for(r["asset_id"]) if r["asset_id"] else None,
            "variant": v.get("label"), "group_id": v.get("group_id"), "test": v.get("test"),
            "first_day": r["first_day"], "last_day": r["last_day"] or None,
            "spend": round(spend, 2), "impressions": int(r["impressions"] or 0),
            "clicks": int(r["clicks"] or 0), "results": results,
            "result_type": r["result_type"], "revenue": revenue,
            "ctr": _ratio(float(r["clicks"] or 0), float(r["impressions"] or 0)),
            "cpa": round(spend / results, 2) if results else None,
            "roas": _ratio(revenue, spend),
        })
    for imp in imports:
        imp["imported_at"] = str(imp["imported_at"])
    return {"ads": ads, "tests": tests(ads), "imports": imports,
            "unmatched": sum(1 for a in ads if not a["asset_id"])}


def tests(ads: list[dict]) -> list[dict]:
    """The variant groups that ran, each with its ads best first and a
    verdict: the winner, or why there is none yet. Cost per result decides,
    and only between ads in one currency with results to divide by."""
    groups: dict[str, list[dict]] = {}
    for ad in ads:
        if ad.get("group_id"):
            groups.setdefault(ad["group_id"], []).append(ad)
    out = []
    for gid, members in groups.items():
        ranked = sorted(members, key=lambda a: (a["cpa"] is None, a["cpa"] or 0, -a["spend"]))
        priced = [a for a in ranked if a["cpa"] is not None]
        currencies = {a["currency"] for a in priced}
        if len(members) < 2:
            verdict, winner = "only one version has run", None
        elif len(priced) < 2:
            verdict, winner = "fewer than two versions have results yet", None
        elif len(currencies) > 1:
            verdict, winner = "the versions ran in different currencies", None
        elif priced[0]["results"] < MIN_RESULTS:
            verdict, winner = f"too early: the best has under {MIN_RESULTS} results", None
        else:
            winner = priced[0]
            verdict = f"{winner['variant']} wins on cost per result"
        out.append({"group_id": gid, "test": next((a["test"] for a in members if a["test"]), None),
                    "ads": ranked, "winner": winner["code"] if winner else None,
                    "verdict": verdict})
    return out


def note(account_id: Optional[int], dsn: Optional[str] = None) -> str:
    """What an Ad Studio turn is told about this account's ads that ran,
    or "" when none has. Facts only, the person's own numbers."""
    data = summary(account_id=account_id, dsn=dsn)
    priced = [a for a in data["ads"] if a["cpa"] is not None and a["asset_id"]]
    if not priced and not data["tests"]:
        return ""
    lines = ["WHAT THEIR ADS DID (imported from their ad account; their own numbers):"]
    for a in sorted(priced, key=lambda a: a["cpa"])[:NOTE_ADS]:
        what = f" -- {a['variant']}" if a["variant"] else ""
        roas = f", return {a['roas']:.2f}x" if a["roas"] is not None else ""
        money = f"{a['cpa']:.2f} {a['currency']}" if a["currency"] else f"{a['cpa']:.2f}"
        lines.append(f"- {a['code']}{what}: {a['results']:g} results at {money} each{roas}")
    for t in data["tests"][:NOTE_ADS]:
        lines.append(f"- Test{(': ' + t['test']) if t['test'] else ''} -> {t['verdict']}")
    lines.append("When they ask for the next ad or for variants, build on what is winning and "
                 "say which result you are building on. Never promise a result.")
    return "\n".join(lines)
