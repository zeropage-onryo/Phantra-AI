def _owned_assets(conn, account_id: int, ids: list[int]) -> dict[int, Optional[int]]:
    """{asset id: its scene} for the ids that are this account's outputs."""
    if not ids or not db.table_exists(conn, "generated_assets"):
        return {}
    found = conn.execute(
        "SELECT id, concept_id FROM generated_assets WHERE account_id = %s AND id = ANY(%s)",
        (account_id, ids)).fetchall()
    return {r["id"]: r.get("concept_id") for r in found}


def import_csv(data: bytes, *, account_id: int, filename: str = "",
               dsn: Optional[str] = None) -> dict:
    """Read an export and keep it. Returns what happened: the platform, how
    many rows were new or updated, how many matched a render, and the ad
    names that carried no code of this account's (to rename). Raises
    ImportRefused for a file it cannot read, before anything is written."""
    parsed = parse(data)
    ensure(dsn)
    import_id = uuid.uuid4().hex[:12]
    added = updated = matched = 0
    unmatched: list[str] = []
    new_assets: set[int] = set()
    with db.connect(dsn) as conn:
        wanted = sorted({c for r in parsed["rows"] for c in r["codes"]})
        owned = _owned_assets(conn, account_id, wanted)
        seen_before = {r["asset_id"] for r in conn.execute(
            "SELECT DISTINCT asset_id FROM ad_results WHERE account_id = %s "
            "AND asset_id = ANY(%s)", (account_id, list(owned))).fetchall()} if owned else set()
        for row in parsed["rows"]:
            asset = next((c for c in row["codes"] if c in owned), None)
            concept = owned.get(asset) if asset else None
            if asset:
                matched += 1
                if row["spend"] > 0 and asset not in seen_before:
                    new_assets.add(asset)
            elif row["ad_name"] not in unmatched:
                unmatched.append(row["ad_name"])
            got = conn.execute(
                "INSERT INTO ad_results (account_id, import_id, platform, ad_key, ad_name, ad_id, "
                "campaign, adset, period_start, period_end, currency, spend, impressions, clicks, "
                "results, result_type, revenue, asset_id, concept_id, filename) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) "
                "ON CONFLICT (account_id, platform, ad_key, period_start, period_end) DO UPDATE SET "
                "import_id = EXCLUDED.import_id, ad_name = EXCLUDED.ad_name, "
                "campaign = EXCLUDED.campaign, adset = EXCLUDED.adset, "
                "currency = EXCLUDED.currency, spend = EXCLUDED.spend, "
                "impressions = EXCLUDED.impressions, clicks = EXCLUDED.clicks, "
                "results = EXCLUDED.results, result_type = EXCLUDED.result_type, "
                "revenue = EXCLUDED.revenue, asset_id = EXCLUDED.asset_id, "
                "concept_id = EXCLUDED.concept_id, filename = EXCLUDED.filename, "
                "imported_at = now() RETURNING (xmax = 0) AS inserted",
                (account_id, import_id, parsed["platform"], row["ad_key"][:MAX_TEXT],
                 row["ad_name"], row["ad_id"], row["campaign"], row["adset"],
                 row["period_start"], row["period_end"], parsed["currency"], row["spend"],
                 row["impressions"], row["clicks"], row["results"], row["result_type"],
                 row["revenue"], asset, concept, _text(filename, 200) or None)).fetchone()
            if got and got["inserted"]:
                added += 1
            else:
                updated += 1
    # an ad that ran is the strongest "kept" there is (src/outcomes.py);
    # written once per output, the first time it shows spend
    from . import outcomes
    for asset in sorted(new_assets):
        outcomes.record("ad_run", account_id=account_id, asset_id=asset, source="ad_results",
                        meta={"platform": parsed["platform"]}, teach=False, dsn=dsn)
    return {"import_id": import_id, "platform": parsed["platform"],
            "currency": parsed["currency"], "rows": len(parsed["rows"]), "added": added,
            "updated": updated, "matched": matched, "skipped": parsed["skipped"],
            "unmatched": unmatched[:50], "unmatched_count": len(unmatched)}


def delete_import(import_id: str, *, account_id: int, dsn: Optional[str] = None) -> int:
    """Take one import's rows back out. Returns how many went. Rows a later
    import updated belong to that import now and stay."""
    ensure(dsn)
    with db.connect(dsn) as conn:
        cur = conn.execute("DELETE FROM ad_results WHERE account_id = %s AND import_id = %s",
                           (account_id, str(import_id or "")[:32]))
        return cur.rowcount or 0


def record_variant(concept_id: int, *, account_id: int, group_id: str, label: str,
                   test: str = "", dsn: Optional[str] = None) -> bool:
    """File a written scene as one version in a test. Never raises."""
    label = _text(label, MAX_LABEL)
    group = re.sub(r"[^A-Za-z0-9_-]", "", str(group_id or ""))[:64]
    if not (concept_id and label and group):
        return False
    try:
        ensure(dsn)
        with db.connect(dsn) as conn:
            conn.execute(
                "INSERT INTO ad_variants (account_id, concept_id, group_id, label, test) "
                "VALUES (%s, %s, %s, %s, %s) ON CONFLICT (account_id, concept_id) DO UPDATE "
                "SET group_id = EXCLUDED.group_id, label = EXCLUDED.label, test = EXCLUDED.test",
                (account_id, int(concept_id), group, label, _text(test, MAX_TEST) or None))
        return True
    except Exception:                                           # noqa: BLE001
        return False


