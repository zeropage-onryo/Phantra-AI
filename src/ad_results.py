"""What an ad did once it ran (2026-10-29, docs/tasks/task-ad-results.md).

Runway Ads' pitch is an agent that "knows your campaign results". Before
this, Phantra knew what a person kept and what an organic post did, and
nothing about paid ads: what a render spent, what it bought, what each
result cost. This module is that half, on the cheapest road there is: the
person exports the ad-level report from Meta Ads Manager or TikTok Ads
Manager as a CSV and drops it on the Ad Studio. No ad-platform app, no
review, no token -- the Ads APIs wait until a paying client needs them.

THE AD CODE IS THE JOIN. Every output has one, `PH<asset id>` (`code_for`),
shown in the Library viewer and on the Ad Studio. Put it in the ad's NAME
(or its URL parameters, `utm_content=PH4821`) and an imported row finds its
render: `codes_in` reads it back, and the render must be this account's
own (`generated_assets.account_id`), so a code copied from somebody else
matches nothing. A row with no code is kept and listed as unmatched: it is
still the person's data, and naming the ad is the fix.

VARIANTS. An Ad Studio plan can write several versions of one ad, each
changing ONE thing (`make_plan`'s `variant` and `test`). Each scene step
it writes is recorded here (`record_variant`, OWNED `ad_variants`: the
scene, the plan's group, the label), so the results can be read the way a
test is: which hook won, at what cost per result, and whether it is too
early to say (`MIN_RESULTS`).

WHAT IS STORED. One `ad_results` row per ad per reporting window per
platform, upserted: importing the same export twice changes nothing, and
importing a later window adds to it. Money is kept in the export's own
currency (the header says it: "Amount spent (USD)"); nothing here converts
it, and nothing here is a Phantra price -- the studio still shows credits
for what Phantra charges.

Readers never raise; `import_csv` refuses a file it cannot read with a
plain reason (`ImportRefused`), and writes nothing in that case.
"""
from __future__ import annotations

import csv
import io
import re
import threading
import uuid
from typing import Any, Optional

from . import db

CODE_PREFIX = "PH"
# PH4821 or PH-4821, anywhere in a name or a URL parameter, never inside a
# longer word or number ("GRAPH12" and "PH48219999999" are not codes)
_CODE = re.compile(r"(?<![A-Za-z0-9])PH-?(\d{1,9})(?![0-9])", re.IGNORECASE)

MAX_BYTES = 5 << 20          # an ad-level export is kilobytes; 5 MB is generous
MAX_ROWS = 20_000
MAX_TEXT = 300
MAX_LABEL = 60
MAX_TEST = 120
# a winner is only called when the best ad has at least this many results;
# below it the group is "too early", whatever the cost per result says
MIN_RESULTS = 5
NOTE_ADS = 3

PLATFORMS = ("meta", "tiktok", "csv")

SCHEMA = """
CREATE TABLE IF NOT EXISTS ad_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id    TEXT   NOT NULL,
    platform     TEXT   NOT NULL,
    ad_key       TEXT   NOT NULL,
    ad_name      TEXT   NOT NULL,
    ad_id        TEXT,
    campaign     TEXT,
    adset        TEXT,
    period_start TEXT   NOT NULL DEFAULT '',
    period_end   TEXT   NOT NULL DEFAULT '',
    currency     TEXT,
    spend        DOUBLE PRECISION NOT NULL DEFAULT 0,
    impressions  BIGINT NOT NULL DEFAULT 0,
    clicks       BIGINT NOT NULL DEFAULT 0,
    results      DOUBLE PRECISION NOT NULL DEFAULT 0,
    result_type  TEXT,
    revenue      DOUBLE PRECISION,
    asset_id     BIGINT,
    concept_id   BIGINT,
    filename     TEXT,
    imported_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ad_variants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id  BIGINT NOT NULL,
    group_id    TEXT   NOT NULL,
    label       TEXT   NOT NULL,
    test        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""
INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS ad_results_one_idx
    ON ad_results (account_id, platform, ad_key, period_start, period_end);
CREATE INDEX IF NOT EXISTS ad_results_asset_idx ON ad_results (account_id, asset_id);
CREATE UNIQUE INDEX IF NOT EXISTS ad_variants_one_idx ON ad_variants (account_id, concept_id);
"""

_ready: set[str] = set()
_ready_lock = threading.Lock()


class ImportRefused(ValueError):
    """The file is not something this can read; nothing was written."""


def init(dsn: Optional[str] = None) -> None:
    key = db.resolve_dsn(dsn)
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "ad_results")
        db.own_table(conn, "ad_variants")
        conn.execute(INDEXES)
    _ready.add(key)


def ensure(dsn: Optional[str] = None) -> None:
    """Once per process and database (never an init per request)."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)


# --------------------------------------------------------------------------
# the code
# --------------------------------------------------------------------------

def code_for(asset_id: int) -> str:
    """The ad code of one output. web/src/lib/ad-results.ts `adCode` writes
    the same; tests/test_ad_results.py holds the two together."""
    return f"{CODE_PREFIX}{int(asset_id)}"


def codes_in(*texts: Any) -> list[int]:
    """Every asset id named by a code in these texts, first seen first."""
    found: list[int] = []
    for text in texts:
        for m in _CODE.finditer(str(text or "")):
            n = int(m.group(1))
            if n > 0 and n not in found:
                found.append(n)
    return found


# --------------------------------------------------------------------------
# reading an export
# --------------------------------------------------------------------------

# each field, and the headers (normalised: lower case, single spaces, a
# trailing currency like "(USD)" taken off) that carry it, best first
FIELDS: dict[str, tuple[str, ...]] = {
    "ad_name": ("ad name",),
    "ad_id": ("ad id",),
    "campaign": ("campaign name", "campaign"),
    "adset": ("ad set name", "ad group name", "ad set", "ad group"),
    "start": ("reporting starts", "date", "day", "by day", "start date", "date start",
              "reporting start"),
    "end": ("reporting ends", "end date", "date end", "reporting end"),
    "spend": ("amount spent", "cost", "spend", "total cost"),
    "impressions": ("impressions",),
    "clicks": ("link clicks", "clicks (destination)", "clicks (all)", "clicks"),
    "results": ("results", "conversions", "purchases", "website purchases", "result"),
    "result_type": ("result indicator", "result type", "optimization goal"),
    "revenue": ("purchases conversion value", "website purchases conversion value",
                "purchase conversion value", "total complete payment value",
                "complete payment value", "total purchase value", "purchase value",
                "conversion value", "revenue"),
    "url_params": ("url parameters", "url tags", "link", "website url"),
}
NEEDED = ("ad_name", "spend")
_CURRENCY = re.compile(r"\s*\(([A-Z]{3})\)\s*$")


def _header(raw: str) -> tuple[str, Optional[str]]:
    """A header normalised for matching, and the currency it names."""
    text = " ".join(str(raw or "").replace("﻿", "").split())
    m = _CURRENCY.search(text)
    currency = m.group(1) if m else None
    if m:
        text = text[: m.start()]
    return text.strip().lower(), currency


def _columns(headers: list[str]) -> tuple[dict[str, int], Optional[str]]:
    """Which column carries each field, and the currency the money is in."""
    normal = [_header(h) for h in headers]
    found: dict[str, int] = {}
    for field, names in FIELDS.items():
        for name in names:
            idx = next((i for i, (h, _) in enumerate(normal) if h == name), None)
            if idx is not None:
                found[field] = idx
                break
    currency = None
    for field in ("spend", "revenue"):
        if field in found and normal[found[field]][1]:
            currency = normal[found[field]][1]
            break
    return found, currency


def _platform(headers: list[str]) -> str:
    names = {_header(h)[0] for h in headers}
    if names & {"reporting starts", "amount spent", "ad set name", "result indicator"}:
        return "meta"
    if names & {"ad group name", "clicks (destination)", "total complete payment value",
                "complete payment value"} or ("cost" in names and "ad name" in names):
        return "tiktok"
    return "csv"


def _number(raw: Any) -> Optional[float]:
    text = str(raw or "").strip()
    if not text or text in ("-", "--", "—", "N/A", "n/a"):
        return None
    text = re.sub(r"[^\d.,\-]", "", text)
    if text.count(",") and text.count("."):
        text = text.replace(",", "")
    elif text.count(",") == 1 and len(text.split(",")[1]) != 3:
        text = text.replace(",", ".")          # 12,50 is twelve and a half
    else:
        text = text.replace(",", "")
    try:
        return float(text)
    except ValueError:
        return None


def _text(raw: Any, limit: int = MAX_TEXT) -> str:
    return " ".join(str(raw or "").split())[:limit]


def _decode(data: bytes) -> str:
    for encoding in ("utf-8-sig", "utf-16", "cp1252"):
        try:
            text = data.decode(encoding)
        except UnicodeDecodeError:
            continue
        if "\x00" not in text:
            return text
    raise ImportRefused("that file is not text: export the report as CSV")


def parse(data: bytes) -> dict:
    """An export, read: {"platform", "currency", "rows": [...], "skipped"}.
    Refuses (ImportRefused) a file that is not a CSV with at least an ad
    name and an amount spent. Rows with no ad name (a totals row) are
    skipped and counted."""
    if not data:
        raise ImportRefused("the file is empty")
    if len(data) > MAX_BYTES:
        raise ImportRefused("that file is over 5 MB: export the ad-level report only")
    if data[:2] == b"PK":
        raise ImportRefused("that is a spreadsheet (.xlsx): export the report as CSV instead")
    text = _decode(data)
    try:
        dialect = csv.Sniffer().sniff(text[:4096], delimiters=",;\t")
    except csv.Error:
        dialect = csv.excel
    table = list(csv.reader(io.StringIO(text), dialect))
    table = [r for r in table if any(c.strip() for c in r)]
    if not table:
        raise ImportRefused("the file has no rows")
    headers = table[0]
    cols, currency = _columns(headers)
    missing = [f for f in NEEDED if f not in cols]
    if missing:
        words = {"ad_name": "an “Ad name” column", "spend": "an “Amount spent” or “Cost” column"}
        raise ImportRefused("this export has no " + " or ".join(words[m] for m in missing)
                            + ": export at the AD level, as CSV")
    if len(table) - 1 > MAX_ROWS:
        raise ImportRefused(f"that is over {MAX_ROWS:,} rows: export a shorter date range")

    def cell(row: list[str], field: str) -> str:
        i = cols.get(field)
        return row[i] if i is not None and i < len(row) else ""

    rows, skipped = [], 0
    for raw in table[1:]:
        name = _text(cell(raw, "ad_name"))
        if not name:
            skipped += 1
            continue
        ad_id = _text(cell(raw, "ad_id"), 64)
        rows.append({
            "ad_name": name,
            "ad_id": ad_id or None,
            "ad_key": ad_id or name.lower(),
            "campaign": _text(cell(raw, "campaign")) or None,
            "adset": _text(cell(raw, "adset")) or None,
            "period_start": _text(cell(raw, "start"), 32),
            "period_end": _text(cell(raw, "end"), 32) or _text(cell(raw, "start"), 32),
            "spend": _number(cell(raw, "spend")) or 0.0,
            "impressions": int(_number(cell(raw, "impressions")) or 0),
            "clicks": int(_number(cell(raw, "clicks")) or 0),
            "results": _number(cell(raw, "results")) or 0.0,
            "result_type": _text(cell(raw, "result_type"), 80) or None,
            "revenue": _number(cell(raw, "revenue")) if "revenue" in cols else None,
            "codes": codes_in(name, cell(raw, "url_params")),
        })
    return {"platform": _platform(headers), "currency": currency, "rows": rows,
            "skipped": skipped, "columns": sorted(cols)}


