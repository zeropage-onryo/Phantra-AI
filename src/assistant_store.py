"""
What the assistant pill remembers, per account (2026-09-29).

Until today the pill kept its persona in localStorage and its conversation
in sessionStorage, so the thread died with the tab (it was lost twice on
2026-09-28 alone) and Nova had to be set up again in every browser. Three
OWNED tables, one owner each:

- `assistants`: the persona -- a name, an emoji, one of the three tones.
  One row per account. Cleaned with the same rules the brain applies when
  it puts the name into a prompt (assistant_brain.clean_name/clean_tone),
  so the pill never shows a name the model was not given.
- `assistant_projects`: the conversation and the step it is on, and since
  2026-10-02 the composer's DRAFT beside it (`draft_json`: the idea in the
  box, the brief the guide wrote, the picked references, the uploads as
  their bin URLs, which mode the box is in, the last "scene written"
  card). One row per account, and it is WORKING MEMORY, not a record
  (2026-10-02, Mike's call): a conversation exists only so the person can
  pick up where they left off, on any page and in any browser. Once the
  scene is CREATED the conversation goes away -- what it produced lives
  on the concept and, after a render, on the asset with its prompt (the
  Assets wall shows it there). The pill's button clears it the same way.
  Since 2026-11-03 (Mike's pick "C2" on the Sessions & Memory canvas) a
  conversation is KEPT when a new session starts: the open row is the one
  with `archived_at` NULL (one per account, the partial unique index) and
  every earlier chat is a parked row beside it, listed in the chat
  sheet's history drawer and reopened from there (`list_chats`,
  `open_chat`). A chat a Create turn ran inside a project carries that
  `project_id` and is kept for good, filed under the project; any other
  chat is deleted CHAT_KEEP_DAYS after it was last used (`expire_chats`).
  A chat with nothing said in it is never parked, it is deleted. The
  Studio composer's own Guide thread lived only in the page's React
  state until 2026-10-02, so clicking to another tab lost the
  conversation and every frame the hunt had drawn; now the composer and
  the pill are two views on this one row.
- `reference_verdicts`: the person's click on a contact sheet beside what
  refcheck decided about the same frame. Keep a frame the checker cut, or
  leave one it kept, and that disagreement is the only evidence there is of
  where the checker's taste and the person's part. `agreement()` reads it.
  Nothing consumes it automatically yet: a checker that retuned itself off
  a dozen clicks would be learning noise.

Nothing here calls a model or spends; every function degrades to "nothing
remembered" rather than raising into the page.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

from . import db

# A thread is the pill's working memory, not an archive: the newest turns
# are what the next turn sends and what the card draws. Bounded so a long
# project cannot grow one row without limit.
MAX_TURNS = 40
MAX_TURNS_BYTES = 400_000
MAX_AVATAR_CHARS = 16          # one emoji can be a long ZWJ sequence
# The draft is bounded by construction (_clean_draft keeps known keys and
# cuts each), so no byte cap is needed beyond the per-field ones.
MAX_DRAFT_TEXT = 10_000        # the composer's own textarea maxLength
MAX_DRAFT_REFS = 40            # picked photos / uploads, each a URL
DRAFT_MODES = ("guide", "create")
# A chat outside any project is kept this long after it was last used
# (2026-11-03, Mike); a project's chats are kept until the project goes.
CHAT_KEEP_DAYS = 14
# How many chats the history drawer lists, newest first.
CHAT_LIST_MAX = 100

SCHEMA = """
CREATE TABLE IF NOT EXISTS assistants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    avatar      TEXT NOT NULL,
    tone        TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS assistant_projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT NOT NULL DEFAULT '',
    stage       TEXT NOT NULL DEFAULT '',
    turns_json  TEXT NOT NULL DEFAULT '[]',
    draft_json  TEXT NOT NULL DEFAULT '{}',
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    archived_at TEXT
);
CREATE TABLE IF NOT EXISTS reference_verdicts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT,
    candidate_id  TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT '',
    query         TEXT NOT NULL DEFAULT '',
    checker_kept  BOOLEAN NOT NULL,
    checker_why   TEXT NOT NULL DEFAULT '',
    person_kept   BOOLEAN NOT NULL,
    source_url    TEXT NOT NULL DEFAULT '',
    created_at    TEXT NOT NULL
);
"""

INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS idx_assistants_account ON assistants (account_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_assistant_projects_open
    ON assistant_projects (account_id) WHERE archived_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_reference_verdicts_account
    ON reference_verdicts (account_id, created_at);
"""

TABLES = ("assistants", "assistant_projects", "reference_verdicts")


def init(dsn: Optional[str] = None) -> None:
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        # additive, for the live table made before the draft existed
        conn.execute("ALTER TABLE assistant_projects "
                     "ADD COLUMN IF NOT EXISTS draft_json TEXT NOT NULL DEFAULT '{}'")
        # which project a chat belongs to (2026-11-03): set by a Create
        # turn that ran inside one; NULL is a chat on its own
        conn.execute("ALTER TABLE assistant_projects "
                     "ADD COLUMN IF NOT EXISTS project_id BIGINT")
        for table in TABLES:
            db.own_table(conn, table)
        conn.execute(INDEXES)
    # chats past their keep date go at every start, as well as on every list
    expire_chats(dsn=dsn)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


# --- the persona -------------------------------------------------------------

def clean_avatar(avatar) -> str:
    """One emoji (or any short glyph), never markup: whitespace and angle
    brackets are dropped, the rest cut to MAX_AVATAR_CHARS."""
    avatar = re.sub(r"[\s<>&\"']", "", str(avatar or ""))
    return avatar[:MAX_AVATAR_CHARS]


def get_persona(*, account_id: int, dsn: Optional[str] = None) -> Optional[dict]:
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT name, avatar, tone, updated_at FROM assistants WHERE account_id = %s",
            (account_id,)).fetchone()
    return dict(row) if row else None


def save_persona(name, avatar, tone, *, account_id: int,
                 dsn: Optional[str] = None) -> dict:
    """Upsert the account's persona, cleaned. Returns what was stored."""
    from . import assistant_brain
    persona = {"name": assistant_brain.clean_name(name),
               "avatar": clean_avatar(avatar) or "🦊",
               "tone": assistant_brain.clean_tone(tone)}
    with db.connect(dsn) as conn:
        conn.execute(
            "INSERT INTO assistants (account_id, name, avatar, tone, updated_at) "
            "VALUES (%s, %s, %s, %s, %s) "
            "ON CONFLICT (account_id) DO UPDATE SET name = EXCLUDED.name, "
            "avatar = EXCLUDED.avatar, tone = EXCLUDED.tone, updated_at = EXCLUDED.updated_at",
            (account_id, persona["name"], persona["avatar"], persona["tone"], _now()))
    return persona


# --- the project ------------------------------------------------------------

def _bounded(turns: list) -> list:
    """The newest MAX_TURNS turns, dropping from the front until the JSON
    fits MAX_TURNS_BYTES. A turn that is not a dict is not a turn."""
    turns = [t for t in (turns or []) if isinstance(t, dict)][-MAX_TURNS:]
    while turns and len(json.dumps(turns, default=str)) > MAX_TURNS_BYTES:
        turns = turns[1:]
    return turns


def _urls(value) -> list:
    """A list of reference URLs as the composer holds them: site-relative
    paths or http(s), strings only, deduplicated in order, bounded."""
    out: list = []
    for u in (value if isinstance(value, list) else [])[:MAX_DRAFT_REFS * 2]:
        u = str(u or "").strip() if isinstance(u, str) else ""
        if u and len(u) <= 1000 and (u.startswith("/") or u.startswith("http")) \
                and u not in out:
            out.append(u)
        if len(out) >= MAX_DRAFT_REFS:
            break
    return out


def _clean_draft(draft) -> dict:
    """The composer's draft, keys and types this store knows and nothing
    else. A field the page never wrote comes back as its empty value, so
    the client can trust the shape and never has to default it."""
    d = draft if isinstance(draft, dict) else {}
    uploads: list = []
    for item in (d.get("uploads") if isinstance(d.get("uploads"), list) else [])[:MAX_DRAFT_REFS]:
        if not isinstance(item, dict):
            continue
        url = _urls([item.get("url")])
        if url:
            uploads.append({"url": url[0],
                            "name": " ".join(str(item.get("name") or "").split())[:200]})
    written = d.get("written") if isinstance(d.get("written"), dict) else None
    if written is not None:
        cid = written.get("conceptId")
        written = {"conceptId": int(cid) if isinstance(cid, int) and not isinstance(cid, bool) else None,
                   "detail": str(written.get("detail") or "")[:300]}
    mode = str(d.get("mode") or "")
    # what each attached reference is for (src/ref_roles.py), kept only for
    # the references the draft still holds
    from . import ref_roles
    held = set(_urls(d.get("picked"))) | {u["url"] for u in uploads}
    roles = {ref: role for ref, role in ref_roles.clean(d.get("roles")).items() if ref in held}
    # a brand kit picked for this conversation outside a project
    # (2026-10-22): an id only; whose it is is checked where it is used
    kit = d.get("brand_kit_id")
    kit = kit if isinstance(kit, int) and not isinstance(kit, bool) and kit > 0 else None
    # the Ad Studio's brief on this conversation (2026-10-26, src/studios.py):
    # cleaned against the studio's config; whether it reaches the brain is
    # the add-on's call, made on every turn (studios.for_account)
    from . import studios
    studio = studios.clean_pick(d.get("studio"))
    return {"idea": str(d.get("idea") or "")[:MAX_DRAFT_TEXT],
            "brief": str(d.get("brief") or "")[:MAX_DRAFT_TEXT],
            # Create is the box's default (Direction A, 2026-10-02); a
            # Guide the person chose is stored and kept
            "mode": mode if mode in DRAFT_MODES else "create",
            "picked": _urls(d.get("picked")),
            "uploads": uploads,
            "roles": roles,
            "written": written,
            "brand_kit_id": kit,
            "studio": studio}


EMPTY_DRAFT = _clean_draft({})


def _project(row) -> dict:
    out = dict(row)
    try:
        out["turns"] = json.loads(out.pop("turns_json") or "[]")
    except ValueError:
        out["turns"] = []
    try:
        out["draft"] = _clean_draft(json.loads(out.pop("draft_json", None) or "{}"))
    except ValueError:
        out["draft"] = dict(EMPTY_DRAFT)
    return out


_PROJECT_COLS = "id, title, stage, turns_json, draft_json, created_at, updated_at, project_id"


def open_project(*, account_id: int, dsn: Optional[str] = None) -> Optional[dict]:
    with db.connect(dsn) as conn:
        row = conn.execute(
            f"SELECT {_PROJECT_COLS} "
            "FROM assistant_projects WHERE account_id = %s AND archived_at IS NULL",
            (account_id,)).fetchone()
    return _project(row) if row else None


def save_project(turns, stage, *, account_id: int, title: str = "",
                 draft: Optional[dict] = None, dsn: Optional[str] = None) -> dict:
    """Write the open project's thread and step, creating it on first save.

    `draft` is the composer's box (see _clean_draft); None -- a caller
    that only knows the thread, like the pill did before the two shared
    a row -- leaves whatever draft is stored exactly as it was."""
    from . import assistant_brain
    turns = _bounded(turns)
    stage = assistant_brain.clean_stage(stage)
    title = " ".join(str(title or "").split())[:120]
    if not title:
        first = next((t.get("content") for t in turns
                      if t.get("role") == "user" and t.get("content")), "")
        title = " ".join(str(first).split())[:80]
    blob = json.dumps(turns, default=str)
    draft_blob = json.dumps(_clean_draft(draft)) if draft is not None else None
    now = _now()
    with db.connect(dsn) as conn:
        row = conn.execute(
            "UPDATE assistant_projects SET turns_json = %s, stage = %s, "
            "draft_json = COALESCE(%s, draft_json), "
            "title = CASE WHEN title = '' THEN %s ELSE title END, updated_at = %s "
            "WHERE account_id = %s AND archived_at IS NULL "
            f"RETURNING {_PROJECT_COLS}",
            (blob, stage, draft_blob, title, now, account_id)).fetchone()
        if row is None:
            row = conn.execute(
                "INSERT INTO assistant_projects "
                "(account_id, title, stage, turns_json, draft_json, created_at, updated_at) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s) "
                f"RETURNING {_PROJECT_COLS}",
                (account_id, title, stage, blob, draft_blob or "{}", now, now)).fetchone()
    return _project(row)


def _said_anything(turns_json: str) -> bool:
    try:
        turns = json.loads(turns_json or "[]")
    except ValueError:
        return False
    return any(isinstance(t, dict) and t.get("role") == "user"
               and str(t.get("content") or "").strip() for t in turns)


def _park_open(conn, account_id: int) -> None:
    """Put the open chat aside: kept (archived_at set) when the person said
    anything in it, deleted when they did not."""
    row = conn.execute(
        "SELECT id, turns_json FROM assistant_projects "
        "WHERE account_id = %s AND archived_at IS NULL", (account_id,)).fetchone()
    if row is None:
        return
    if _said_anything(row["turns_json"]):
        conn.execute("UPDATE assistant_projects SET archived_at = %s "
                     "WHERE id = %s AND account_id = %s", (_now(), row["id"], account_id))
    else:
        conn.execute("DELETE FROM assistant_projects WHERE id = %s AND account_id = %s",
                     (row["id"], account_id))


def clear_project(*, account_id: int, forget: bool = False,
                  dsn: Optional[str] = None) -> None:
    """Start a new session: the open chat is put aside, kept in the history
    drawer (2026-11-03), and the next save starts a fresh one. `forget`
    deletes it instead -- what `save_as_project` uses, because that
    conversation has just been filed into the project's own history."""
    with db.connect(dsn) as conn:
        if forget:
            conn.execute("DELETE FROM assistant_projects "
                         "WHERE account_id = %s AND archived_at IS NULL", (account_id,))
        else:
            _park_open(conn, account_id)


# --- the history drawer (2026-11-03) -------------------------------------------

def _cutoff() -> str:
    """The updated_at a project-less chat must be newer than to be kept.
    updated_at is an ISO text in UTC written by _now(), so it orders as text."""
    return (datetime.now(timezone.utc) - timedelta(days=CHAT_KEEP_DAYS)).isoformat()


# A chat is on its own when it names no project, or names one that is gone
# (a deleted project, or one that is not this account's). A database with no
# projects table yet (a bare test schema) has only chats on their own.
_NO_PROJECT = ("(c.project_id IS NULL OR NOT EXISTS (SELECT 1 FROM projects p "
               "WHERE p.id = c.project_id AND p.account_id IS NOT DISTINCT FROM c.account_id))")


def _no_project(conn) -> str:
    has = conn.execute("SELECT to_regclass('projects') IS NOT NULL "
                       "AND to_regclass('project_messages') IS NOT NULL AS ok").fetchone()["ok"]
    return _NO_PROJECT if has else "TRUE"


def expire_chats(*, account_id: Optional[int] = None, dsn: Optional[str] = None) -> int:
    """Delete every chat outside a project last used more than
    CHAT_KEEP_DAYS ago -- the account's, or everyone's on a start. Returns
    how many went. Never raises: a failed sweep is tried again next time."""
    try:
        with db.connect(dsn) as conn:
            # one account's, or (account_id None, the start's sweep) everyone's
            return int(conn.execute(
                "DELETE FROM assistant_projects c WHERE c.updated_at < %s "
                "AND c.account_id = COALESCE(%s, c.account_id) AND " + _no_project(conn),
                (_cutoff(), account_id)).rowcount or 0)
    except Exception as exc:                       # pragma: no cover - never fails a page
        import sys
        print(f"  chats not expired: {exc}", file=sys.stderr)
        return 0


def _days_left(updated_at: str) -> Optional[int]:
    try:
        last = datetime.fromisoformat(str(updated_at))
    except ValueError:
        return None
    if last.tzinfo is None:
        last = last.replace(tzinfo=timezone.utc)
    left = last + timedelta(days=CHAT_KEEP_DAYS) - datetime.now(timezone.utc)
    return max(0, -(-int(left.total_seconds()) // 86400))      # whole days, rounded up


def list_chats(*, account_id: int, dsn: Optional[str] = None) -> dict[str, Any]:
    """The history drawer: every kept chat, newest first, and the projects
    that have any talk in them.

    - `chats`: {id, title, project_id (None when on its own), updated_at,
      open, turns, days_left} -- `days_left` only for a chat outside a
      project, the whole days until it is deleted; the drawer shows it in
      the last week only.
    - `projects`: {id, title, updated_at, messages} for each live project
      with chats or with history on its own workspace (`project_messages`),
      newest first; `messages` counts the workspace's turns.
    """
    expire_chats(account_id=account_id, dsn=dsn)
    with db.connect(dsn) as conn:
        alone = _no_project(conn)
        rows = conn.execute(
            "SELECT c.id, c.title, c.turns_json, c.updated_at, c.archived_at, "
            f"CASE WHEN {alone} THEN NULL ELSE c.project_id END AS project_id "
            "FROM assistant_projects c WHERE c.account_id = %s "
            "ORDER BY c.updated_at DESC LIMIT %s",
            (account_id, CHAT_LIST_MAX)).fetchall()
        projects = [] if alone == "TRUE" else conn.execute(
            "SELECT p.id, p.title, p.updated_at, "
            "(SELECT COUNT(*) FROM project_messages m WHERE m.project_id = p.id "
            " AND m.account_id IS NOT DISTINCT FROM p.account_id) AS messages "
            "FROM projects p WHERE p.account_id = %s AND p.archived_at IS NULL "
            "AND (EXISTS (SELECT 1 FROM project_messages m WHERE m.project_id = p.id "
            "             AND m.account_id IS NOT DISTINCT FROM p.account_id) "
            "     OR p.id IN (SELECT project_id FROM assistant_projects "
            "                 WHERE account_id = %s AND project_id IS NOT NULL)) "
            "ORDER BY p.updated_at DESC LIMIT %s",
            (account_id, account_id, CHAT_LIST_MAX)).fetchall()
    chats = []
    for r in rows:
        try:
            turns = json.loads(r["turns_json"] or "[]")
        except ValueError:
            turns = []
        said = [t for t in turns if isinstance(t, dict) and t.get("role") == "user"
                and str(t.get("content") or "").strip()]
        is_open = r["archived_at"] is None
        if is_open and not said:
            continue                      # an empty open chat is not history yet
        pid = int(r["project_id"]) if r["project_id"] is not None else None
        chats.append({"id": int(r["id"]),
                      "title": r["title"] or "Untitled chat",
                      "project_id": pid,
                      "updated_at": r["updated_at"],
                      "open": is_open,
                      "turns": len(turns),
                      "days_left": None if pid else _days_left(r["updated_at"])})
    return {"chats": chats,
            "projects": [{"id": int(p["id"]), "title": p["title"],
                          "updated_at": p["updated_at"].isoformat()
                          if isinstance(p["updated_at"], datetime) else p["updated_at"],
                          "messages": int(p["messages"])} for p in projects],
            "keep_days": CHAT_KEEP_DAYS}


def open_chat(chat_id: int, *, account_id: int, dsn: Optional[str] = None) -> Optional[dict]:
    """Make a kept chat the open one: the chat open now is put aside (kept
    if anything was said in it) and the chosen one comes back, its keep
    date restarted. None when there is no such chat for this account."""
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT id, archived_at FROM assistant_projects WHERE id = %s AND account_id = %s",
            (chat_id, account_id)).fetchone()
        if row is None:
            return None
        if row["archived_at"] is not None:
            _park_open(conn, account_id)
        conn.execute(
            "UPDATE assistant_projects SET archived_at = NULL, updated_at = %s "
            "WHERE id = %s AND account_id = %s", (_now(), chat_id, account_id))
        got = conn.execute(
            f"SELECT {_PROJECT_COLS} FROM assistant_projects WHERE id = %s AND account_id = %s",
            (chat_id, account_id)).fetchone()
    return _project(got) if got else None


def delete_chat(chat_id: int, *, account_id: int, dsn: Optional[str] = None) -> bool:
    """Delete one kept chat for good (the drawer's ×). True if it went."""
    with db.connect(dsn) as conn:
        n = conn.execute("DELETE FROM assistant_projects WHERE id = %s AND account_id = %s",
                         (chat_id, account_id)).rowcount
    return bool(n)


def tag_project(project_id: int, *, account_id: int, dsn: Optional[str] = None) -> None:
    """A Create turn ran inside this project: the open chat is the
    project's from now on, kept for as long as the project is. Opens an
    empty chat to carry the tag when none is open yet (the page saves the
    turn into it right after). Only one of the account's own projects is
    taken. Never raises: filing is bookkeeping on top of a turn."""
    try:
        with db.connect(dsn) as conn:
            if _no_project(conn) == "TRUE":
                return
            owned = conn.execute(
                "SELECT 1 FROM projects WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
                (project_id, account_id)).fetchone()
            if not owned:
                return
            n = conn.execute(
                "UPDATE assistant_projects SET project_id = %s "
                "WHERE account_id = %s AND archived_at IS NULL",
                (project_id, account_id)).rowcount
            if not n:
                now = _now()
                conn.execute(
                    "INSERT INTO assistant_projects (account_id, project_id, created_at, updated_at) "
                    "VALUES (%s, %s, %s, %s) ON CONFLICT DO NOTHING",
                    (account_id, project_id, now, now))
    except Exception as exc:                       # pragma: no cover - never fails a turn
        import sys
        print(f"  chat not filed under project {project_id}: {exc}", file=sys.stderr)


# --- keep / reject against the checker -------------------------------------

def record_verdicts(frames, *, account_id: int, project_id: Optional[int] = None,
                    dsn: Optional[str] = None) -> int:
    """One row per frame the person saw on a contact sheet when they pressed
    Keep: what refcheck decided (`checker_kept`, `why`) and what they did
    (`person_kept`). Only ids a hunt actually served are recorded
    (imagesearch.get), the same fabrication rule keep_references applies.
    Returns how many rows were written."""
    from .imagesearch import get
    rows = []
    for f in list(frames or [])[:200]:
        if not isinstance(f, dict):
            continue
        cid = str(f.get("id") or "").strip()
        if not cid or (get(cid, dsn=dsn) if dsn is not None else get(cid)) is None:
            continue
        rows.append((account_id, project_id, cid,
                     str(f.get("role") or "")[:40], str(f.get("query") or "")[:200],
                     bool(f.get("checker_kept")), str(f.get("why") or "")[:300],
                     bool(f.get("person_kept")), str(f.get("source_url") or "")[:500],
                     _now()))
    if not rows:
        return 0
    with db.connect(dsn) as conn:
        with conn.cursor() as cur:
            cur.executemany(
                "INSERT INTO reference_verdicts (account_id, project_id, candidate_id, role, "
                "query, checker_kept, checker_why, person_kept, source_url, created_at) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)", rows)
    return len(rows)


def agreement(*, account_id: int, dsn: Optional[str] = None) -> dict[str, Any]:
    """How often the person's Keep matched the checker's call.
    `kept_anyway` is a frame the checker cut and the person kept (the
    checker too strict); `left_out` is one it kept and the person dropped
    (too lenient). `rate` is None until there is anything to divide."""
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT COUNT(*) AS n, "
            "COUNT(*) FILTER (WHERE checker_kept = person_kept) AS agree, "
            "COUNT(*) FILTER (WHERE NOT checker_kept AND person_kept) AS kept_anyway, "
            "COUNT(*) FILTER (WHERE checker_kept AND NOT person_kept) AS left_out "
            "FROM reference_verdicts WHERE account_id = %s", (account_id,)).fetchone()
    n = int(row["n"])
    return {"n": n, "agree": int(row["agree"]), "kept_anyway": int(row["kept_anyway"]),
            "left_out": int(row["left_out"]),
            "rate": round(int(row["agree"]) / n, 3) if n else None}
