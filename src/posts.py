"""
A post: one clip or still, going to one connected account, at one time
(2026-10-22, docs/tasks/task-publish-worker.md). The Postiz `Post` row,
in this repo's shape, and the thing the calendar will draw.

WHAT A ROW IS. `connection_id` names the social_connections row it posts
through (so the provider, the account and the token all follow from it),
`source_ref` is the studio output it carries -- `gen:<id>`, a render on
the Library, or `asset:<id>`, an import -- with what the worker needs to
hand the platform written down in `media_json` at creation (kind, the
stored URL, the local path, seconds), `caption` is the words, and
`settings_json` is whatever the provider's own form asked (nothing yet
for Discord and Instagram beyond the caption). `publish_at` is when; a
post with no time is now. `group_id` ties the copies of one campaign post
across channels together so an edit or a delete can take them as one.

THE STATES, and who moves a row between them:

    draft       -> queued      the person (schedule)
    queued      -> publishing  the worker (claim, FOR UPDATE SKIP LOCKED)
    publishing  -> published   the worker, with release_id + release_url
    publishing  -> error       the worker: the platform said no, the
                               connection needs reconnecting, or retries
                               ran out (`error` says which, in plain words)
    error       -> queued      the person (post again)
    queued|draft -> cancelled  the person
    publishing  -> (nothing)   a row being sent cannot be moved or cancelled

A row in `publishing` with `pending_json` is one the platform took and is
still processing (an Instagram container, later a TikTok publish_id); the
worker polls it on its own schedule (`next_attempt_at`). `locked_by` /
`locked_at` say which worker holds it, so a worker that died leaves a
row the next tick can see is stuck rather than one that silently never
posts.

WHAT IS NEVER DONE HERE: sending. `src/publish_worker.py` is the only
caller of a provider's post_* functions. This module writes intentions
and reads them back; a request creates a row and the clock does the rest.

OWNED (db.OWNED_TABLES): a post is one account's; so is its event log.
"""
from __future__ import annotations

import json
import re
import threading
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

from . import db, social, social_connections

SCHEMA = """
CREATE TABLE IF NOT EXISTS posts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT NOT NULL,
    connection_id   BIGINT NOT NULL,
    provider        TEXT   NOT NULL,
    group_id        TEXT   NOT NULL,
    publish_at      TIMESTAMPTZ NOT NULL,
    state           TEXT   NOT NULL DEFAULT 'queued',
    caption         TEXT   NOT NULL DEFAULT '',
    source_ref      TEXT   NOT NULL,
    media_json      TEXT   NOT NULL DEFAULT '{}',
    settings_json   TEXT   NOT NULL DEFAULT '{}',
    concept_id      BIGINT,
    project_id      BIGINT,
    release_id      TEXT,
    release_url     TEXT,
    error           TEXT,
    creation_method TEXT   NOT NULL DEFAULT 'web',
    created_by      TEXT,
    attempts        INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    locked_by       TEXT,
    locked_at       TIMESTAMPTZ,
    pending_json    TEXT,
    published_at    TIMESTAMPTZ,
    video_id        BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS post_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL,
    post_id     BIGINT NOT NULL,
    at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    event       TEXT   NOT NULL,
    detail      TEXT   NOT NULL DEFAULT ''
);
"""

INDEXES = """
CREATE INDEX IF NOT EXISTS idx_posts_due ON posts (state, publish_at) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_posts_account ON posts (account_id, publish_at);
CREATE INDEX IF NOT EXISTS idx_posts_group ON posts (group_id);
CREATE INDEX IF NOT EXISTS idx_post_events_post ON post_events (post_id, id);
"""

STATES = ("draft", "queued", "publishing", "published", "error", "cancelled")
CREATION_METHODS = ("web", "mcp", "api", "autopilot")
CAPTION_MAX = 5000
# a worker that has held a row this long without a pending step is dead
STUCK_SECONDS = 15 * 60

_ready: set[str] = set()
_ready_lock = threading.Lock()


class PostRefused(Exception):
    """Said to the person, in plain words."""


