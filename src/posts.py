def _now() -> datetime:
    return datetime.now(timezone.utc)


def _parse_when(value: Any) -> datetime:
    """An ISO timestamp (with or without a zone; naive reads as UTC), a
    datetime, or nothing for now."""
    if value is None or value == "" or value == "now":
        return _now()
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    text = str(value).strip().replace("Z", "+00:00")
    try:
        when = datetime.fromisoformat(text)
    except ValueError:
        raise PostRefused(f"{value!r} is not a time (use ISO 8601, e.g. 2026-10-23T14:00:00Z)")
    return when if when.tzinfo else when.replace(tzinfo=timezone.utc)


def _json(text: Optional[str]) -> dict[str, Any]:
    try:
        out = json.loads(text or "{}")
    except (TypeError, ValueError):
        return {}
    return out if isinstance(out, dict) else {}


def _iso(value: Any) -> Optional[str]:
    return value.isoformat() if isinstance(value, datetime) else None


def public(row: dict) -> dict[str, Any]:
    """What a page or a tool sees. No token rides here (there is none)."""
    mod = social.get(row["provider"])
    media = _json(row.get("media_json"))
    return {
        "id": int(row["id"]),
        "connection_id": int(row["connection_id"]),
        "provider": row["provider"],
        "provider_name": mod.NAME if mod is not None else row["provider"],
        "group_id": row["group_id"],
        "publish_at": _iso(row["publish_at"]),
        "state": row["state"],
        "caption": row.get("caption") or "",
        "source_ref": row["source_ref"],
        "media": {k: media.get(k) for k in ("ref", "media_url", "kind", "seconds") if k in media},
        "settings": _json(row.get("settings_json")),
        "concept_id": row.get("concept_id"),
        "project_id": row.get("project_id"),
        "release_id": row.get("release_id"),
        "release_url": row.get("release_url"),
        "error": row.get("error"),
        "creation_method": row.get("creation_method") or "web",
        "attempts": int(row.get("attempts") or 0),
        "pending": bool(row.get("pending_json")),
        "published_at": _iso(row.get("published_at")),
        "video_id": row.get("video_id"),
        "created_at": _iso(row.get("created_at")),
        "updated_at": _iso(row.get("updated_at")),
    }


def create(account_id: int, *, connection_id: int, source_ref: str, caption: str = "",
           publish_at: Any = None, settings: Optional[dict] = None, draft: bool = False,
           project_id: Optional[int] = None, group_id: Optional[str] = None,
           creation_method: str = "web", created_by: Optional[str] = None,
           dsn: Optional[str] = None) -> dict[str, Any]:
    """Write an intention down. Refuses, in plain words, a connection that
    is not this account's or not finished, a source this account does not
    own, a caption past the platform's limit, and a kind of media the
    platform cannot take -- every check the worker would otherwise fail
    on at 3am, run now, while a person is watching."""
    ensure(dsn)
    conn = social_connections.get(account_id, int(connection_id), dsn=dsn)
    if conn is None:
        raise PostRefused("That account is not connected to this workspace.")
    if conn["status"] == "pending":
        raise PostRefused(f"Finish connecting {conn['provider_name']} first.")
    mod = social.get(conn["provider"])
    if mod is None or not hasattr(mod, "post_start"):
        raise PostRefused(f"Posting to {conn['provider_name']} is not built yet.")
    source = resolve_source(source_ref, account_id, dsn)
    words = (caption or "").strip()
    limit = min(CAPTION_MAX, int(getattr(mod, "CAPTION_MAX", CAPTION_MAX)))
    if len(words) > limit:
        raise PostRefused(f"{mod.NAME} takes a caption of at most {limit} characters "
                          f"(this one is {len(words)}).")
    settings = dict(settings or {})
    if hasattr(mod, "check_post"):
        problem = mod.check_post(source, words, settings)
        if problem:
            raise PostRefused(problem)
    when = _parse_when(publish_at)
    if creation_method not in CREATION_METHODS:
        creation_method = "api"
    with db.connect(dsn) as conn_:
        row = conn_.execute(
            "INSERT INTO posts (account_id, connection_id, provider, group_id, publish_at, state, "
            "caption, source_ref, media_json, settings_json, concept_id, project_id, "
            "creation_method, created_by) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) "
            "RETURNING id",
            (account_id, conn["id"], conn["provider"], group_id or uuid.uuid4().hex[:12], when,
             "draft" if draft else "queued", words, source["ref"], json.dumps(source),
             json.dumps(settings), source.get("concept_id"), project_id, creation_method,
             created_by)).fetchone()
    post_id = int(row["id"])
    note(account_id, post_id, "created", f"{'draft' if draft else 'queued'} for {when.isoformat()}", dsn=dsn)
    got = get(account_id, post_id, dsn=dsn)
    assert got is not None
    return got


def create_group(account_id: int, *, connection_ids: list[int], source_ref: str, caption: str = "",
                 publish_at: Any = None, settings: Optional[dict] = None, draft: bool = False,
                 project_id: Optional[int] = None, creation_method: str = "web",
                 created_by: Optional[str] = None, captions: Optional[dict[int, str]] = None,
                 dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """One clip to several accounts at one press (2026-10-22, the
    calendar's drawer): one row per connection, one group_id. Every row's
    checks run BEFORE any row is written, so a press that would be refused
    on the third account writes nothing for the first two. `captions`
    overrides the words for one connection (a per-account tab)."""
    ensure(dsn)
    ids: list[int] = []
    for cid in connection_ids or []:
        try:
            n = int(cid)
        except (TypeError, ValueError):
            raise PostRefused(f"{cid!r} is not a connection id.")
        if n not in ids:
            ids.append(n)
    if not ids:
        raise PostRefused("Pick at least one account.")
    captions = captions or {}
    # the dry run: every check create() would make, with no insert
    for cid in ids:
        conn = social_connections.get(account_id, cid, dsn=dsn)
        if conn is None:
            raise PostRefused("That account is not connected to this workspace.")
        if conn["status"] == "pending":
            raise PostRefused(f"Finish connecting {conn['provider_name']} first.")
        mod = social.get(conn["provider"])
        if mod is None or not hasattr(mod, "post_start"):
            raise PostRefused(f"Posting to {conn['provider_name']} is not built yet.")
        source = resolve_source(source_ref, account_id, dsn)
        words = (captions.get(cid) if captions.get(cid) is not None else caption or "").strip()
        limit = min(CAPTION_MAX, int(getattr(mod, "CAPTION_MAX", CAPTION_MAX)))
        if len(words) > limit:
            raise PostRefused(f"{mod.NAME} takes a caption of at most {limit} characters "
                              f"(this one is {len(words)}).")
        if hasattr(mod, "check_post"):
            problem = mod.check_post(source, words, dict(settings or {}))
            if problem:
                raise PostRefused(f"{mod.NAME}: {problem}")
    group = uuid.uuid4().hex[:12]
    out = []
    for cid in ids:
        words = captions.get(cid) if captions.get(cid) is not None else caption
        out.append(create(account_id, connection_id=cid, source_ref=source_ref, caption=words or "",
                          publish_at=publish_at, settings=settings, draft=draft,
                          project_id=project_id, group_id=group, creation_method=creation_method,
                          created_by=created_by, dsn=dsn))
    return out


def _row(account_id: int, post_id: int, dsn: Optional[str]) -> Optional[dict]:
    with db.connect(dsn) as conn:
        return conn.execute(
            "SELECT * FROM posts WHERE id = %s AND account_id = %s AND deleted_at IS NULL",
            (post_id, account_id)).fetchone()


def get(account_id: int, post_id: int, *, dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    ensure(dsn)
    row = _row(account_id, post_id, dsn)
    return public(row) if row else None


def list_for(account_id: int, *, start: Any = None, end: Any = None,
             state: Optional[str] = None, limit: int = 500,
             dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """The calendar's read: this account's posts whose publish_at is in
    [start, end), newest-scheduled last; `state` narrows."""
    ensure(dsn)
    clauses = ["deleted_at IS NULL"]
    args: list[Any] = [account_id]
    if start is not None:
        clauses.append("publish_at >= %s")
        args.append(_parse_when(start))
    if end is not None:
        clauses.append("publish_at < %s")
        args.append(_parse_when(end))
    if state:
        if state not in STATES:
            raise PostRefused(f"state must be one of {', '.join(STATES)}")
        clauses.append("state = %s")
        args.append(state)
    args.append(max(1, min(int(limit), 2000)))
    with db.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT * FROM posts WHERE account_id = %s AND "
            f"{' AND '.join(clauses)} ORDER BY publish_at, id LIMIT %s",
            tuple(args)).fetchall()
    return [public(r) for r in rows]


def set_date(account_id: int, post_id: int, publish_at: Any, *,
             dsn: Optional[str] = None) -> dict[str, Any]:
    """Move a post. A row being sent cannot move; a published one is a
    record, not a plan."""
    when = _parse_when(publish_at)
    row = _row(account_id, post_id, dsn)
    if not row:
        raise PostRefused("No such post on this workspace.")
    if row["state"] in ("publishing", "published"):
        raise PostRefused("This post is already being sent." if row["state"] == "publishing"
                          else "This post has gone out; it cannot be moved.")
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE posts SET publish_at = %s, next_attempt_at = NULL, updated_at = now() "
            "WHERE id = %s AND account_id = %s", (when, post_id, account_id))
    note(account_id, post_id, "moved", when.isoformat(), dsn=dsn)
    got = get(account_id, post_id, dsn=dsn)
    assert got is not None
    return got


def set_state(account_id: int, post_id: int, state: str, *,
              dsn: Optional[str] = None) -> dict[str, Any]:
    """The person's moves: queue a draft, post again after an error,
    cancel what has not gone. Never into or out of `publishing`."""
    row = _row(account_id, post_id, dsn)
    if not row:
        raise PostRefused("No such post on this workspace.")
    was = row["state"]
    allowed = {
        "queued": ("draft", "error", "cancelled"),
        "draft": ("queued", "error", "cancelled"),
        "cancelled": ("draft", "queued", "error"),
    }
    if state not in allowed or was not in allowed[state]:
        if was == "publishing":
            raise PostRefused("This post is being sent right now; it cannot be changed.")
        if was == "published":
            raise PostRefused("This post has gone out.")
        raise PostRefused(f"A {was} post cannot become {state}.")
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE posts SET state = %s, error = CASE WHEN %s = 'queued' THEN NULL ELSE error END, "
            "attempts = CASE WHEN %s = 'queued' THEN 0 ELSE attempts END, next_attempt_at = NULL, "
            "updated_at = now() WHERE id = %s AND account_id = %s",
            (state, state, state, post_id, account_id))
    note(account_id, post_id, state, f"was {was}", dsn=dsn)
    got = get(account_id, post_id, dsn=dsn)
    assert got is not None
    return got


def update(account_id: int, post_id: int, *, caption: Optional[str] = None,
           settings: Optional[dict] = None, dsn: Optional[str] = None) -> dict[str, Any]:
    """The words or the provider settings of a post not yet sent."""
    row = _row(account_id, post_id, dsn)
    if not row:
        raise PostRefused("No such post on this workspace.")
    if row["state"] == "publishing":
        raise PostRefused("This post is being sent right now; it cannot be changed.")
    if row["state"] == "published":
        raise PostRefused("This post has gone out; it cannot be edited.")
    mod = social.get(row["provider"])
    words = row["caption"] if caption is None else (caption or "").strip()
    limit = min(CAPTION_MAX, int(getattr(mod, "CAPTION_MAX", CAPTION_MAX)))
    if len(words) > limit:
        raise PostRefused(f"{mod.NAME} takes a caption of at most {limit} characters.")
    merged = _json(row.get("settings_json"))
    if settings:
        merged.update(settings)
    if mod is not None and hasattr(mod, "check_post"):
        problem = mod.check_post(_json(row.get("media_json")), words, merged)
        if problem:
            raise PostRefused(problem)
    with db.connect(dsn) as conn:
        conn.execute(
            "UPDATE posts SET caption = %s, settings_json = %s, updated_at = now() "
            "WHERE id = %s AND account_id = %s",
            (words, json.dumps(merged), post_id, account_id))
    got = get(account_id, post_id, dsn=dsn)
    assert got is not None
    return got


def remove(account_id: int, post_id: int, *, dsn: Optional[str] = None) -> bool:
    """Soft. A post being sent stays until it lands; a published post's
    row is history and stays visible (cancel is not un-posting)."""
    row = _row(account_id, post_id, dsn)
    if not row:
        return False
    if row["state"] == "publishing":
        raise PostRefused("This post is being sent right now; it cannot be deleted.")
    with db.connect(dsn) as conn:
        cur = conn.execute(
            "UPDATE posts SET deleted_at = now(), updated_at = now() "
            "WHERE id = %s AND account_id = %s AND deleted_at IS NULL", (post_id, account_id))
        return cur.rowcount > 0


def note(account_id: int, post_id: int, event: str, detail: str = "", *,
         dsn: Optional[str] = None) -> None:
    """One line of the post's own log. Never raises: the log is not the
    post."""
    try:
        with db.connect(dsn) as conn:
            conn.execute(
                "INSERT INTO post_events (account_id, post_id, event, detail) VALUES (%s, %s, %s, %s)",
                (account_id, post_id, event[:40], (detail or "")[:1000]))
    except Exception:
        pass


