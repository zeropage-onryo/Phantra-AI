def resolve_source(ref: str, account_id: int, dsn: Optional[str] = None) -> dict[str, Any]:
    """gen:<id> (a render on the Library) or asset:<id> (an import) ->
    {ref, media_url, output_path, kind, seconds, ai_generated}. A URL is
    never taken: a post goes out from something this account owns."""
    from . import render_assets
    from .cut import store as cut_store
    kind, _, rest = (ref or "").strip().partition(":")
    if not rest.isdigit() or kind not in ("gen", "asset"):
        raise PostRefused(f"{ref!r}: a post's source is gen:<id> (a render in your Library) "
                          "or asset:<id> (a clip you imported)")
    if kind == "gen":
        row = render_assets.get(int(rest), dsn, account_id=account_id)
        if not row or row.get("deleted_at"):
            raise PostRefused(f"no render {rest} on this account")
        meta = row.get("metadata") or {}
        return {"ref": f"gen:{rest}", "media_url": row.get("media_url") or "",
                "output_path": row.get("output_path") or "",
                "kind": row.get("media_kind") or "", "seconds": _seconds(meta),
                "concept_id": row.get("concept_id") or meta.get("concept_id"),
                "ai_generated": True}
    row = cut_store.get_media(int(rest), account_id=account_id, dsn=dsn)
    if not row:
        raise PostRefused(f"no import {rest} on this account")
    return {"ref": f"asset:{rest}", "media_url": row.get("media_url") or "",
            "output_path": row.get("output_path") or "", "kind": row.get("kind") or "",
            "seconds": row.get("seconds"), "concept_id": None, "ai_generated": False}


def _seconds(meta: dict) -> Optional[float]:
    params = meta.get("params") if isinstance(meta.get("params"), dict) else {}
    for value in (meta.get("seconds"), meta.get("duration"),
                  params.get("seconds"), params.get("duration")):
        match = re.match(r"\s*(\d+(?:\.\d+)?)", str(value)) if value is not None else None
        if match:
            return float(match.group(1))
    return None


