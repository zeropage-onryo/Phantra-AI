"""
A creator's own recipes (2026-10-11, docs/tasks/task-connector-overnight.md
PR 4): `save_recipe`, listed by `recipes` beside the studio's skill shelf
(src/skills.py) and read by `recipe`.

A recipe is text a person wrote about how THEY like a kind of work done.
It is theirs: kept under their account, listed to them, and -- the
important part -- handed back to a chat as QUOTED DATA, never as
instructions the connector vouches for. The studio's shelf (prompts/
skills/*.md) is guidance the studio wrote; a saved recipe is not, and the
tool that returns one says so.

INSERT-ONLY (the task's rule: every edit makes a new item): saving a name
again writes version n+1 and `get` reads the newest; older versions stay.
A name on the studio's shelf cannot be taken. OWNED (db.OWNED_TABLES).
"""
from __future__ import annotations

import re
from typing import Any, Optional

from . import db

SCHEMA = """
CREATE TABLE IF NOT EXISTS mcp_recipes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT,
    user_id     TEXT NOT NULL DEFAULT '',
    name        TEXT NOT NULL,
    title       TEXT NOT NULL DEFAULT '',
    body        TEXT NOT NULL,
    project_id  BIGINT,
    version     INTEGER NOT NULL DEFAULT 1,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""
INDEXES = """
CREATE INDEX IF NOT EXISTS idx_mcp_recipes_name ON mcp_recipes (account_id, name, version DESC);
"""

MAX_BODY = 8000
MAX_TITLE = 80
NAME = re.compile(r"[a-z0-9][a-z0-9-]{0,39}")

_ready: set[str] = set()


def init(dsn: Optional[str] = None) -> None:
    """Create and own the table. Idempotent."""
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "mcp_recipes")
        conn.execute(INDEXES)
    _ready.add(db.resolve_dsn(dsn))


def ensure(dsn: Optional[str] = None) -> None:
    if db.resolve_dsn(dsn) in _ready:
        return
    db.run_init(lambda: init(dsn), dsn)


def clean_name(raw) -> str:
    """A recipe name as it is stored: lowered, hyphenated, `NAME`-shaped;
    "" for anything that is not one."""
    text = str(raw or "").strip().lower()
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"[^a-z0-9-]", "", text).strip("-")
    return text if NAME.fullmatch(text) else ""


def title_of(body: str, name: str) -> str:
    """The first heading or line of the body, else the name."""
    for line in (body or "").splitlines():
        line = line.strip().lstrip("#").strip()
        if line:
            return line[:MAX_TITLE]
    return name


def save(account_id: Optional[int], user_id: Optional[str], name: str, body: str, *,
         project_id: Optional[int] = None, dsn: Optional[str] = None) -> dict[str, Any]:
    """A new version of `name` for this account. The caller has checked
    the name, the length and the project."""
    name = clean_name(name)
    if not name:
        raise ValueError("a recipe name is letters, numbers and hyphens")
    body = (body or "").strip()
    if not body:
        raise ValueError("a recipe needs a body")
    if len(body) > MAX_BODY:
        raise ValueError(f"a recipe is at most {MAX_BODY} characters ({len(body)} given)")
    with db.connect(dsn) as conn:
        last = conn.execute(
            "SELECT COALESCE(MAX(version), 0) AS v FROM mcp_recipes "
            "WHERE account_id IS NOT DISTINCT FROM %s AND name = %s",
            (account_id, name)).fetchone()["v"]
        row = conn.execute(
            "INSERT INTO mcp_recipes (account_id, user_id, name, title, body, project_id, version) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING id, version, created_at",
            (account_id, str(user_id or ""), name, title_of(body, name), body,
             int(project_id) if project_id is not None else None, int(last) + 1)).fetchone()
    return {"id": int(row["id"]), "name": name, "version": int(row["version"]),
            "created_at": row["created_at"]}


def get(account_id: Optional[int], name: str, *, version: Optional[int] = None,
        dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    """The newest version of `name` (or `version`), or None."""
    name = clean_name(name)
    if not name:
        return None
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "mcp_recipes"):
            return None
        if version is None:
            row = conn.execute(
                "SELECT * FROM mcp_recipes WHERE account_id IS NOT DISTINCT FROM %s "
                "AND name = %s ORDER BY version DESC LIMIT 1", (account_id, name)).fetchone()
        else:
            row = conn.execute(
                "SELECT * FROM mcp_recipes WHERE account_id IS NOT DISTINCT FROM %s "
                "AND name = %s AND version = %s", (account_id, name, int(version))).fetchone()
    return dict(row) if row else None


def names(account_id: Optional[int], dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """Every recipe name this account saved, with how many versions and
    the newest one's title, project and time; newest first."""
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "mcp_recipes"):
            return []
        rows = conn.execute(
            "SELECT DISTINCT ON (name) name, title, project_id, version, created_at, "
            "COUNT(*) OVER (PARTITION BY name) AS versions "
            "FROM mcp_recipes WHERE account_id IS NOT DISTINCT FROM %s "
            "ORDER BY name, version DESC", (account_id,)).fetchall()
    out = [{"name": r["name"], "title": r["title"], "project_id": r["project_id"],
            "version": int(r["version"]), "versions": int(r["versions"]),
            "updated_at": r["created_at"]} for r in rows]
    out.sort(key=lambda r: str(r["updated_at"]), reverse=True)
    return out


__all__ = ["MAX_BODY", "NAME", "init", "ensure", "clean_name", "title_of", "save", "get",
           "names"]
