"""Paid add-ons on top of a plan (2026-10-26, Mike: "studios are a priced
tier ... it's a flat add-on").

A plan buys credits (src/pricing.py PLANS, `accounts.plan`); an add-on buys
a WAY OF WORKING and no credits at all -- today one, `studios`, which opens
the Ad Studio (src/studios.py). It is its own Stripe subscription beside the
plan's, so it is recorded in its own OWNED table and never in
`accounts.plan`: one column with two meanings is how a cancelled add-on
would have cleared somebody's plan (billing.handle_event routes an add-on's
events here BEFORE any plan branch; see `billing._addon_of`).

What a row is: one account's one add-on, its status and where it came from
-- `stripe` (a subscription; the webhook keeps it current) or `grant` (the
operator's `python -m src.accounts studios <slug> --on`, the way into a
studio before its Stripe Price exists, and for Mike's own workspace). A
revoke never deletes the row: it is the record of what was paid for.

`active()` is the ONE reader. It never raises (a read error is "not
active" -- the paid gate fails closed -- and the page shows the upgrade
card instead of breaking), and `PHANTRA_STUDIOS_GATE=0` opens every studio
to every account, for an installation with no add-on to sell.
"""
from __future__ import annotations

import os
import threading
from datetime import datetime, timezone
from typing import Optional

from . import db

# the add-ons there are; a key here is also the Stripe item key
# (pricing.ADDONS) and what billing's checkout metadata names
KNOWN = ("studios",)
SOURCES = ("stripe", "grant")
ACTIVE = "active"
REVOKED = "revoked"
GATE_ENV = "PHANTRA_STUDIOS_GATE"

SCHEMA = """
CREATE TABLE IF NOT EXISTS account_addons (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    addon                  TEXT NOT NULL,
    status                 TEXT NOT NULL,
    source                 TEXT NOT NULL,
    stripe_subscription_id TEXT,
    current_period_end     TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""
INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS account_addons_one_idx ON account_addons (account_id, addon);
"""

_ready: set[str] = set()
_ready_lock = threading.Lock()


def init(dsn: Optional[str] = None) -> None:
    """Create the table and own it. Idempotent; registered in app/main.py's
    lifespan and tests/test_tenancy.py::_init_everything."""
    key = db.resolve_dsn(dsn)
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "account_addons")
        conn.execute(INDEXES)
    _ready.add(key)


def ensure(dsn: Optional[str] = None) -> None:
    """Once per process and database, through db.run_init (never an init
    per request: two at once deadlock)."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)


def gate_on() -> bool:
    """False only when the installation opened the studios to everyone."""
    return (os.environ.get(GATE_ENV) or "1").strip().lower() not in ("0", "false", "off", "no")


def _clean(addon: str) -> str:
    addon = (addon or "").strip().lower()
    if addon not in KNOWN:
        raise ValueError(f"no add-on {addon!r} -- the add-ons are {', '.join(KNOWN)}")
    return addon


def row(account_id: Optional[int], addon: str, dsn: Optional[str] = None) -> Optional[dict]:
    """This account's row for the add-on, or None. Never raises."""
    if account_id is None:
        return None
    try:
        addon = _clean(addon)
        ensure(dsn)
        with db.connect(dsn) as conn:
            found = conn.execute(
                "SELECT addon, status, source, stripe_subscription_id, current_period_end, "
                "updated_at FROM account_addons WHERE account_id = %s AND addon = %s",
                (int(account_id), addon)).fetchone()
    except Exception:
        return None
    return dict(found) if found else None


def active(account_id: Optional[int], addon: str = "studios", dsn: Optional[str] = None) -> bool:
    """Whether this account may use the add-on. The one reader."""
    if not gate_on():
        return True
    found = row(account_id, addon, dsn)
    return bool(found and found.get("status") == ACTIVE)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def set_status(account_id: int, addon: str, status: str, *, source: str,
               subscription: Optional[str] = None, period_end: Optional[str] = None,
               dsn: Optional[str] = None) -> dict:
    """Insert or update the one row. Raises like every billing write (the
    webhook answers 500 and Stripe retries)."""
    addon = _clean(addon)
    if status not in (ACTIVE, REVOKED):
        raise ValueError(f"status must be {ACTIVE} or {REVOKED}")
    if source not in SOURCES:
        raise ValueError(f"source must be one of {SOURCES}")
    ensure(dsn)
    with db.connect(dsn) as conn:
        conn.execute(
            "INSERT INTO account_addons (account_id, addon, status, source, "
            "stripe_subscription_id, current_period_end) VALUES (%s, %s, %s, %s, %s, %s) "
            "ON CONFLICT (account_id, addon) DO UPDATE SET status = EXCLUDED.status, "
            "source = EXCLUDED.source, "
            "stripe_subscription_id = COALESCE(EXCLUDED.stripe_subscription_id, "
            "account_addons.stripe_subscription_id), "
            "current_period_end = COALESCE(EXCLUDED.current_period_end, "
            "account_addons.current_period_end), updated_at = now()",
            (int(account_id), addon, status, source, subscription, period_end))
    return {"account_id": int(account_id), "addon": addon, "status": status, "source": source}


def grant(slug: str, addon: str, on: bool, dsn: Optional[str] = None) -> dict:
    """The operator's switch (`python -m src.accounts studios <slug> --on`):
    set_credit_exempt's shape -- reports the BEFORE, idempotent, an unknown
    slug is an error. Turning a Stripe-paid add-on off by hand is refused:
    the customer is paying for it, so it is cancelled in Stripe, whose
    webhook then revokes it here."""
    from . import accounts
    accounts.init(dsn)
    addon = _clean(addon)
    slug = (slug or "").strip().lower()
    if not slug:
        raise ValueError("which account? -- pass the slug, e.g. phantra")
    with db.connect(dsn) as conn:
        found = conn.execute("SELECT id FROM accounts WHERE slug = %s", (slug,)).fetchone()
        if found is None:
            known = [r["slug"] for r in conn.execute("SELECT slug FROM accounts ORDER BY slug")]
            raise ValueError(f"no account {slug!r}" + (f" -- try one of {known}" if known else ""))
    account_id = int(found["id"])
    before = row(account_id, addon, dsn)
    was = bool(before and before.get("status") == ACTIVE)
    if not on and before and before.get("source") == "stripe" and was:
        raise ValueError(f"{slug!r} pays for {addon} through Stripe -- cancel the "
                         "subscription there and the webhook revokes it")
    if was != bool(on):
        set_status(account_id, addon, ACTIVE if on else REVOKED, source="grant", dsn=dsn)
    return {"slug": slug, "account_id": account_id, "addon": addon,
            "was": was, "now": bool(on), "changed": was != bool(on)}


def period_end_of(obj: dict) -> Optional[str]:
    """A subscription's or invoice line's period end as an ISO time, or None."""
    raw = obj.get("current_period_end")
    if raw is None:
        lines = ((obj.get("lines") or {}).get("data") or [{}])
        raw = ((lines[0] if lines else {}).get("period") or {}).get("end")
    try:
        return datetime.fromtimestamp(int(raw), timezone.utc).isoformat(timespec="seconds")
    except (TypeError, ValueError, OverflowError, OSError):
        return None
