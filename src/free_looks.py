def source_file(ref: str, *, account_id: Optional[int], dsn: Optional[str],
                workdir: Path) -> Path:
    """The clip behind a `gen:<id>` / `asset:<id>` of this account's, on
    this disk (downloaded into `workdir` when only the bucket has it) --
    the editor's own reader (src/cut/sources.py)."""
    from .cut import sources
    try:
        return sources.resolve(ref, account_id=account_id, workdir=workdir, dsn=dsn)
    except sources.SourceError as e:
        raise ValueError(str(e)) from e


def sound_pass_card(ref: str, facts: dict, *, account_id: Optional[int],
                    dsn: Optional[str]) -> dict:
    """The Sound Pass SLOT of Make It Pro: a priced add-sound card on the
    clip just made, exactly what the composer's card and
    POST /api/effects/quote would show. Nothing runs here."""
    from . import effects, ledger
    name = LOOKS["make_it_pro"]["sound_pass"]
    usd = effects.quote_usd(name, effects.check_options(name, {}), facts)
    try:
        charged = not ledger.credit_exempt(account_id, dsn)
    except Exception:                                   # noqa: BLE001
        charged = True
    return {"effect": name, "label": "Sound Pass", "sources": [ref],
            "prompt": SOUND_PASS_PROMPT, "options": {},
            "credits": ledger.charge_credits(usd), "charged": charged,
            "clip": {k: facts[k] for k in ("seconds", "width", "height")},
            "note": "runs only after its own Approve"}


def run_effect(effect: str, options: dict, *, sources: list[str],
               account_id: Optional[int], dsn: Optional[str] = None,
               source: str = "composer", project_id: Optional[int] = None,
               publish: Optional[Callable] = None, extra: Optional[dict] = None,
               end_card: bool = True, source_path=None) -> dict[str, Any]:
    """A free look through the effects door: the shape of effects.run's
    result ({ok, media_url, generation_id, asset_id, path, media_kind,
    error} plus credits 0, the timing and, for Make It Pro, `next`: the
    Sound Pass card). No key, no cap, no hold, no provider. Raises on a
    bad request or a failed ffmpeg; effects.run turns that into a result."""
    from . import generative, render_assets
    from . import media as media_mod
    from .shot import Shot
    effect = (effect or "").strip()
    row = LOOKS[effect]
    kwargs = {"dsn": dsn} if dsn is not None else {}
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    from . import render_names
    name = render_names.unguessable(f"look-{effect}-{stamp}") + ".mp4"
    out_path = RENDER_DIR / name
    with tempfile.TemporaryDirectory(prefix="phantra-looks-") as tmp:
        tmp = Path(tmp)
        src = Path(source_path) if source_path else source_file(
            sources[0], account_id=account_id, dsn=dsn, workdir=tmp)
        facts = probe(src)
        graded = tmp / "graded.mp4"
        made = apply(effect, src, graded if end_card else out_path, options, facts=facts)
        card = None
        if end_card:
            card = append_end_card(graded, out_path)
    timing = {"look": made["timing"], **({"end_card": card["timing"]} if card else {})}
    params = {"provider": "local", "model": effect, "effect": effect, "look": effect,
              "options": made["params"].get("options", options), "source": source,
              "sources": list(sources or []), "free": True, "credits": 0,
              "graph": made["graph"], "size": list(made["size"]), "timing": timing,
              "end_card": END_CARD_SECONDS if end_card else 0,
              "drawtext": has_drawtext(),
              **({"project_id": int(project_id)} if project_id else {}),
              **(extra or {})}
    text = f"{row['label']} {json.dumps(params['options'], sort_keys=True)}"
    generative.ensure(**kwargs)
    shot_id = generative.add_shot(Shot(subject=row["label"][:100], action=effect),
                                  notes=f"{row['label']}, a free look", dsn=dsn,
                                  account_id=account_id)
    generation_id = generative.record_generation(
        shot_id, LOG_TOOL, text, params=params, output_path=str(out_path), cost_usd=None,
        notes="made locally with ffmpeg -- no provider, no credits",
        dsn=dsn, account_id=account_id)
    stored = f"/renders/looks/{out_path.name}"
    if publish is not None:
        media_url = publish(out_path, "video/mp4", account_id)
    else:
        media_mod.mirror(out_path, f"renders/looks/{out_path.name}", account_id,
                         content_type="video/mp4", derive=False)
        try:                                    # the wall's tile, as fal._publish draws one
            media_mod.mirror_poster(out_path, f"renders/looks/{out_path.name}", account_id)
        except Exception:                       # noqa: BLE001 -- the tile falls back to the clip
            pass
        media_url = media_mod.url_for(stored, account_id)
    asset = render_assets.record_best_effort(
        account_id=account_id, generation_id=generation_id, tool=LOG_TOOL, model=effect,
        media_kind="video", prompt=text, media_url=media_url, output_path=str(out_path),
        metadata=params, dsn=dsn)
    asset_id = asset.get("id")
    ref = f"gen:{asset_id}" if asset_id else None
    result = {"ok": True, "media_url": media_url, "generation_id": generation_id,
              "asset_id": asset_id, "ref": ref, "path": str(out_path), "media_kind": "video",
              "error": None, "credits": 0, "note": FREE_NOTE, "timing": timing,
              "size": list(made["size"]), "next": None}
    if row.get("sound_pass") and ref:
        result["next"] = sound_pass_card(ref, probe(out_path), account_id=account_id, dsn=dsn)
    return result
