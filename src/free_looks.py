def plan(look: str, facts: dict, options: Optional[dict] = None, *,
         workdir: Optional[Path] = None) -> dict:
    """One look on one measured clip -> what ffmpeg will be told: the extra
    inputs, the filter graph, how the sound is handled, and the numbers a
    test can check (the bar height, the crop, the zoom at 0.3s). Pure but
    for the overlays it draws into `workdir` (the date stamp) and the
    assets it makes sure exist."""
    look = (look or "").strip()
    row = LOOKS.get(look)
    if row is None:
        raise ValueError(f"look must be one of {list(LOOK_NAMES)}, got {look!r}")
    opts = {k: (options or {}).get(k, o.get("default")) for k, o in row["options"].items()}
    w, h, fps = int(facts["width"]), int(facts["height"]), float(facts.get("fps") or 30)
    audio = bool(facts.get("audio"))
    assets = ensure_assets()
    inputs: list[list[str]] = []        # each: the args before `-i <path>`, then the path
    params: dict[str, Any] = {"options": opts}

    def film(chain: list[str]) -> None:
        chain += ["format=rgb24", f"lut3d=file={_fq(assets['film_grade.cube'])}:interp=tetrahedral",
                  "format=yuv420p", "noise=c0s=14:c0f=t+u"]

    def vertical(chain: list[str]) -> None:
        cw, ch = vertical_crop(w, h)
        params["crop"] = {"width": cw, "height": ch}
        params["size"] = (cw, ch)
        chain.append(f"crop={cw}:{ch}:(iw-{cw})/2:(ih-{ch})/2")

    v: list[str] = []
    graph_tail = ""
    full_graph: Optional[str] = None            # a look that builds its own whole graph
    where = Path(workdir or tempfile.gettempdir())
    bound = ["-loop", "1", "-t", f"{float(facts['seconds']):.3f}"]   # a looped PNG must END
    amap: Optional[str] = "0:a" if audio else None
    if look in ("film_grade", "make_it_pro"):
        film(v)
        if look == "film_grade" and opts.get("letterbox"):
            bar = letterbox_bar(w, h)
            params["letterbox_bar"] = bar
            params["active"] = {"width": w, "height": h - 2 * bar}
            if bar:
                v += [f"drawbox=x=0:y=0:w=iw:h={bar}:color=black:t=fill",
                      f"drawbox=x=0:y=ih-{bar}:w=iw:h={bar}:color=black:t=fill"]
        if look == "make_it_pro":
            vertical(v)
    elif look == "noir":
        v += ["format=rgb24", f"lut3d=file={_fq(assets['noir.cube'])}:interp=tetrahedral",
              "format=yuv420p", "noise=c0s=12:c0f=t+u", "vignette=angle=PI/4.5",
              "hue=s=0"]                              # chroma to 128 exactly, last
    elif look == "flash_2000s":
        bound = ["-loop", "1", "-t", f"{float(facts['seconds']):.3f}"]   # a looped PNG must END
        inputs.append([*bound, str(assets["flash.png"])])
        v += ["format=rgb24",
              "curves=r='0/0 0.5/0.56 1/1':g='0/0 0.5/0.52 1/1':b='0/0.03 0.5/0.47 1/0.96'",
              "eq=saturation=1.3:contrast=1.1:gamma=0.98",
              "format=yuv420p", "noise=c0s=8:c0f=t+u"]
        graph_tail = (f";[1:v]scale={w}:{h},format=rgba[flash];"
                      f"[g][flash]overlay=0:0:enable='lt(mod(t,{FLASH_PERIOD}),{FLASH_LENGTH})'"
                      f":format=auto:shortest=1[f]")
        params["flash"] = {"period": FLASH_PERIOD, "length": FLASH_LENGTH}
        stamped = bool(opts.get("stamp"))
        params["stamp"] = stamped
        if stamped:
            where = Path(workdir or tempfile.gettempdir())
            stamp = date_stamp_png(w, h, where / f"stamp-{w}x{h}.png")
            inputs.append([*bound, str(stamp)])
            graph_tail += (";[2:v]format=rgba[stamp];[f][stamp]overlay=0:0:format=auto"
                           ":shortest=1[v0]")
        else:
            graph_tail += ";[f]null[v0]"
    elif look == "crash_zoom":
        zoom = float(opts.get("zoom") or 1.35)
        params["zoom"] = zoom
        params["zoom_at_0.3"] = zoom_at(ZOOM_IN_END, zoom)
        params["zoom_at_0"] = zoom_at(0.0, zoom)
        v.append(f"zoompan=z='{_zoom_expr(zoom)}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)'"
                 f":d=1:s={w}x{h}:fps={fps:g}")
        v.append("format=yuv420p")
        inputs.append([str(assets["whoosh.wav"])])
        n = 1                                 # the whoosh is input 1
        if audio:
            graph_tail = (f";[0:a]aformat=sample_rates=48000:channel_layouts=stereo[sa];"
                          f"[{n}:a]aformat=sample_rates=48000:channel_layouts=stereo[wh];"
                          f"[sa][wh]amix=inputs=2:duration=first:dropout_transition=0"
                          f":normalize=0[a]")
        else:
            graph_tail = (f";[{n}:a]aformat=sample_rates=48000:channel_layouts=stereo,"
                          f"apad=whole_dur={float(facts['seconds']):.3f}[a]")
        amap = "[a]"
    elif look == "vertical_ready":
        vertical(v)
        v.append("format=yuv420p")
    elif look == "title_sequence":
        j = max(2, _even(min(w, h) * 0.008))          # the jitter, px each way
        params["jitter"] = j
        v += ["format=rgb24", f"colorchannelmixer={SEPIA}", "eq=contrast=1.25:saturation=0.7",
              f"crop={w - 2 * j}:{h - 2 * j}:x='{j}+{j}*sin(n*7.31)':y='{j}+{j}*cos(n*5.17)'",
              f"scale={w}:{h}", "format=yuv420p", "noise=c0s=26:c0f=t+u",
              "vignette=angle=PI/4"]
        strobe = bool(opts.get("strobe"))
        params["strobe"] = ({"period": STROBE_PERIOD, "length": STROBE_LENGTH}
                            if strobe else None)
        if strobe:
            v.append(f"eq=brightness='if(lt(mod(t,{STROBE_PERIOD}),{STROBE_LENGTH}),0.45,0)'"
                     ":eval=frame")
