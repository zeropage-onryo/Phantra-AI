def frame_bytes(path, t: float, pix_fmt: str = "yuv420p") -> bytes:
    """One decoded frame at `t` seconds, raw, in `pix_fmt`."""
    bin_ = ffmpeg_bin()
    if not bin_:
        raise RuntimeError("ffmpeg is not installed")
    proc = subprocess.run([bin_, "-hide_banner", "-loglevel", "error", "-ss", f"{t:.3f}",
                           "-i", str(path), "-frames:v", "1", "-f", "rawvideo",
                           "-pix_fmt", pix_fmt, "-"],
                          capture_output=True, timeout=120)
    if proc.returncode != 0 or not proc.stdout:
        raise RuntimeError(f"no frame at {t}s: {(proc.stderr or b'')[-200:]!r}")
    return proc.stdout


def frame_yuv(path, t: float) -> tuple[int, int, bytes, bytes, bytes]:
    """(width, height, Y, U, V) of the frame at `t`, yuv420p planes."""
    facts = probe(path)
    w, h = int(facts["width"]), int(facts["height"])
    raw = frame_bytes(path, t, "yuv420p")
    ysz, csz = w * h, (w // 2) * (h // 2)
    return w, h, raw[:ysz], raw[ysz:ysz + csz], raw[ysz + csz:ysz + 2 * csz]


def frame_image(path, t: float):
    """The frame at `t` as a Pillow RGB image."""
    from PIL import Image
    facts = probe(path)
    w, h = int(facts["width"]), int(facts["height"])
    return Image.frombytes("RGB", (w, h), frame_bytes(path, t, "rgb24"))


def nonblack_rows(path, t: float, threshold: int = 24) -> int:
    """How many rows of the frame at `t` carry picture (a row whose peak
    luma is over `threshold`): the letterbox's active height."""
    w, h, y, _, _ = frame_yuv(path, t)
    return sum(1 for r in range(h) if max(y[r * w:(r + 1) * w]) > threshold)


def measured_zoom(before, after, candidates=(1.0, 1.05, 1.1, 1.15, 1.2, 1.25, 1.3,
                                             1.35, 1.4, 1.5)) -> float:
    """Which centre-crop factor of `before` (a Pillow image) best matches
    `after`: the zoom one frame carries against another, from the pixels."""
    from PIL import Image, ImageChops, ImageStat
    w, h = before.size
    small = (160, int(round(160 * h / w)) or 1)
    target = after.convert("L").resize(small, Image.BILINEAR)
    best, best_err = 1.0, None
    for z in candidates:
        cw, ch = w / z, h / z
        box = ((w - cw) / 2, (h - ch) / 2, (w + cw) / 2, (h + ch) / 2)
        guess = before.convert("L").crop(tuple(int(round(b)) for b in box)).resize(
            small, Image.BILINEAR)
        err = ImageStat.Stat(ImageChops.difference(guess, target)).mean[0]
        if best_err is None or err < best_err:
            best, best_err = z, err
    return best


