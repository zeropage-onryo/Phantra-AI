def enabled() -> bool:
    return (os.environ.get(ENV) or "").strip() == "1"


def is_look(effect: str) -> bool:
    return (effect or "").strip() in LOOKS


def require_enabled(effect: str) -> None:
    """ValueError when a free look is named on a server that has them off."""
    if is_look(effect) and not enabled():
        raise ValueError(f"the free looks are not switched on for this server ({ENV}=1)")


def ensure_assets() -> dict[str, Path]:
    """The generated assets, written on first use (src/looks_assets.py)."""
    from . import looks_assets
    return looks_assets.write_all(ASSETS_DIR, only_missing=True)


def ffmpeg_bin() -> Optional[str]:
    return shutil.which("ffmpeg")


def has_drawtext() -> bool:
    """Does this host's ffmpeg have `drawtext`? (The Mac's Homebrew build
    does not; nothing here needs it -- see the module docstring.)"""
    bin_ = ffmpeg_bin()
    if not bin_:
        return False
    try:
        out = subprocess.run([bin_, "-hide_banner", "-filters"], capture_output=True,
                             text=True, timeout=30).stdout
    except Exception:                                   # noqa: BLE001
        return False
    return any(line.split()[1:2] == ["drawtext"] for line in out.splitlines())


def _fq(path) -> str:
    """A path quoted for a filter argument (the worktree's own path has
    spaces in it)."""
    text = str(path).replace("\\", "\\\\").replace("'", "\\'")
    return f"'{text}'"


def _even(n: float) -> int:
    n = int(n)
    return n if n % 2 == 0 else n - 1


