def probe(path) -> dict:
    """seconds / width / height / fps / audio of a clip (effects.probe_video
    plus whether it carries sound)."""
    from . import effects
    facts = effects.probe_video(path)
    facts["audio"] = has_audio(path)
    return facts


def has_audio(path) -> bool:
    try:
        out = subprocess.run(
            ["ffprobe", "-v", "error", "-select_streams", "a:0",
             "-show_entries", "stream=codec_type", "-of", "json", str(path)],
            capture_output=True, text=True, timeout=60, check=True).stdout
        return bool(json.loads(out).get("streams"))
    except Exception:                                   # noqa: BLE001
        return False


def letterbox_bar(width: int, height: int, ratio: float = LETTERBOX_RATIO) -> int:
    """The height of each black bar that leaves an active picture of
    `ratio` (2.39:1), or 0 when the frame is already that wide. The
    active height takes the frame's parity so the two bars are equal."""
    active = int(round(width / ratio))
    if (height - active) % 2:
        active += 1
    if active >= height:
        return 0
    return (height - active) // 2


def vertical_crop(width: int, height: int) -> tuple[int, int]:
    """The largest centred 9k x 16k crop (k even, so both sides are even
    for yuv420p) that fits: width/height is EXACTLY 9/16."""
    k = min(width // 9, height // 16)
    if k % 2:
        k -= 1
    if k <= 0:
        raise ValueError(f"a {width}x{height} clip is too small for a 9:16 crop")
    return 9 * k, 16 * k


def zoom_at(t: float, zoom: float) -> float:
    """The crash zoom's crop factor at `t` seconds: 1 -> `zoom` over the
    first 0.3s, held, then eased back to 1 by 1.4s."""
    if t < ZOOM_IN_END:
        return 1.0 + (zoom - 1.0) * (t / ZOOM_IN_END)
    if t < ZOOM_HOLD_END:
        return zoom
    if t < ZOOM_OUT_END:
        return zoom - (zoom - 1.0) * ((t - ZOOM_HOLD_END) / (ZOOM_OUT_END - ZOOM_HOLD_END))
    return 1.0


def _zoom_expr(zoom: float) -> str:
    z = f"{zoom:.4f}"
    return (f"if(lt(it,{ZOOM_IN_END}),1+({z}-1)*(it/{ZOOM_IN_END}),"
            f"if(lt(it,{ZOOM_HOLD_END}),{z},"
            f"if(lt(it,{ZOOM_OUT_END}),{z}-({z}-1)*((it-{ZOOM_HOLD_END})/"
            f"{ZOOM_OUT_END - ZOOM_HOLD_END}),1)))")


