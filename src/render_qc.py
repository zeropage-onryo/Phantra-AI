"""A look at every clip the moment it lands (2026-10-25, the render test).

The render test's clips failed in ways nobody had to pay to find out: the
brand name said wrong in the voiceover, the app's words smeared, the product
drawn the wrong shape. Each was visible in the first watch. So when a shot's
clip lands, Gemini watches it once against what was asked for (the shot's
prompt, the scene's brand kit: its name, its linked products, any words the
prompt quotes) and answers four plain facts plus up to three notes, which
the Render card prints under that shot.

It ADVISES and never rejects (the project's rule: prompts request, code
advises): a note is a line under a clip that is already paid for and kept.
It costs no credits (model text is free on a plan, metered like every call
through gemini_utils.generate_with_retry as stage "render_qc"), runs inside
the render job after each shot, and never raises -- a missing key, a failed
call or an unreadable answer is no notes, said in a line on stderr.
`PHANTRA_RENDER_QC=0` turns it off.

Notes live in the OWNED table `render_qc`, one row per landed clip, read by
`for_concept` into the Render card's state. `ensure(dsn)` inits once per
process and database (never an init per request).
"""
from __future__ import annotations

import json
import os
import re
import sys
import threading
from pathlib import Path
from typing import Optional

from . import db

PROMPT = Path(__file__).resolve().parent.parent / "prompts/render_qc.txt"
STAGE = "render_qc"
NOTES_MAX = 3
NOTE_MAX = 160
INLINE_LIMIT = 18 << 20          # Gemini's inline request cap is 20 MB
FACTS = {
    "brand_said": ("said", "misspoken", "not_said", "n/a"),
    "text": ("readable", "garbled", "none", "n/a"),
    "product": ("present", "missing", "wrong_shape", "n/a"),
    "people": ("fine", "distorted", "none"),
}
# the facts that mean something is wrong, in the words the card prints
PROBLEMS = {
    ("brand_said", "misspoken"): "the brand name is said wrong",
    ("text", "garbled"): "on-screen words are garbled",
    ("product", "missing"): "the product does not appear",
    ("product", "wrong_shape"): "the product is the wrong shape",
    ("people", "distorted"): "hands or faces are distorted",
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS render_qc (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id  BIGINT NOT NULL,
    part        INTEGER,
    media       TEXT   NOT NULL,
    facts_json  TEXT   NOT NULL DEFAULT '{}',
    notes_json  TEXT   NOT NULL DEFAULT '[]',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""
INDEXES = """
CREATE INDEX IF NOT EXISTS idx_render_qc_concept ON render_qc (account_id, concept_id);
"""

_ready: set[str] = set()
_ready_lock = threading.Lock()


def init(dsn: Optional[str] = None) -> None:
    key = db.resolve_dsn(dsn)
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "render_qc")
        conn.execute(INDEXES)
    _ready.add(key)


def ensure(dsn: Optional[str] = None) -> None:
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)


def enabled() -> bool:
    return os.environ.get("PHANTRA_RENDER_QC", "1").strip().lower() not in ("0", "false", "off", "no")


def quoted_words(prompt: str) -> list[str]:
    """Words the prompt asks to be READ on screen: what it puts in quotes."""
    found = re.findall(r"[\"“]([^\"”]{2,60})[\"”]", prompt or "")
    return list(dict.fromkeys(w.strip() for w in found if w.strip()))[:6]


def build_prompt(prompt: str, brand: str = "", products=(), words=()) -> str:
    return PROMPT.read_text().format(
        prompt=(prompt or "").strip()[:4000] or "(none)",
        brand=brand or "none given",
        products=", ".join(products) or "none given",
        words=", ".join(f'"{w}"' for w in words) or "none asked for")


def check(raw) -> Optional[dict]:
    """The model's answer held to the four facts and short notes, or None
    when it is not an answer. An unknown value is dropped, never guessed."""
    if not isinstance(raw, str):
        return None
    text = raw.strip()
    text = re.sub(r"^```(?:json)?|```$", "", text, flags=re.M).strip()
    try:
        data = json.loads(text)
    except ValueError:
        return None
    if not isinstance(data, dict):
        return None
    facts = {k: data[k] for k, legal in FACTS.items() if data.get(k) in legal}
    notes = []
    for n in data.get("notes") or []:
        line = " ".join(str(n).split())
        if line:
            notes.append(line if len(line) <= NOTE_MAX else line[:NOTE_MAX].rsplit(" ", 1)[0] + "…")
    return {"facts": facts, "notes": notes[:NOTES_MAX]}


def problems(facts: dict) -> list[str]:
    return [line for (k, v), line in PROBLEMS.items() if facts.get(k) == v]


def review(path, *, prompt: str, brand: str = "", products=(), client=None,
           account_id: Optional[int] = None) -> Optional[dict]:
    """Watch one clip once. {"facts", "notes"} or None (off, no key, no
    file, a failed call, an unreadable answer). Never raises."""
    if not enabled():
        return None
    try:
        data = Path(path).read_bytes()
    except (OSError, TypeError) as e:
        print(f"  render check skipped: the clip could not be read ({e})", file=sys.stderr)
        return None
    if len(data) > INLINE_LIMIT:
        print("  render check skipped: the clip is too large to send inline", file=sys.stderr)
        return None
    try:
        from google.genai import types

        from . import gemini_utils
        if client is None:
            if not gemini_utils.api_key_for(account_id):
                return None
            client = gemini_utils.client_for(account_id)
        raw = gemini_utils.generate_with_retry(
            client, gemini_utils.FAST_MODEL,
            [types.Part.from_bytes(data=data, mime_type="video/mp4"),
             build_prompt(prompt, brand, products, quoted_words(prompt))],
            stage=STAGE, account_id=account_id)
    except Exception as e:
        print(f"  render check failed: {type(e).__name__}: {e}", file=sys.stderr)
        return None
    return check(raw)


def record(concept_id: int, part: Optional[int], media: str, result: dict,
           dsn: Optional[str] = None, *, account_id: int) -> None:
    """Keep one clip's check. Never raises."""
    try:
        ensure(dsn)
        with db.connect(dsn) as conn:
            conn.execute(
                "INSERT INTO render_qc (account_id, concept_id, part, media, facts_json, notes_json)"
                " VALUES (%s, %s, %s, %s, %s, %s)",
                (account_id, concept_id, part, media, json.dumps(result.get("facts") or {}),
                 json.dumps(result.get("notes") or [])))
    except Exception as e:
        print(f"  render check not kept: {type(e).__name__}: {e}", file=sys.stderr)


def for_concept(concept_id: int, dsn: Optional[str] = None, *,
                account_id: int) -> dict:
    """{"<shot n>" ("0" for a scene rendered whole): {"media", "problems",
    "notes"}} -- the newest check of each shot's clip, so a shot rendered
    again reads its new clip's. {} when none, or the table cannot be read."""
    try:
        ensure(dsn)
        with db.connect(dsn) as conn:
            rows = conn.execute(
                "SELECT part, media, facts_json, notes_json FROM render_qc"
                " WHERE account_id = %s AND concept_id = %s ORDER BY id",
                (account_id, concept_id)).fetchall()
    except Exception as e:
        print(f"  render checks not read: {type(e).__name__}: {e}", file=sys.stderr)
        return {}
    out = {}
    for part, media, facts, notes in rows:
        try:
            out[str(part or 0)] = {"media": media, "problems": problems(json.loads(facts or "{}")),
                                   "notes": list(json.loads(notes or "[]"))}
        except ValueError:
            continue
    return out


def check_shot(concept_id: int, part: Optional[int], result: dict, *, prompt: str,
               account_id: int, kit=None, dsn: Optional[str] = None) -> Optional[dict]:
    """After a shot's clip landed (`result` is generate_for_shot's answer):
    watch it against its prompt and the scene's kit, and keep what was seen
    under the clip's media name. Never raises."""
    if not enabled() or not result.get("ok") or not result.get("path"):
        return None
    try:
        from . import brand_kits
        products = [e["name"] for e in brand_kits.linked(kit, dsn) if e["kind"] == "prop"] if kit else []
        brand = kit.get("name", "") if kit else ""
    except Exception:
        products, brand = [], ""
    seen = review(result["path"], prompt=prompt, brand=brand, products=products,
                  account_id=account_id)
    if seen is None:
        return None
    media = result.get("media_url") or result["path"]
    from .asset_shelf import storable_ref
    try:
        media = storable_ref(media) or media
    except Exception:
        pass
    record(concept_id, part, media, seen, dsn, account_id=account_id)
    return seen


__all__ = ["STAGE", "FACTS", "PROBLEMS", "init", "ensure", "enabled", "quoted_words",
           "build_prompt", "check", "problems", "review", "record", "for_concept", "check_shot"]
