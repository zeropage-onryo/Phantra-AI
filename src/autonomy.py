"""
Autonomy bookkeeping for the content graph: the one switch that stops
everything, the prompt gate's log and the standing corrections.

Same shape as preprod.py/entities.py: own SCHEMA, own init(), tables on
the shared pipeline DB through db.connect -- one database, not a
second store. Postgres since 2026-09-03; `dsn` where it took `path`.

There is no `channels` table since 2026-10-13 and no `hold_queue` since
2026-10-14 (both Mike's calls, docs/tasks/task-remove-brand-labels.md): a
graph run ends by returning its result, and nothing parks it, grades it
or posts it from a queue. The live tables are dropped in step 6.

Three tables:
- corrections  -- mid-run human notes, for the human_note interrupt
                  node when it lands. Written now so the schema exists.
- settings     -- key/value; the kill switch lives here. Global on
                  purpose: one place to pull the plug at once.
- prompt_scores -- the prompt gate's log (nothing writes it since
                  2026-10-11; the rows already in it stay readable).
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Optional

import psycopg

from . import db

SCHEMA = """
CREATE TABLE IF NOT EXISTS corrections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL,
    run_id     TEXT,
    note       TEXT NOT NULL,
    consumed   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS settings (
    key        TEXT PRIMARY KEY,
    value      TEXT
);

CREATE TABLE IF NOT EXISTS prompt_scores (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TEXT NOT NULL,
    run_id        TEXT,
    prompt        TEXT,
    score         INTEGER,
    passed        INTEGER,
    reason        TEXT,
    dims          TEXT,           -- json {subject, camera, motion, lighting, coherence}
    human_verdict TEXT,           -- 'post' | 'reject' | NULL, from the retired hold grading
    unreadable    INTEGER NOT NULL DEFAULT 0  -- 1 = the judge errored, so this row is NOT a verdict
);
CREATE INDEX IF NOT EXISTS idx_prompt_scores_run ON prompt_scores (run_id);
"""

KILL_KEY = "kill_switch"

# What a graph run may do when it reaches the end: stop, always. Kept as
# a name because the run's state still says it.
AUTONOMY = "shadow"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def init(dsn=None) -> None:
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        # prompt_scores.unreadable (2026-09-14): a live database predates
        # it, and the default is what makes the backfill a no-op -- every
        # existing row WAS a real verdict as far as anyone can now tell,
        # so 0 is both the honest value and the one that leaves
        # prompt_gate_agreement reading exactly as it did before.
        if "unreadable" not in db.columns(conn, "prompt_scores"):
            conn.execute("ALTER TABLE prompt_scores ADD COLUMN "
                         "unreadable INTEGER NOT NULL DEFAULT 0")


# --- post targets ---------------------------------------------------------

# The platforms a channel may name as a post target. A target is a
# promise that an adapter exists: autopilot._post_dispatch routes on
# exactly these names, and a typo'd one would fan a post action out to a
# platform that raises NotImplementedError in live mode -- which is a
# gate failure discovered at the worst possible moment. Validated on the
# way in by validate_targets.
POST_TARGETS = ("instagram", "youtube", "tiktok")


def parse_targets(value) -> list[str]:
    """The stored comma list as a clean, ordered, de-duplicated list.
    Order is kept because it is the order a fan-out posts in, and a
    person who wrote "instagram,youtube" meant Instagram first."""
    seen: list[str] = []
    for part in str(value or "").split(","):
        name = part.strip().lower()
        if name and name not in seen:
            seen.append(name)
    return seen


def validate_targets(value) -> list[str]:
    """Parse and refuse anything without an adapter. Raises ValueError
    naming the offender -- the caller is a person editing a channel, and
    "instgram" should fail at the edit, not at 3am."""
    targets = parse_targets(value)
    unknown = [t for t in targets if t not in POST_TARGETS]
    if unknown:
        raise ValueError(
            f"unknown post target(s) {', '.join(unknown)} -- "
            f"must be one of {', '.join(POST_TARGETS)}")
    return targets


# --- the kill switch ------------------------------------------------------

def kill(reason: str = "", dsn=None) -> None:
    with db.connect(dsn) as conn:
        conn.execute(
            "INSERT INTO settings (key, value) VALUES (%s, %s) "
            "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            (KILL_KEY, reason or "killed"),
        )


def unkill(dsn=None) -> None:
    with db.connect(dsn) as conn:
        conn.execute("DELETE FROM settings WHERE key = %s", (KILL_KEY,))


def killed(dsn=None) -> bool:
    """True stops every run before it renders. Also honours the
    PHANTRA_KILL env var so the plug can be pulled without a DB write."""
    import os
    if os.environ.get("PHANTRA_KILL"):
        return True
    with db.connect(dsn) as conn:
        row = conn.execute("SELECT value FROM settings WHERE key = %s", (KILL_KEY,)).fetchone()
        return row is not None


def prompt_scores_for_run(run_id: Optional[str], dsn=None) -> list[dict]:
    """Every gate verdict logged against one run, oldest first -- the
    first-draft score and, after a rework, the revised one -- so the
    reader can see whether the rewrite moved the number. Empty for a
    run that never reached the gate."""
    if not run_id:
        return []
    try:
        with db.connect(dsn) as conn:
            rows = conn.execute(
                "SELECT id, created_at, score, passed, reason, dims, human_verdict "
                "FROM prompt_scores WHERE run_id = %s ORDER BY id",
                (run_id,)).fetchall()
    except psycopg.Error:
        return []
    out = []
    for r in rows:
        row = dict(r)
        try:
            row["dims"] = json.loads(row["dims"]) if row.get("dims") else {}
        except (ValueError, TypeError):
            row["dims"] = {}
        row["passed"] = bool(row.get("passed"))
        out.append(row)
    return out


# --- the prompt gate's log -------------------------------------------------
# HISTORY SINCE 2026-10-11: the gate's LLM rubric is gone (orchestrator.
# score_prompts is a code check now) and nothing calls log_prompt_scores.
# The table and its readers stay for the rows already in it -- the cards'
# `gate`, the MCP's `_gate`, and the step-0 snapshot read them.

def log_prompt_scores(run_id, scored: list, dsn=None) -> None:
    """One row per scored prompt per run -- the record the gate-vs-you
    agreement number is computed from. Logged before any credit could
    be spent, pass or fail."""
    with db.connect(dsn) as conn:
        for x in scored:
            conn.execute(
                "INSERT INTO prompt_scores (created_at, run_id, prompt, score, "
                "passed, reason, dims, unreadable) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s, %s)",
                (_now(), run_id, x.get("prompt"), x.get("score"),
                 int(bool(x.get("pass"))), x.get("reason"),
                 json.dumps(x.get("dims", {})),
                 int(bool(x.get("unreadable")))),
            )


def prompt_gate_agreement(dsn=None) -> dict:
    """Gate vs. you, over the graded rows: (passed AND you'd post) OR
    (held AND you'd reject). The two disagreement types cost
    differently -- passed-but-reject burns a credit, held-but-post only
    costs a manual approval -- so both are broken out."""
    with db.connect(dsn) as conn:
        row = conn.execute(
            # Postgres cannot SUM a boolean; SQLite quietly treated one as 0/1
            "SELECT COUNT(*),"
            " SUM(CASE WHEN (passed = 1 AND human_verdict = 'post') OR"
            "     (passed = 0 AND human_verdict = 'reject') THEN 1 ELSE 0 END),"
            " SUM(CASE WHEN passed = 1 AND human_verdict = 'reject' THEN 1 ELSE 0 END),"
            " SUM(CASE WHEN passed = 0 AND human_verdict = 'post' THEN 1 ELSE 0 END)"
            " FROM prompt_scores WHERE human_verdict IS NOT NULL"
            # A row the judge never rendered a verdict on measures the
            # Gemini API's uptime, not the gate's judgement. Genuine
            # passed = 0 rows stay in, deliberately -- see
            # orchestrator._gate_advisory on why the scores themselves
            # are never massaged.
            " AND unreadable = 0"
        ).fetchone()
    graded, agreed, expensive, cheap = (row[0], row[1] or 0, row[2] or 0, row[3] or 0)
    return {
        "graded": graded,
        "agreement": round(agreed / graded, 3) if graded else None,
        "passed_but_rejected": expensive,   # would have burned a credit
        "held_but_posted": cheap,           # only cost an approval
    }


def first_try_pass_rate(dsn=None) -> dict:
    """Purely descriptive: how often the gate lets a render through.
    Not the trust number -- that's prompt_gate_agreement."""
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT COUNT(*), SUM(passed) FROM prompt_scores "
            "WHERE unreadable = 0"
        ).fetchone()
    total, passed = row[0], row[1] or 0
    return {"total": total, "passed": passed,
            "rate": round(passed / total, 3) if total else None}


# --- corrections (for the human_note interrupt, when it lands) ------------

def add_correction(note: str, run_id: Optional[str] = None, dsn=None) -> int:
    with db.connect(dsn) as conn:
        row = conn.execute(
            "INSERT INTO corrections (created_at, run_id, note) VALUES (%s, %s, %s) "
            "RETURNING id",
            (_now(), run_id, note),
        ).fetchone()
        return int(row["id"])


def pending_corrections(dsn=None) -> list[dict]:
    with db.connect(dsn) as conn:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM corrections WHERE consumed = 0 ORDER BY created_at"
        )]


def consume_correction(correction_id: int, dsn=None) -> None:
    with db.connect(dsn) as conn:
        conn.execute("UPDATE corrections SET consumed = 1 WHERE id = %s", (correction_id,))
