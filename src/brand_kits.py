def _swatch(s: dict) -> str:
    name = f"{s['name']} " if s.get("name") else ""
    return f"{name}{s['hex']} ({s['role']})"


def palette_line(kit: dict) -> str:
    palette = (kit.get("spec") or {}).get("palette") or []
    return "; ".join(_swatch(s) for s in palette)


def colour(kit: dict, role: str, default: str = "#FFFFFF") -> str:
    for s in (kit.get("spec") or {}).get("palette") or []:
        if s["role"] == role:
            return s["hex"]
    return default


def brief_lines(kit: Optional[dict], dsn: Optional[str] = None) -> str:
    """The BRAND block the writer and the brain read under the project, or
    "" for no kit. Element names are read live, so a renamed product is
    named as it is now."""
    if not kit:
        return ""
    spec = kit.get("spec") or {}
    ident, voice, look = spec.get("identity") or {}, spec.get("voice") or {}, spec.get("look") or {}
    lines = [f"BRAND KIT “{kit['name']}” -- this project is made for this brand. "
             "Write in its voice and keep to its rules:"]
    if ident.get("positioning"):
        lines.append(f"- Positioning: {ident['positioning']}")
    if ident.get("audience"):
        lines.append(f"- Audience: {ident['audience']}")
    if ident.get("tagline"):
        lines.append(f"- Tagline: “{ident['tagline']}”")
    if ident.get("selling_points"):
        lines.append(f"- Selling points: {'; '.join(ident['selling_points'])}")
    if voice.get("tone"):
        lines.append(f"- Tone: {voice['tone']}")
    if voice.get("use"):
        lines.append(f"- Words to use: {', '.join(voice['use'])}")
    if voice.get("avoid"):
        lines.append(f"- Words never to use: {', '.join(voice['avoid'])}")
    if voice.get("cta"):
        lines.append(f"- Call to action style: {voice['cta']}")
    names = _element_names(kit, dsn)
    for p in spec.get("products") or []:
        name = names.get(("prop", p["id"])) or p.get("name") or f"product {p['id']}"
        claims = "; ".join(p.get("claims") or [])
        lines.append(f"- Product: {name}" + (f" -- the only claims allowed: {claims}" if claims
                                             else " -- make no claims about it"))
    if spec.get("never_claim"):
        lines.append(f"- Never claim: {'; '.join(spec['never_claim'])}")
    cast = [names.get(("character", c["id"])) or c.get("name") for c in spec.get("characters") or []]
    cast = [c for c in cast if c]
    if cast:
        lines.append(f"- The brand's recurring cast: {', '.join(cast)}")
    if look.get("banned"):
        lines.append(f"- Never write into a scene: {', '.join(look['banned'])}")
    return "\n".join(lines)


def _element_names(kit: dict, dsn: Optional[str]) -> dict:
    spec = kit.get("spec") or {}
    if not (spec.get("products") or spec.get("characters")):
        return {}
    from . import entities
    names = {}
    try:
        for kind, links, getter in (("prop", spec.get("products") or [], entities.get_prop),
                                    ("character", spec.get("characters") or [],
                                     entities.get_character)):
            for link in links:
                found = getter(link["id"], dsn, account_id=kit["account_id"])
                if found:
                    names[(kind, link["id"])] = found.get("name")
    except Exception:
        pass
    return names


def look_suffix(kit: Optional[dict]) -> str:
    """What every still, keyframe and clip prompt gains under a kit, or "".
    The banned list rides as an `Avoid:` line so a per-model rule that moves
    the avoid-list into a negative prompt (src/prompts_for.py) finds it."""
    if not kit:
        return ""
    spec = kit.get("spec") or {}
    look = spec.get("look") or {}
    parts = []
    head = f"BRAND LOOK ({kit['name']})"
    body = []
    if look.get("style"):
        body.append(look["style"])
    if look.get("aesthetics"):
        body.append("Aesthetic: " + ", ".join(a["tag"] for a in look["aesthetics"]) + ".")
    palette = palette_line(kit)
    if palette:
        body.append(f"Brand palette: {palette}.")
    if body:
        parts.append(f"{head}: " + " ".join(body))
    if look.get("banned"):
        parts.append("Avoid: " + ", ".join(look["banned"]) + ".")
    return "\n".join(parts)


def dress(prompt: str, kit: Optional[dict]) -> str:
    """A render prompt under a kit: the prompt, then the look. Unchanged
    for no kit (or a kit with no look to add)."""
    suffix = look_suffix(kit)
    if not suffix or not (prompt or "").strip():
        return prompt
    return f"{prompt.rstrip()}\n\n{suffix}"


REFERENCE_LABEL = ("BRAND LOOK reference -- use ONLY its colour, light and finish. "
                   "Do not copy its subject, its place or its framing")


def still_references(kit: Optional[dict], limit: int = STILL_REFS_MAX) -> list[tuple[str, bytes]]:
    """The kit's look references as (caption, bytes) for a still or a
    keyframe -- appended AFTER the scene's own, never first (the first
    reference is what a frame anchors on)."""
    if not kit:
        return []
    out = []
    for a in [a for a in kit.get("assets") or [] if a["role"] == "reference"][:limit]:
        data = file_bytes(a["stored"], kit["account_id"])
        if data:
            out.append((REFERENCE_LABEL, data))
    return out


