def init(dsn: Optional[str] = None) -> None:
    """Both tables. Idempotent; run at process start under db.run_init."""
    key = db.resolve_dsn(dsn)
    with connect(dsn) as conn:
        conn.execute(SCHEMA)
        own_table(conn, "brand_kits")
        own_table(conn, "brand_kit_assets")
    _ready.add(key)


def ensure(dsn: Optional[str] = None) -> None:
    """The tables exist before a request reads them -- once per process and
    database, through db.run_init (two inits at once deadlock)."""
    key = db.resolve_dsn(dsn)
    if key in _ready:
        return
    with _ready_lock:
        if key not in _ready:
            db.run_init(lambda: init(dsn), dsn)


class KitError(ValueError):
    """A field the kit refuses, with the field it is about."""

    def __init__(self, field: str, message: str):
        super().__init__(message)
        self.field = field


