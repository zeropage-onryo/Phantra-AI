def _iso(value):
    return value.isoformat() if hasattr(value, "isoformat") else value


def _kit(row, assets: list[dict]) -> dict:
    spec = row["spec"] if isinstance(row["spec"], dict) else json.loads(row["spec"] or "{}")
    kit = {"id": row["id"], "account_id": row["account_id"], "name": row["name"],
           "spec": spec, "assets": assets,
           "created_at": _iso(row["created_at"]), "updated_at": _iso(row["updated_at"]),
           "deleted": row["deleted_at"] is not None}
    kit["hash"] = hash_of(kit)
    return kit


def _asset(row) -> dict:
    meta = row["meta"] if isinstance(row["meta"], dict) else json.loads(row["meta"] or "{}")
    return {"id": row["id"], "role": row["role"], "stored": row["stored"],
            "mime": row["mime"], "meta": meta, "created_at": _iso(row["created_at"])}


def _assets(conn, kit_ids: list[int], account_id: int) -> dict[int, list[dict]]:
    if not kit_ids:
        return {}
    rows = conn.execute(
        "SELECT * FROM brand_kit_assets WHERE kit_id = ANY(%s) AND deleted_at IS NULL "
        "AND account_id IS NOT DISTINCT FROM %s ORDER BY id",
        (kit_ids, account_id)).fetchall()
    out: dict[int, list[dict]] = {}
    for r in rows:
        out.setdefault(r["kit_id"], []).append(_asset(r))
    return out


def create(name, spec=None, dsn: Optional[str] = None, *, account_id: int) -> dict:
    name, spec = clean_name(name), clean_spec(spec)
    ensure(dsn)
    with connect(dsn) as conn:
        row = conn.execute(
            "INSERT INTO brand_kits (account_id, name, spec) VALUES (%s, %s, %s) RETURNING *",
            (account_id, name, json.dumps(spec))).fetchone()
        return _kit(row, [])


def get(kit_id: int, dsn: Optional[str] = None, *, account_id: int,
        include_deleted: bool = False) -> Optional[dict]:
    """The caller's kit, or None -- another account's id reads like one that
    does not exist."""
    ensure(dsn)
    with connect(dsn) as conn:
        row = conn.execute(
            "SELECT * FROM brand_kits WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
            (int(kit_id), account_id)).fetchone()
        if not row or (row["deleted_at"] is not None and not include_deleted):
            return None
        return _kit(row, _assets(conn, [row["id"]], account_id).get(row["id"], []))


def list_kits(dsn: Optional[str] = None, *, account_id: int) -> list[dict]:
    """The account's kits, newest-touched first, each with how many live
    projects picked it."""
    ensure(dsn)
    with connect(dsn) as conn:
        rows = conn.execute(
            "SELECT * FROM brand_kits WHERE account_id IS NOT DISTINCT FROM %s "
            "AND deleted_at IS NULL ORDER BY updated_at DESC, id DESC",
            (account_id,)).fetchall()
        assets = _assets(conn, [r["id"] for r in rows], account_id)
        used: dict[int, int] = {}
        if rows and db.columns(conn, "projects") and "brand_kit_id" in db.columns(conn, "projects"):
            for r in conn.execute(
                    "SELECT brand_kit_id, COUNT(*) AS n FROM projects "
                    "WHERE account_id IS NOT DISTINCT FROM %s AND brand_kit_id IS NOT NULL "
                    "AND archived_at IS NULL GROUP BY brand_kit_id", (account_id,)).fetchall():
                used[r["brand_kit_id"]] = r["n"]
        out = []
        for r in rows:
            kit = _kit(r, assets.get(r["id"], []))
            kit["projects"] = used.get(r["id"], 0)
            out.append(kit)
        return out


def update(kit_id: int, dsn: Optional[str] = None, *, account_id: int,
           name=None, spec=None) -> Optional[dict]:
    sets, args = ["updated_at = now()"], []
    if name is not None:
        sets.append("name = %s")
        args.append(clean_name(name))
    if spec is not None:
        sets.append("spec = %s")
        args.append(json.dumps(clean_spec(spec)))
    ensure(dsn)
    with connect(dsn) as conn:
        row = conn.execute(
            f"UPDATE brand_kits SET {', '.join(sets)} WHERE id = %s "
            "AND account_id IS NOT DISTINCT FROM %s AND deleted_at IS NULL RETURNING id",
            (*args, int(kit_id), account_id)).fetchone()
    return get(row["id"], dsn, account_id=account_id) if row else None


def duplicate(kit_id: int, dsn: Optional[str] = None, *, account_id: int) -> Optional[dict]:
    """A copy named "<name> copy", sharing the stored files (they are
    content-addressed, so nothing is uploaded twice)."""
    kit = get(kit_id, dsn, account_id=account_id)
    if not kit:
        return None
    name = (kit["name"] + " copy")[:NAME_MAX]
    with connect(dsn) as conn:
        row = conn.execute(
            "INSERT INTO brand_kits (account_id, name, spec) VALUES (%s, %s, %s) RETURNING id",
            (account_id, name, json.dumps(kit["spec"]))).fetchone()
        for a in kit["assets"]:
            conn.execute(
                "INSERT INTO brand_kit_assets (kit_id, account_id, role, stored, mime, meta) "
                "VALUES (%s, %s, %s, %s, %s, %s)",
                (row["id"], account_id, a["role"], a["stored"], a["mime"],
                 json.dumps(a["meta"])))
    return get(row["id"], dsn, account_id=account_id)


def delete(kit_id: int, dsn: Optional[str] = None, *, account_id: int,
           restore: bool = False) -> bool:
    """Soft: the row stays and Undo brings it back. A project that picked a
    deleted kit reads as having none (`for_project`)."""
    ensure(dsn)
    with connect(dsn) as conn:
        cur = conn.execute(
            "UPDATE brand_kits SET deleted_at = CASE WHEN %s THEN NULL ELSE now() END, "
            "updated_at = now() WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
            (bool(restore), int(kit_id), account_id))
        return cur.rowcount > 0


