def for_project(project: Optional[dict], dsn: Optional[str] = None) -> Optional[dict]:
    """The kit a project picked, or None: no project, no pick, a deleted
    kit, another account's kit, or any failure. With no pick it answers
    without touching the database."""
    if not project or not project.get("brand_kit_id"):
        return None
    try:
        return get(int(project["brand_kit_id"]), dsn, account_id=project.get("account_id"))
    except Exception as e:                  # a kit is an addition, never a gate
        print(f"note: brand kit not read: {type(e).__name__}: {e}", file=sys.stderr)
        return None


def for_concept(concept_id, dsn: Optional[str] = None, *,
                account_id: Optional[int]) -> Optional[dict]:
    """The kit of the project a scene belongs to, or None."""
    if not concept_id:
        return None
    from . import projects
    try:
        project = projects.project_for_concept(int(concept_id), dsn, account_id=account_id)
    except Exception:
        return None
    return for_project(project, dsn)


def for_cut(cut: Optional[dict], dsn: Optional[str] = None, *,
            account_id: Optional[int]) -> Optional[dict]:
    """The kit a Cut project draws with: its scene's project's, or -- for a
    cut with no scene, a motion ad -- the studio project it was made for."""
    if not cut:
        return None
    return (for_concept(cut.get("concept_id"), dsn, account_id=account_id)
            or for_project_id(cut.get("studio_project_id"), dsn, account_id=account_id))


def for_project_id(project_id, dsn: Optional[str] = None, *,
                   account_id: Optional[int]) -> Optional[dict]:
    if not project_id:
        return None
    from . import projects
    try:
        project = projects.get(int(project_id), dsn, account_id=account_id)
    except Exception:
        return None
    return for_project(project, dsn)


def hash_of(kit: Optional[dict]) -> str:
    """What a render's look depends on: the spec and the files. "" for no kit."""
    if not kit:
        return ""
    blob = json.dumps({"spec": kit.get("spec") or {},
                       "files": sorted(f"{a['role']}:{a['stored']}"
                                       for a in kit.get("assets") or [])},
                      sort_keys=True)
    return hashlib.sha1(blob.encode("utf-8")).hexdigest()[:12]


def provenance(kit: Optional[dict]) -> dict:
    """What a kitted render records in generations.params_json; {} for none."""
    return {"brand_kit": {"id": kit["id"], "hash": kit["hash"]}} if kit else {}


