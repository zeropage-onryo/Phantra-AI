"""Brand kits: a client's identity, look, voice and sound, picked per project
(docs/tasks/task-brand-kit.md, 2026-10-20, Mike's approval).

A kit belongs to an ACCOUNT -- many per account, one per client, which is
what an agency needs -- and does nothing until a PROJECT picks it
(`projects.brand_kit_id`). There is no studio-wide or default kit: Mike's
rule since 2026-10-13 is that a brand exists only inside a project, never
studio-wide (docs/tasks/task-remove-brand-labels.md), and a kit nobody
picked is inert.

OPT-IN, BYTE FOR BYTE. Every reader asks `for_project` / `for_concept`
first and does nothing at all when the answer is None, so a project with no
kit sends the same prompts, the same provider arguments, the same quote
hash and the same Cut export as before kits existed
(tests/test_brand_kit_no_kit.py holds the goldens).

What reads a kit:

  * the writer and the brain -- `brief_lines`, appended to the project
    block by projects.brief_block: tone, words, CTA, products and their
    claims, the recurring cast, what never to write;
  * every still, keyframe and clip -- `look_suffix`, appended at RENDER
    time (never baked into the saved prompt, so a quote, a re-plan and a
    connector-written scene are untouched, and switching kits changes the
    next render with no edits), plus the kit's reference images as
    look-only references on stills and keyframes;
  * the quote -- `hash_of`, folded into the content hash only when a kit
    is set, so a kit switched between a price and its approve re-prices;
  * the Cut -- the `brand` caption style and the logo end card
    (src/cut/brand.py).

The sound block is stored and read by nothing yet: the audio layer will.

Files (logos, fonts, look references, music references) are stored by NAME
(`/brandkits/<sha24>.<ext>`, content-addressed so a duplicated kit shares
them) under data/brandkits/<account>/ and mirrored to
`m/<account>/brandkits/...`; rows never carry an address.
"""
