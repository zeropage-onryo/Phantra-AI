def sniff(data: bytes, filename: str = "") -> str:
    """What a file is, from its bytes first and its name second."""
    head = data[:16]
    if head.startswith(b"\x89PNG"):
        return "image/png"
    if head.startswith(b"\xff\xd8"):
        return "image/jpeg"
    if head[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    if head[:4] == b"RIFF" and data[8:12] == b"WAVE":
        return "audio/wav"
    if head[:4] in (b"\x00\x01\x00\x00", b"true"):
        return "font/ttf"
    if head[:4] == b"OTTO":
        return "font/otf"
    if head[:3] == b"ID3" or head[:2] in (b"\xff\xfb", b"\xff\xf3", b"\xff\xf2"):
        return "audio/mpeg"
    if data[4:8] == b"ftyp":
        return "audio/mp4"
    text = data[:512].lstrip().lower()
    if text.startswith(b"<svg") or (text.startswith(b"<?xml") and b"<svg" in data[:2048].lower()):
        return "image/svg+xml"
    name = (filename or "").lower()
    if name.endswith((".heic", ".heif")):
        return "image/heic"
    return "application/octet-stream"


def font_family(data: bytes) -> Optional[str]:
    """The family name inside a font file -- what libass and @font-face are
    told to use. None for a file that does not open as a font."""
    try:
        from PIL import ImageFont
        family, _style = ImageFont.truetype(io.BytesIO(data), 20).getname()
        return family or None
    except Exception:
        return None


def _local(account_id: int, stored: str) -> Path:
    return FILES_DIR / str(account_id) / Path(stored).name


def _store(data: bytes, mime: str, account_id: int) -> str:
    name = Path(stored_name(data, mime)).name
    target = _local(account_id, name)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        target.write_bytes(data)
    from . import media
    media.mirror(target, f"brandkits/{name}", account_id, content_type=mime,
                 derive=mime in ("image/png", "image/jpeg", "image/webp"))
    return f"/brandkits/{name}"


def file_bytes(stored: str, account_id: int) -> Optional[bytes]:
    """A kit file's bytes: this machine's disk first, the account's bucket
    key second, None when neither has it."""
    if not stored or not stored.startswith("/brandkits/") or "/" in stored[len("/brandkits/"):]:
        return None
    target = _local(account_id, stored)
    if target.exists():
        try:
            return target.read_bytes()
        except OSError:
            pass
    from . import media, storage
    data = storage.get_bytes(media.object_key(stored.lstrip("/"), account_id))
    if data is not None:
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)       # cache: the next read is the disk
        except OSError:
            pass
    return data


def check_asset(role: str, data: bytes, *, filename: str = "", licensed: bool = False,
                licence: str = "") -> tuple[bytes, str, dict]:
    """What `add_asset` would store for one file -- (bytes, mime, meta) --
    or KitError. Writes nothing, so a report can run every check first."""
    if role not in ASSET_ROLES:
        raise KitError("role", f"role must be one of {', '.join(ASSET_ROLES)}")
    label, mimes, cap, _keep = ASSET_ROLES[role]
    if not data:
        raise KitError(role, "the file is empty")
    if len(data) > cap:
        raise KitError(role, f"{label} is at most {cap >> 20} MB")
    mime = sniff(data, filename)
    meta: dict[str, Any] = {"filename": Path(filename or "").name[:120]}
    if role == "reference":
        from . import refbin
        jpeg = refbin.to_jpeg(data)       # HEIC, PNG, WebP -> one JPEG, upright
        if jpeg is None:
            raise KitError(role, "that file does not open as an image")
        data, mime = jpeg, "image/jpeg"
    if mime not in mimes:
        raise KitError(role, f"{label} must be {' or '.join(EXT.get(m, m) for m in mimes)}")
    if role in FONT_ROLES:
        if not licensed:
            raise KitError(role, "confirm you have the right to embed this font in video")
        family = font_family(data)
        if not family:
            raise KitError(role, "that file does not open as a font")
        meta.update(family=family, licensed=True)
        if licence:
            meta["licence"] = _text(licence, "font licence", LINE_MAX)
    if role.startswith("logo_") and not role.endswith("_source"):
        try:
            from PIL import Image
            with Image.open(io.BytesIO(data)) as im:
                meta.update(width=im.width, height=im.height)
        except Exception:
            raise KitError(role, "that file does not open as an image") from None
    return data, mime, meta


def stored_name(data: bytes, mime: str) -> str:
    """The name a file is stored under (content-addressed)."""
    return f"/brandkits/{hashlib.sha256(data).hexdigest()[:24]}.{EXT[mime]}"


def add_asset(kit_id: int, role: str, data: bytes, dsn: Optional[str] = None, *,
              account_id: int, filename: str = "", licensed: bool = False,
              licence: str = "") -> dict:
    """One file onto a kit, or KitError. A role that keeps one file replaces
    the old one (soft); `reference` keeps up to eight."""
    data, mime, meta = check_asset(role, data, filename=filename, licensed=licensed,
                                   licence=licence)
    keep = ASSET_ROLES[role][3]
    kit = get(kit_id, dsn, account_id=account_id)
    if not kit:
        raise KitError("kit", "no such brand kit")
    same = [a for a in kit["assets"] if a["role"] == role]
    if keep > 1 and len(same) >= keep:
        raise KitError(role, f"a kit keeps at most {keep} of these -- remove one first")
    stored = _store(data, mime, account_id)
    with connect(dsn) as conn:
        if keep == 1:
            conn.execute(
                "UPDATE brand_kit_assets SET deleted_at = now() WHERE kit_id = %s AND role = %s "
                "AND deleted_at IS NULL AND account_id IS NOT DISTINCT FROM %s",
                (kit["id"], role, account_id))
        row = conn.execute(
            "INSERT INTO brand_kit_assets (kit_id, account_id, role, stored, mime, meta) "
            "VALUES (%s, %s, %s, %s, %s, %s) RETURNING *",
            (kit["id"], account_id, role, stored, mime, json.dumps(meta))).fetchone()
        conn.execute("UPDATE brand_kits SET updated_at = now() WHERE id = %s "
                     "AND account_id IS NOT DISTINCT FROM %s", (kit["id"], account_id))
        return _asset(row)


def remove_asset(kit_id: int, asset_id: int, dsn: Optional[str] = None, *,
                 account_id: int) -> bool:
    ensure(dsn)
    with connect(dsn) as conn:
        cur = conn.execute(
            "UPDATE brand_kit_assets SET deleted_at = now() WHERE id = %s AND kit_id = %s "
            "AND deleted_at IS NULL AND account_id IS NOT DISTINCT FROM %s",
            (int(asset_id), int(kit_id), account_id))
        if cur.rowcount:
            conn.execute("UPDATE brand_kits SET updated_at = now() WHERE id = %s "
                         "AND account_id IS NOT DISTINCT FROM %s", (int(kit_id), account_id))
        return cur.rowcount > 0


def asset(kit: dict, role: str) -> Optional[dict]:
    """The kit's newest file in a role, or None."""
    found = [a for a in (kit or {}).get("assets") or [] if a["role"] == role]
    return found[-1] if found else None


