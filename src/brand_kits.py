def _text(value, field: str, limit: int) -> str:
    if value is None:
        return ""
    if not isinstance(value, str):
        raise KitError(field, f"{field} must be text")
    value = value.strip()
    if len(value) > limit:
        raise KitError(field, f"{field} is at most {limit} characters")
    return value


def _words(value, field: str, limit: int = LIST_MAX) -> list[str]:
    if value in (None, ""):
        return []
    if isinstance(value, str):
        value = [w for w in re.split(r"[\n,]", value)]
    if not isinstance(value, list):
        raise KitError(field, f"{field} must be a list")
    out = []
    for item in value:
        item = _text(item, field, LIST_ITEM_MAX)
        if item and item not in out:
            out.append(item)
    if len(out) > limit:
        raise KitError(field, f"{field} holds at most {limit} entries")
    return out


def _number(value, field: str, low: float, high: float, default):
    if value in (None, ""):
        return default
    try:
        number = float(value)
    except (TypeError, ValueError):
        raise KitError(field, f"{field} must be a number") from None
    if not low <= number <= high:
        raise KitError(field, f"{field} must be between {low:g} and {high:g}")
    return number


def _choice(value, field: str, allowed, default):
    if value in (None, ""):
        return default
    if value not in allowed:
        raise KitError(field, f"{field} must be one of {', '.join(a or '(none)' for a in allowed)}")
    return value


def _links(value, field: str, kinds, limit: int, claims: bool) -> list[dict]:
    if not value:
        return []
    if not isinstance(value, list):
        raise KitError(field, f"{field} must be a list")
    out, seen = [], set()
    for item in value:
        if not isinstance(item, dict):
            raise KitError(field, f"each of {field} names an element")
        kind = item.get("kind")
        if kind not in kinds:
            raise KitError(field, f"{field} takes {' or '.join(kinds)} elements")
        try:
            eid = int(item.get("id"))
        except (TypeError, ValueError):
            raise KitError(field, f"each of {field} needs an element id") from None
        if (kind, eid) in seen:
            continue
        seen.add((kind, eid))
        link = {"kind": kind, "id": eid, "name": _text(item.get("name"), field, LIST_ITEM_MAX)}
        if claims:
            link["claims"] = _words(item.get("claims"), f"{field} claims", CLAIMS_MAX)
        out.append(link)
    if len(out) > limit:
        raise KitError(field, f"{field} holds at most {limit}")
    return out


def _lines(value, field: str, limit: int, length: int) -> list[str]:
    """A short list of sentences (one per line, or a list); commas stay."""
    if value in (None, ""):
        return []
    if isinstance(value, str):
        value = value.split("\n")
    if not isinstance(value, list):
        raise KitError(field, f"{field} must be a list")
    out = []
    for item in value:
        item = _text(item, field, length)
        if item and item not in out:
            out.append(item)
    if len(out) > limit:
        raise KitError(field, f"{field} holds at most {limit} entries")
    return out


def _aesthetics(value) -> list[dict]:
    """[{tag, because}]: a word for the look and the reason it fits."""
    if not value:
        return []
    if not isinstance(value, list):
        raise KitError("aesthetics", "aesthetics must be a list")
    out, seen = [], set()
    for item in value:
        if isinstance(item, str):
            item = {"tag": item}
        if not isinstance(item, dict):
            raise KitError("aesthetics", "each aesthetic is {tag, because}")
        tag = _text(item.get("tag"), "aesthetic", 40)
        if not tag or tag.casefold() in seen:
            continue
        seen.add(tag.casefold())
        out.append({"tag": tag, "because": _text(item.get("because"), "aesthetic reason", 160)})
    if len(out) > AESTHETICS_MAX:
        raise KitError("aesthetics", f"aesthetics holds at most {AESTHETICS_MAX}")
    return out


def _import(value) -> Optional[dict]:
    """Where an imported kit came from and how sure the import was of each
    value -- {source, at, roles: {role: {why, confidence}}, candidates}.
    None when absent (a hand-made kit carries no evidence)."""
    if not value:
        return None
    if not isinstance(value, dict):
        raise KitError("import", "import must be {source, at, roles}")
    roles = {}
    for role, ev in (value.get("roles") or {}).items():
        if role not in IMPORT_ROLES:
            raise KitError("import", f"import role must be one of {', '.join(IMPORT_ROLES)}")
        if not isinstance(ev, dict):
            raise KitError("import", "each import role is {why, confidence}")
        roles[role] = {"why": _text(ev.get("why"), "import reason", LINE_MAX),
                       "confidence": _choice(ev.get("confidence"), "import confidence",
                                             CONFIDENCES, "low")}
    candidates = []
    for c in value.get("candidates") or []:
        if not isinstance(c, dict) or not _HEX.match((c.get("hex") or "").strip()):
            raise KitError("import", "each candidate colour is {hex, why}")
        candidates.append({"hex": c["hex"].strip().upper(),
                           "why": _text(c.get("why"), "import reason", LINE_MAX)})
    if len(candidates) > IMPORT_CANDIDATES_MAX:
        raise KitError("import", f"an import keeps at most {IMPORT_CANDIDATES_MAX} candidates")
    return {"source": _text(value.get("source"), "import source", 300),
            "at": _text(value.get("at"), "import time", 40),
            "roles": roles, "candidates": candidates}


def clean_spec(raw: Any) -> dict:
    """The stored shape of a kit's spec, or KitError naming the field.
    Unknown keys are dropped; a value off its legal set is refused, never
    clamped (the conventions' "refuse, never clamp")."""
    raw = raw if isinstance(raw, dict) else {}

    ident = raw.get("identity") or {}
    identity = {"tagline": _text(ident.get("tagline"), "tagline", 120),
                "positioning": _text(ident.get("positioning"), "positioning", LINE_MAX),
                "audience": _text(ident.get("audience"), "audience", LINE_MAX),
                "url": _text(ident.get("url"), "url", 120),
                "selling_points": _lines(ident.get("selling_points"), "selling points",
                                         SELLING_POINTS_MAX, SELLING_POINT_MAX)}

    palette = []
    for i, swatch in enumerate(raw.get("palette") or []):
        if not isinstance(swatch, dict):
            raise KitError("palette", "each colour is {hex, role}")
        hexv = (swatch.get("hex") or "").strip()
        if not _HEX.match(hexv):
            raise KitError("palette", f"colour {i + 1} is not a #RRGGBB hex")
        palette.append({"hex": hexv.upper(),
                        "role": _choice(swatch.get("role"), "palette role",
                                        PALETTE_ROLES, "extra"),
                        "name": _text(swatch.get("name"), "colour name", 40)})
    if len(palette) > PALETTE_MAX:
        raise KitError("palette", f"a palette holds at most {PALETTE_MAX} colours")
    for role in PALETTE_ROLES[:-1]:
        if sum(1 for s in palette if s["role"] == role) > 1:
            raise KitError("palette", f"only one colour can be the {role}")

    cap = raw.get("captions") or {}
    captions = {"font": _choice(cap.get("font"), "caption font", CAPTION_FONTS, "heading"),
                "size": _number(cap.get("size"), "caption size", 0.025, 0.1, 0.05),
                "fill": _choice(cap.get("fill"), "caption colour", PALETTE_ROLES[:-1], "text"),
                "outline": _choice(cap.get("outline"), "caption outline",
                                   ("none",) + PALETTE_ROLES[:-1], "none"),
                "box": _choice(cap.get("box"), "caption box",
                               ("none",) + PALETTE_ROLES[:-1], "none"),
                "position": _choice(cap.get("position"), "caption position",
                                    CAPTION_POSITIONS, "bottom"),
                "uppercase": bool(cap.get("uppercase"))}

    motion_raw = raw.get("motion") or {}
    from .cut import doc as cut_doc
    motion = {"transition": _choice(motion_raw.get("transition"), "transition",
                                    tuple(cut_doc.TRANSITION_STYLES), "fade"),
              "seconds": _number(motion_raw.get("seconds"), "transition length", 0.2, 2.0, 0.6)}

    end = raw.get("end_card") or {}
    end_card = {"on": end.get("on", True) is not False,
                "seconds": _number(end.get("seconds"), "end card length", 1.0, 6.0, 2.5),
                "background": _choice(end.get("background"), "end card background",
                                      PALETTE_ROLES[:-1], "background"),
                "show_url": end.get("show_url", True) is not False}

    look_raw = raw.get("look") or {}
    look = {"style": _text(look_raw.get("style"), "style description", LOOK_STYLE_MAX),
            "banned": _words(look_raw.get("banned"), "banned elements"),
            "aesthetics": _aesthetics(look_raw.get("aesthetics"))}

    voice_raw = raw.get("voice") or {}
    voice = {"tone": _text(voice_raw.get("tone"), "tone", TONE_MAX),
             "use": _words(voice_raw.get("use"), "words to use"),
             "avoid": _words(voice_raw.get("avoid"), "words to avoid"),
             "cta": _text(voice_raw.get("cta"), "CTA style", CTA_MAX)}

    sound_raw = raw.get("sound") or {}
    music_raw = sound_raw.get("music") or {}
    bpm = _number(music_raw.get("bpm"), "BPM", 40, 220, None)
    sound = {"voice": _text(sound_raw.get("voice"), "default voice", LINE_MAX),
             "music": {"genre": _text(music_raw.get("genre"), "music genre", LIST_ITEM_MAX),
                       "bpm": int(bpm) if bpm is not None else None,
                       "mood": _text(music_raw.get("mood"), "music mood", LINE_MAX)},
             "loudness": _number(sound_raw.get("loudness"), "loudness target", -30, -6, None)}

    spec = {"v": SPEC_VERSION, "identity": identity, "palette": palette,
            "captions": captions,
            "safe_zone": _number(raw.get("safe_zone"), "safe zone", 0, 0.2, 0.06),
            "aspect": _choice(raw.get("aspect"), "default aspect", ASPECTS, ""),
            "motion": motion, "end_card": end_card, "look": look, "voice": voice,
            "sound": sound,
            "products": _links(raw.get("products"), "products", ("prop",), PRODUCTS_MAX, True),
            "never_claim": _words(raw.get("never_claim"), "claims never to make"),
            "characters": _links(raw.get("characters"), "characters", ("character",),
                                 CHARACTERS_MAX, False)}
    evidence = _import(raw.get("import"))
    if evidence:
        spec["import"] = evidence
    return spec


def clean_name(name) -> str:
    name = " ".join(str(name or "").split())
    if not name:
        raise KitError("name", "a brand kit needs a name")
    if len(name) > NAME_MAX:
        raise KitError("name", f"the name is at most {NAME_MAX} characters")
    return name


