"""What a person DID with an output (2026-10-11; step 4 of
docs/tasks/task-higgsfield-shape.md).

The eval layer used to sit on the idea: a card was picked or passed on a
board, and a rubric scored the prompt before anything was made. Both
measured a guess. The unit here is a GENERATION -- one row of
`generated_assets` (`gen:<id>`) and its attempt row in `generations` --
and the signal is what the person does with it afterwards, collected
without asking them to grade anything:

    kept       cut_add   it went onto a timeline
               export    a cut containing it was exported
               element_from   it became an element's photo
               ref_reuse it was used as a reference or as an effect's source
               continued a continue action made something from it
               download  it was downloaded
               star      it was starred on the wall
               post      a posted video was linked to it
    discarded  delete    it was taken off the wall
               regen     the same scene part, or the same prompt, was made
                         again within ten minutes with this one never kept
    edited     prompt_edit   it was made from a prompt the person had edited

`record()` is the one writer and it NEVER RAISES (the `spend.record_call`
shape): the bookkeeping must not cost the click it is recording. It only
ever writes about an output the caller's own account owns -- an id that is
somebody else's, or nobody's, records nothing.

`generations.kept` is DERIVED from here on: any kept event sets it, so the
readers that always read it (`generative.tool_scoreboard`,
`costs.render_costs`) start to mean something. Nothing un-sets it; an
event is a thing that happened.

`note_new()` is called once for every new output (`render_assets.record`)
and is where the two events that are about a PAIR of outputs are found:
`regen` on the earlier one, and `prompt_edit` on the new one.

The second half of the module is the reading: keep rate by model, by the
brain that wrote the scene and by writer template; attempts before a
keeper; credits per kept output; the discard mix. Per account, by week,
never averaged across accounts.

`src/` never imports `app/`: the routes call in.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import datetime, timedelta, timezone
from statistics import median
from typing import Any, Iterable, Optional

from . import db

KEPT = ("cut_add", "export", "element_from", "ref_reuse", "continued",
        "download", "star", "post")
DISCARDED = ("delete", "regen")
EDITED = ("prompt_edit",)
EVENTS = KEPT + DISCARDED + EDITED

# "made again" counts as a discard of the earlier one only this soon after
REGEN_WINDOW_S = 600
# how many weeks the Stats tab shows
WEEKS = 8

SCHEMA = """
CREATE TABLE IF NOT EXISTS output_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            TEXT   NOT NULL,
    account_id    BIGINT,
    generation_id BIGINT,
    asset_id      BIGINT,
    event         TEXT   NOT NULL,
    -- which door it came through (library, composer, editor, effect, mcp,
    -- backfill); for prompt_edit, the edited pair's own name
    source        TEXT,
    meta          TEXT
);

CREATE INDEX IF NOT EXISTS idx_output_events_asset   ON output_events (asset_id, event);
CREATE INDEX IF NOT EXISTS idx_output_events_account ON output_events (account_id, at);
"""

_GEN_REF = re.compile(r"^gen:(\d+)$")


def init(dsn: Optional[str] = None) -> None:
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        db.own_table(conn, "output_events")


def _note(what: str, exc: Exception) -> None:
    print(f"note: outcome {what} skipped ({type(exc).__name__}: {exc})", file=sys.stderr)


def _meta(row: dict) -> dict:
    try:
        return json.loads(row.get("metadata_json") or "{}") or {}
    except (TypeError, ValueError):
        return {}


def _asset(conn, account_id: Optional[int], *, asset_id: Optional[int] = None,
           generation_id: Optional[int] = None) -> Optional[dict]:
    """This account's output, by either of its two ids, or None."""
    if asset_id is None and generation_id is None:
        return None
    if asset_id is not None:
        row = conn.execute(
            "SELECT * FROM generated_assets WHERE id = %s "
            "AND account_id IS NOT DISTINCT FROM %s", (asset_id, account_id)).fetchone()
    else:
        row = conn.execute(
            "SELECT * FROM generated_assets WHERE generation_id = %s "
            "AND account_id IS NOT DISTINCT FROM %s", (generation_id, account_id)).fetchone()
    return dict(row) if row else None


def _ready(conn) -> bool:
    return db.table_exists(conn, "output_events") and db.table_exists(conn, "generated_assets")


# --------------------------------------------------------------------------
# the writer
# --------------------------------------------------------------------------

def record(event: str, *, account_id: Optional[int], asset_id: Optional[int] = None,
           generation_id: Optional[int] = None, source: str = "",
           meta: Optional[dict] = None, at: Optional[str] = None,
           teach: bool = True, dsn: Optional[str] = None) -> Optional[int]:
    """One thing that happened to one output. Returns the event's id, or
    None when nothing was written: an unknown event, an output that is not
    this account's, a database that has no table yet, any error at all.
    Never raises.

    `teach=False` writes the event (and `kept`) and nothing else: no edit
    pair is ingested or withdrawn and no keeper's prompt is filed. It is
    for history being written down after the fact
    (ops/backfill_output_events.py) -- teaching embeds a prompt, which is
    a model call, and a backfill must not make one or put lessons on the
    shared shelf as a side effect of counting."""
    try:
        if event not in EVENTS:
            raise ValueError(f"unknown outcome event {event!r}")
        with db.connect(dsn) as conn:
            if not _ready(conn):
                return None
            row = _asset(conn, account_id, asset_id=asset_id, generation_id=generation_id)
            if row is None:
                return None
            new = conn.execute(
                "INSERT INTO output_events (at, account_id, generation_id, asset_id, event, "
                "source, meta) VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING id",
                (at or db._now(), account_id, row.get("generation_id"), row["id"], event,
                 (source or "")[:120] or None,
                 json.dumps(meta, sort_keys=True) if meta else None)).fetchone()["id"]
            if event in KEPT and row.get("generation_id") and db.table_exists(conn, "generations"):
                # derived: any kept event sets it (see the module docstring)
                conn.execute(
                    "UPDATE generations SET kept = 1 WHERE id = %s AND kept = 0 "
                    "AND account_id IS NOT DISTINCT FROM %s",
                    (row["generation_id"], account_id))
    except Exception as exc:                                    # noqa: BLE001
        _note(f"event {event!r}", exc)
        return None
    if teach:
        # the pair first: an edit that is taught here is this output's
        # lesson, and the keeper below then finds it already filed
        _settle_edit_pair(event, row["id"], account_id, dsn)
        if event in KEPT:
            _teach_keeper(row, account_id, dsn)
    return int(new)


def asset_of(ref: Any) -> Optional[int]:
    """`"gen:12"` -> 12. Anything else -> None."""
    m = _GEN_REF.match(str(ref or "").strip())
    return int(m.group(1)) if m else None


def asset_for_url(url: str, *, account_id: Optional[int],
                  dsn: Optional[str] = None) -> Optional[int]:
    """The output a media URL is, or None: a client holds minted URLs
    (signed, public or a local route), so the match is on the object's own
    tail (`renders/<provider>/<file>`), never on the string."""
    try:
        from . import media
        tail = media.tail_for(str(url or "").split("?")[0])
        if not tail or not tail.startswith(("renders/", "images/", "clips/")):
            return None
        name = tail.rsplit("/", 1)[-1]
        with db.connect(dsn) as conn:
            if not db.table_exists(conn, "generated_assets"):
                return None
            rows = conn.execute(
                "SELECT id, media_url FROM generated_assets WHERE media_url LIKE %s "
                "AND account_id IS NOT DISTINCT FROM %s ORDER BY id DESC",
                ("%" + name.replace("%", r"\%").replace("_", r"\_"), account_id)).fetchall()
        for r in rows:
            if media.tail_for(str(r["media_url"]).split("?")[0]) == tail:
                return int(r["id"])
    except Exception as exc:                                    # noqa: BLE001
        _note("url lookup", exc)
    return None


def record_ref(event: str, ref: Any, *, account_id: Optional[int], source: str = "",
               meta: Optional[dict] = None, dsn: Optional[str] = None) -> Optional[int]:
    """`record` for whatever names the output: `gen:<id>`, or a media URL.
    A reference that is not one of this account's outputs -- an upload, an
    element's photo, somebody's frame -- records nothing, which is right:
    the event is about outputs."""
    asset = asset_of(ref)
    if asset is None:
        asset = asset_for_url(str(ref or ""), account_id=account_id, dsn=dsn)
    if asset is None:
        return None
    return record(event, asset_id=asset, account_id=account_id, source=source,
                  meta=meta, dsn=dsn)


def record_refs(event: str, refs: Iterable[Any], *, account_id: Optional[int],
                source: str = "", dsn: Optional[str] = None) -> int:
    """`record_ref` over a list, each output once. Returns how many."""
    seen, n = set(), 0
    for ref in refs or []:
        key = str(ref)
        if key in seen:
            continue
        seen.add(key)
        if record_ref(event, ref, account_id=account_id, source=source, dsn=dsn):
            n += 1
    return n


def record_handles(event: str, handles: Iterable[Any], *, account_id: Optional[int],
                   source: str = "", meta: Optional[dict] = None,
                   skip: Iterable[Any] = (), dsn: Optional[str] = None) -> int:
    """`record` for every OUTPUT among a cut's media handles (`gen:<id>`;
    an upload is `asset:<id>` and is not an output), leaving out the ones
    in `skip`. Returns how many were written. Never raises."""
    n = 0
    try:
        left_out = {str(h) for h in skip}
        for handle in dict.fromkeys(str(h) for h in handles or []):
            asset = asset_of(handle)
            if asset is None or handle in left_out:
                continue
            if record(event, asset_id=asset, account_id=account_id, source=source,
                      meta=meta, dsn=dsn):
                n += 1
    except Exception as exc:                                    # noqa: BLE001
        _note(f"handles {event!r}", exc)
    return n


def withdraw(event: str, *, asset_id: int, account_id: Optional[int],
             dsn: Optional[str] = None) -> bool:
    """Take back the newest `event` on this output: the studio's Undo. A
    delete that was undone was a slip of the hand, not a verdict. Never
    raises."""
    try:
        with db.connect(dsn) as conn:
            if not _ready(conn):
                return False
            cur = conn.execute(
                "DELETE FROM output_events WHERE id = (SELECT MAX(id) FROM output_events "
                "WHERE asset_id = %s AND event = %s AND account_id IS NOT DISTINCT FROM %s) "
                "AND account_id IS NOT DISTINCT FROM %s",
                (asset_id, event, account_id, account_id))
            return bool(cur.rowcount)
    except Exception as exc:                                    # noqa: BLE001
        _note(f"withdraw {event!r}", exc)
        return False


def events_for(asset_ids: Iterable[int], *, account_id: Optional[int],
               dsn: Optional[str] = None) -> dict[int, list[dict]]:
    """{asset id: its events, oldest first}. Reads only; raises like any
    reader."""
    ids = sorted({int(i) for i in asset_ids})
    out: dict[int, list[dict]] = {i: [] for i in ids}
    if not ids:
        return out
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "output_events"):
            return out
        for r in conn.execute(
                "SELECT * FROM output_events WHERE asset_id = ANY(%s) "
                "AND account_id IS NOT DISTINCT FROM %s ORDER BY id", (ids, account_id)):
            out[int(r["asset_id"])].append(dict(r))
    return out


# --------------------------------------------------------------------------
# a new output: regen on the one before it, prompt_edit on this one
# --------------------------------------------------------------------------

def _prompt_key(text: Optional[str]) -> str:
    return hashlib.sha256(" ".join(str(text or "").lower().split()).encode()).hexdigest()[:16]


def _slot(row: dict, meta: dict) -> Optional[tuple]:
    """The scene part an output was made for, or None when it was made
    for no scene: (concept, shot, part)."""
    concept = row.get("concept_id") or meta.get("concept_id")
    if not concept:
        return None
    shot = row.get("shot_n") or meta.get("shot_n") or 1
    return (int(concept), int(shot), meta.get("part") or meta.get("beat"))


def pair_ref(concept_id: int, shot_n: Optional[int]) -> str:
    """The name an edit-teach pair is filed under (app.api._teach_prompt_edit)."""
    return f"concept-{int(concept_id)}-shot-{int(shot_n or 1)}"


def note_new(asset_id: int, *, account_id: Optional[int],
             dsn: Optional[str] = None) -> dict[str, Any]:
    """Called once when an output is recorded. Never raises.

    REGEN: an earlier output of this account's, of the same kind, made in
    the last ten minutes for the same scene part -- or from the same
    prompt and the same sources -- that has no kept event and is not
    already discarded, was passed over by making this one. The new output
    is never a regen of something it was MADE FROM (an effect on a clip,
    a finish of a draft).

    PROMPT_EDIT: the new output is on a shot whose prompt the person
    edited and whose pair is still waiting; the event links the two so a
    kept output teaches the edit and a discarded one withdraws it."""
    out: dict[str, Any] = {"regen": [], "prompt_edit": None}
    try:
        with db.connect(dsn) as conn:
            if not _ready(conn):
                return out
            new = _asset(conn, account_id, asset_id=asset_id)
            if new is None:
                return out
            meta = _meta(new)
            made_from = {asset_of(s) for s in (meta.get("sources") or [])} - {None}
            since = (datetime.now(timezone.utc) - timedelta(seconds=REGEN_WINDOW_S)
                     ).isoformat(timespec="seconds")
            earlier = [dict(r) for r in conn.execute(
                "SELECT * FROM generated_assets WHERE id < %s AND media_kind = %s "
                "AND deleted_at IS NULL AND created_at >= %s "
                "AND account_id IS NOT DISTINCT FROM %s ORDER BY id DESC LIMIT 40",
                (new["id"], new["media_kind"], since, account_id))]
            slot, key = _slot(new, meta), _prompt_key(new.get("prompt"))
            same = []
            for old in earlier:
                if old["id"] in made_from:
                    continue
                old_meta = _meta(old)
                if slot is not None and _slot(old, old_meta) == slot:
                    same.append((old["id"], "part"))
                elif (old.get("model") == new.get("model")
                      and _prompt_key(old.get("prompt")) == key
                      and (old_meta.get("sources") or []) == (meta.get("sources") or [])
                      and (slot is None or _slot(old, old_meta) is None)):
                    same.append((old["id"], "prompt"))
            settled = set()
            if same:
                for r in conn.execute(
                        "SELECT asset_id, event FROM output_events WHERE asset_id = ANY(%s) "
                        "AND account_id IS NOT DISTINCT FROM %s",
                        ([i for i, _ in same], account_id)):
                    if r["event"] in KEPT or r["event"] in DISCARDED:
                        settled.add(int(r["asset_id"]))
            pending_pair = None
            if slot is not None and db.table_exists(conn, "winning_prompts"):
                ref = pair_ref(slot[0], slot[1])
                if conn.execute("SELECT 1 FROM winning_prompts WHERE video_ref = %s "
                                "AND ingested = 0 LIMIT 1", (ref,)).fetchone():
                    pending_pair = ref
    except Exception as exc:                                    # noqa: BLE001
        _note("new output", exc)
        return out
    # the link FIRST: a regen below asks whether every output made from the
    # edit is gone, and this one is not
    if pending_pair:
        if record("prompt_edit", asset_id=new["id"], account_id=account_id,
                  source=pending_pair, dsn=dsn):
            out["prompt_edit"] = pending_pair
    for old_id, why in same:
        if old_id in settled:
            continue
        if record("regen", asset_id=old_id, account_id=account_id, source="auto",
                  meta={"by": new["id"], "match": why}, dsn=dsn):
            out["regen"].append(old_id)
    return out


def _settle_edit_pair(event: str, asset_id: int, account_id: Optional[int],
                      dsn: Optional[str]) -> None:
    """The Teach tab's job, done by the outcome (step 5): an edited pair is
    taught when an output made from the edit is KEPT, and withdrawn when
    every output made from it has been discarded. Never raises."""
    if event not in KEPT and event not in DISCARDED:
        return
    try:
        with db.connect(dsn) as conn:
            if not db.table_exists(conn, "winning_prompts"):
                return
            refs = [r["source"] for r in conn.execute(
                "SELECT DISTINCT source FROM output_events WHERE asset_id = %s "
                "AND event = 'prompt_edit' AND account_id IS NOT DISTINCT FROM %s",
                (asset_id, account_id)) if r["source"]]
            live: dict[str, bool] = {}
            for ref in refs:
                if not conn.execute("SELECT 1 FROM winning_prompts WHERE video_ref = %s "
                                    "AND ingested = 0 LIMIT 1", (ref,)).fetchone():
                    continue                # already taught, or withdrawn by hand
                linked = [int(r["asset_id"]) for r in conn.execute(
                    "SELECT DISTINCT asset_id FROM output_events WHERE event = 'prompt_edit' "
                    "AND source = %s AND account_id IS NOT DISTINCT FROM %s",
                    (ref, account_id))]
                gone = {int(r["asset_id"]) for r in conn.execute(
                    "SELECT DISTINCT asset_id FROM output_events WHERE asset_id = ANY(%s) "
                    "AND event = ANY(%s) AND account_id IS NOT DISTINCT FROM %s",
                    (linked, list(DISCARDED), account_id))}
                live[ref] = any(i not in gone for i in linked)
        if not live:
            return
        from . import accounts, winners
        for ref, still_live in live.items():
            if event in KEPT:
                winners.ingest_pending(ref, dsn=dsn, project=accounts.slug_of(account_id, dsn=dsn))
            elif not still_live:
                winners.discard_pending(ref, dsn=dsn)
    except Exception as exc:                                    # noqa: BLE001
        _note("edit pair", exc)


# the note a keeper's prompt is filed under on the winning shelf
KEEPER_NOTE = "kept output"


def _teach_keeper(asset: dict, account_id: Optional[int], dsn: Optional[str]) -> None:
    """Few-shot from the person's own keepers (step 7 item 4): the prompt
    behind a KEPT output goes onto the `winning_prompts` shelf the scene
    writer already retrieves from, labelled with the account that taught
    it (so that account's own keepers rank first) and with the model it
    was made on. Never raises.

    ONLY FOR AN ACCOUNT THAT TEACHES. The shelf is shared, and whose
    prompts reach it was decided on 2026-09-18 ("only for my account
    specifically, not for other users"): `edit_teach.allowed` is that
    decision's one gate, and it is asked here. Everyone else's kept
    outputs are counted on Stats and taught nowhere.

    What is filed is the SCENE's prompt when the output belongs to one
    (under the scene shot's own name, where an edit pair or an older
    verdict would be -- so a shot that already carries a winning lesson is
    not filed twice), else the output's own prompt under `gen:<id>`.
    Never an effect's or a join's: those were not written."""
    try:
        from . import accounts, edit_teach, winners
        if not edit_teach.allowed(account_id, dsn):
            return
        meta = _meta(asset)
        if asset.get("tool") == "cut" or meta.get("sources") or meta.get("finish_of"):
            return
        prompt = asset.get("prompt")
        tool = asset.get("model") or asset.get("tool")
        ref = f"gen:{int(asset['id'])}"
        slot = _slot(asset, meta)
        if slot is not None:
            ref = pair_ref(slot[0], slot[1])
            with db.connect(dsn) as conn:
                if db.table_exists(conn, "shoot_concepts"):
                    scene = conn.execute(
                        "SELECT shots_json FROM shoot_concepts WHERE id = %s "
                        "AND account_id IS NOT DISTINCT FROM %s", (slot[0], account_id)).fetchone()
                    for shot in (json.loads(scene["shots_json"] or "[]") if scene else []):
                        if (shot.get("n") or 1) == slot[1] and (shot.get("prompt") or "").strip():
                            prompt = shot["prompt"]
        if not (prompt or "").strip():
            return
        if any(r.get("verdict") == "worked" for r in winners.recorded(ref, dsn=dsn)):
            return
        winners.record_and_learn(tool, prompt, note=KEEPER_NOTE, video_ref=ref, verdict="worked",
                                 dsn=dsn, project=accounts.slug_of(account_id, dsn=dsn))
    except Exception as exc:                                    # noqa: BLE001
        _note("keeper", exc)


# --------------------------------------------------------------------------
# the reading (step 5): per account, by week
# --------------------------------------------------------------------------

def _week(stamp: Optional[str]) -> str:
    """The Monday of the week a timestamp falls in, as YYYY-MM-DD."""
    try:
        day = datetime.fromisoformat(str(stamp).replace("Z", "+00:00")).date()
    except (TypeError, ValueError):
        return "unknown"
    return (day - timedelta(days=day.weekday())).isoformat()


def _outputs(account_id: Optional[int], dsn: Optional[str]) -> list[dict]:
    """Every output of this account's (deleted ones too: a deleted output
    was still made), each with `kept`, `discarded` (the set of discard
    events on it), its week, the brain and the writer template behind its
    scene, and what its generation cost."""
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "generated_assets"):
            return []
        rows = [dict(r) for r in conn.execute(
            "SELECT * FROM generated_assets WHERE account_id IS NOT DISTINCT FROM %s "
            "ORDER BY id", (account_id,))]
        events: dict[int, set] = {}
        if db.table_exists(conn, "output_events"):
            for r in conn.execute(
                    "SELECT asset_id, event FROM output_events "
                    "WHERE account_id IS NOT DISTINCT FROM %s", (account_id,)):
                events.setdefault(int(r["asset_id"]), set()).add(r["event"])
        costs: dict[int, Optional[float]] = {}
        if db.table_exists(conn, "generations"):
            for r in conn.execute(
                    "SELECT id, cost_usd FROM generations "
                    "WHERE account_id IS NOT DISTINCT FROM %s", (account_id,)):
                costs[int(r["id"])] = r["cost_usd"]
        scenes: dict[int, dict] = {}
        if db.table_exists(conn, "shoot_concepts"):
            for r in conn.execute(
                    "SELECT id, prompt_hash, shots_json FROM shoot_concepts "
                    "WHERE account_id IS NOT DISTINCT FROM %s", (account_id,)):
                brain = preset = None
                try:
                    shots = json.loads(r["shots_json"] or "[]") or [{}]
                    brain = ((shots[0] or {}).get("timeline") or {}).get("brain")
                    preset = (shots[0] or {}).get("preset")
                except (TypeError, ValueError, AttributeError, IndexError):
                    pass
                scenes[int(r["id"])] = {"template": r["prompt_hash"], "brain": brain,
                                        "preset": preset}
    out = []
    for row in rows:
        meta = _meta(row)
        seen = events.get(int(row["id"]), set())
        concept = row.get("concept_id") or meta.get("concept_id")
        # two different blanks: made for no scene, or for a scene that does
        # not say (one window has no timeline; a hand-written row no template)
        scene = scenes.get(int(concept)) if concept else None
        blank = "no scene" if scene is None else "not recorded"
        scene = scene or {}
        out.append({
            "id": int(row["id"]), "week": _week(row.get("created_at")),
            "model": row.get("model") or row.get("tool") or "unknown",
            "tool": row.get("tool"), "media_kind": row.get("media_kind"),
            "brain": scene.get("brain") or blank,
            "template": scene.get("template") or blank,
            "preset": scene.get("preset"),
            # which per-model prompt rule shaped it (src/prompts_for.py)
            "rule": meta.get("prompt_rule") or "as written",
            "kept": bool(seen & set(KEPT)),
            "discarded": seen & set(DISCARDED),
            "slot": _slot(row, meta), "prompt_key": _prompt_key(row.get("prompt")),
            "cost_usd": costs.get(int(row["generation_id"])) if row.get("generation_id") else None,
        })
    return out


def _recent_weeks(outputs: list[dict], weeks: int) -> list[str]:
    seen = sorted({o["week"] for o in outputs if o["week"] != "unknown"}, reverse=True)
    return seen[:weeks]


def keep_rates(outputs: list[dict], by: str, weeks: int = WEEKS) -> list[dict]:
    """[{week, key, made, kept, rate}], newest week first, the busiest key
    first inside a week. `by` is model | brain | template."""
    keep = _recent_weeks(outputs, weeks)
    cells: dict[tuple, list[int]] = {}
    for o in outputs:
        if o["week"] not in keep:
            continue
        cell = cells.setdefault((o["week"], str(o[by])), [0, 0])
        cell[0] += 1
        cell[1] += 1 if o["kept"] else 0
    rows = [{"week": w, "key": k, "made": made, "kept": kept,
             "rate": round(kept / made, 3) if made else None}
            for (w, k), (made, kept) in cells.items()]
    rows.sort(key=lambda r: (r["week"], r["made"]), reverse=True)
    return rows


def attempts_before_keeper(outputs: list[dict]) -> dict[str, Any]:
    """How many tries a thing took before one was kept. A "thing" is a
    scene part (concept, shot, part, kind), or -- for an output made for no
    scene -- one prompt on one model. Only things that HAVE a keeper are
    averaged; the ones still without one are counted beside them."""
    groups: dict[tuple, list[dict]] = {}
    for o in outputs:
        key = ((o["slot"], o["media_kind"]) if o["slot"] is not None
               else (o["prompt_key"], o["model"], o["media_kind"]))
        groups.setdefault(key, []).append(o)
    tries, waiting = [], 0
    for members in groups.values():
        members.sort(key=lambda o: o["id"])
        first = next((i for i, o in enumerate(members) if o["kept"]), None)
        if first is None:
            waiting += 1
        else:
            tries.append(first + 1)
    return {"things": len(tries), "average": round(sum(tries) / len(tries), 2) if tries else None,
            "median": median(tries) if tries else None,
            "first_try": sum(1 for t in tries if t == 1), "no_keeper_yet": waiting}


def credits_per_kept(outputs: list[dict], weeks: int = WEEKS) -> list[dict]:
    """[{week, credits, made, kept, per_kept}]: what every output made that
    week cost, in credits, over how many of them were kept. The credits are
    `ledger.charge_credits` of each generation's recorded cost -- the one
    number a hold charges -- so an exempt account reads what it WOULD have
    been charged. An output with no recorded cost (a manual import, a free
    join) adds nothing."""
    from . import ledger
    keep = _recent_weeks(outputs, weeks)
    cells: dict[str, list[int]] = {w: [0, 0, 0] for w in keep}
    for o in outputs:
        if o["week"] not in cells:
            continue
        cell = cells[o["week"]]
        cell[1] += 1
        cell[2] += 1 if o["kept"] else 0
        if o["cost_usd"]:
            try:
                cell[0] += int(ledger.charge_credits(o["cost_usd"]))
            except Exception:                                   # noqa: BLE001
                pass
    return [{"week": w, "credits": c, "made": made, "kept": kept,
             "per_kept": round(c / kept) if kept else None}
            for w, (c, made, kept) in sorted(cells.items(), reverse=True)]


def discard_mix(outputs: list[dict], weeks: int = WEEKS) -> list[dict]:
    """[{week, made, deleted, regenerated}] -- each output once per kind."""
    keep = _recent_weeks(outputs, weeks)
    cells: dict[str, list[int]] = {w: [0, 0, 0] for w in keep}
    for o in outputs:
        if o["week"] not in cells:
            continue
        cell = cells[o["week"]]
        cell[0] += 1
        cell[1] += 1 if "delete" in o["discarded"] else 0
        cell[2] += 1 if "regen" in o["discarded"] else 0
    return [{"week": w, "made": made, "deleted": deleted, "regenerated": regen}
            for w, (made, deleted, regen) in sorted(cells.items(), reverse=True)]


def preset_counts(*, account_id: Optional[int],
                  dsn: Optional[str] = None) -> dict[str, dict[str, int]]:
    """{preset id: {"tried", "kept"}} for this account: the outputs made on
    a scene written with that camera preset, and how many of them were
    kept. A preset nobody has used is absent. Never raises -- a count that
    cannot be read is an empty answer, and the menu says "untested"."""
    try:
        counts: dict[str, dict[str, int]] = {}
        for o in _outputs(account_id, dsn):
            if not o.get("preset"):
                continue
            cell = counts.setdefault(str(o["preset"]), {"tried": 0, "kept": 0})
            cell["tried"] += 1
            cell["kept"] += 1 if o["kept"] else 0
        return counts
    except Exception as exc:                                    # noqa: BLE001
        _note("preset counts", exc)
        return {}


# What the Create brain is shown of this (2026-10-16, Vesper review): the
# person's own keep rate per model over the recent weeks, so a proposal can
# lean on what they actually keep. Too few outputs says nothing.
TASTE_MIN_MADE = 3
TASTE_MODELS = 5
TASTE_NOTE = ("What this person did with their recent outputs, per model: kept means "
              "they cut, exported, downloaded, starred, posted, reused or continued it. "
              "Lean toward what they keep when you propose a model, and say so in a few "
              "words; never insist, and the price is still the card's.")


def taste(*, account_id: Optional[int], weeks: int = WEEKS,
          dsn: Optional[str] = None) -> Optional[dict[str, Any]]:
    """{note, made, kept, by_model: [{model, kind, made, kept}]} for ONE
    account's outputs in its last `weeks` busy weeks, the busiest models
    first, or None when there is too little to say (or no account). Never
    raises: a database that cannot answer is None."""
    if account_id is None:
        return None
    try:
        outputs = _outputs(account_id, dsn)
    except Exception as exc:                                    # noqa: BLE001
        _note("taste", exc)
        return None
    recent = set(_recent_weeks(outputs, weeks))
    outputs = [o for o in outputs if o["week"] in recent]
    if len(outputs) < TASTE_MIN_MADE:
        return None
    cells: dict[tuple, list[int]] = {}
    for o in outputs:
        cell = cells.setdefault((str(o["model"]), str(o["media_kind"] or "")), [0, 0])
        cell[0] += 1
        cell[1] += 1 if o["kept"] else 0
    rows = sorted(cells.items(), key=lambda kv: (-kv[1][0], -kv[1][1], kv[0]))
    return {
        "note": TASTE_NOTE,
        "made": len(outputs), "kept": sum(1 for o in outputs if o["kept"]),
        "by_model": [{"model": model, "kind": kind or None, "made": made, "kept": kept}
                     for (model, kind), (made, kept) in rows[:TASTE_MODELS]],
    }


def summary(*, account_id: Optional[int], weeks: int = WEEKS,
            dsn: Optional[str] = None) -> dict[str, Any]:
    """Everything the Dev Studio's Stats tab shows about outputs, for ONE
    account. Never raises: a database that cannot answer reads as nothing
    made, with the reason."""
    try:
        outputs = _outputs(account_id, dsn)
    except Exception as exc:                                    # noqa: BLE001
        _note("summary", exc)
        return {"made": 0, "kept": 0, "rate": None, "by_model": [], "by_brain": [],
                "by_template": [], "by_rule": [], "attempts": attempts_before_keeper([]),
                "credits": [], "discards": [], "error": f"{type(exc).__name__}: {exc}"}
    made, kept = len(outputs), sum(1 for o in outputs if o["kept"])
    return {
        "made": made, "kept": kept, "rate": round(kept / made, 3) if made else None,
        "by_model": keep_rates(outputs, "model", weeks),
        "by_brain": keep_rates(outputs, "brain", weeks),
        "by_template": keep_rates(outputs, "template", weeks),
        "by_rule": keep_rates(outputs, "rule", weeks),
        "attempts": attempts_before_keeper(outputs),
        "credits": credits_per_kept(outputs, weeks),
        "discards": discard_mix(outputs, weeks),
        "error": None,
    }
