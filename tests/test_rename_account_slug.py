"""The account slug rename (ops/rename_account_slug.py, step 8 of
docs/tasks/task-remove-brand-labels.md): report first, refuse what it does
not understand, back up, rename in one transaction."""
import json

import pytest

from ops import rename_account_slug as rename
from src import accounts, db

OLD, NEW = "old-slug", "new-slug"


@pytest.fixture
def live_shape(pg):
    accounts.init(pg)
    accounts.upsert_account(OLD, "Old Films", dsn=pg)
    accounts.upsert_account("someone", "Someone", dsn=pg)
    with db.connect(pg) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS rag_documents (id BIGINT GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY, project TEXT);
            CREATE TABLE IF NOT EXISTS workflows_leftover (id BIGINT PRIMARY KEY, brand TEXT);
        """)
        conn.execute("INSERT INTO rag_documents (project) VALUES (%s), (%s), ('someone')",
                     (OLD, OLD))
    return pg


def _slugs(dsn):
    with db.connect(dsn) as conn:
        return sorted(r["slug"] for r in conn.execute("SELECT slug FROM accounts").fetchall())


def test_the_report_counts_every_copy_and_changes_nothing(live_shape):
    plan = rename.scan(live_shape, OLD, NEW, "New")
    assert plan["account"]["slug"] == OLD and plan["new_slug_taken"] is False
    assert plan["renames"] == {"rag_documents.project": 2, "accounts.slug": 1}
    assert plan["unknown"] == {}
    assert rename.refusal(plan) == ""
    assert OLD in _slugs(live_shape)


def test_a_copy_nobody_decided_about_refuses_the_write(live_shape):
    with db.connect(live_shape) as conn:
        conn.execute("INSERT INTO workflows_leftover VALUES (1, %s)", (OLD,))
    plan = rename.scan(live_shape, OLD, NEW)
    assert plan["unknown"] == {"workflows_leftover.brand": 1}
    assert "decide them first" in rename.refusal(plan)
    with pytest.raises(RuntimeError, match="decide them first"):
        rename.rename(live_shape, plan)
    assert OLD in _slugs(live_shape)


def test_a_taken_slug_or_a_missing_account_refuses(live_shape):
    assert "already taken" in rename.refusal(rename.scan(live_shape, OLD, "someone"))
    assert "no account" in rename.refusal(rename.scan(live_shape, "nobody", NEW))


def test_backup_then_rename_moves_both_and_is_rerunnable(live_shape, tmp_path):
    plan = rename.scan(live_shape, OLD, NEW, "New")
    written = rename.backup(live_shape, plan, tmp_path)
    assert written == {"rag_documents.project": 2, "accounts.slug": 1,
                       "accounts.display_name": 1}
    assert json.loads((tmp_path / "accounts.display_name.json").read_text())[0][
        "display_name"] == "Old Films"
    assert rename.rename(live_shape, plan) == {"rag_documents.project": 2, "accounts.slug": 1}
    assert _slugs(live_shape) == sorted([NEW, "someone"])
    with db.connect(live_shape) as conn:
        assert conn.execute("SELECT display_name FROM accounts WHERE slug = %s",
                            (NEW,)).fetchone()["display_name"] == "New"
        projects = sorted(r["project"] for r in conn.execute(
            "SELECT project FROM rag_documents").fetchall())
    assert projects == sorted([NEW, NEW, "someone"])
    again = rename.scan(live_shape, OLD, NEW)
    assert again["account"] is None and "no account" in rename.refusal(again)


def test_a_count_that_moved_since_the_report_rolls_back(live_shape):
    plan = rename.scan(live_shape, OLD, NEW)
    with db.connect(live_shape) as conn:
        conn.execute("INSERT INTO rag_documents (project) VALUES (%s)", (OLD,))
    with pytest.raises(RuntimeError, match="rolled back"):
        rename.rename(live_shape, plan)
    assert OLD in _slugs(live_shape)


def test_the_command_needs_a_backup_to_write(live_shape, capsys):
    assert rename.main(["--from", OLD, "--to", NEW, "--dsn", live_shape, "--write"]) == 2
    assert rename.main(["--from", OLD, "--to", NEW, "--dsn", live_shape]) == 0
    assert "report only" in capsys.readouterr().out
    assert OLD in _slugs(live_shape)
